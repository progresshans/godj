func TestPostgresDecimalNativeParametersCatalogAndDriver(t *testing.T) {
	for _, raw := range []string{"0", "-0", "1.23", "123456789012345678.123456789012", "999999999999999999.999999999999"} {
		number, err := decimal.Parse(raw)
		if err != nil {
			t.Fatal(err)
		}
		value, err := postgresValue(query.Decimal(number))
		if err != nil {
			t.Fatal(err)
		}
		numeric, ok := value.(pgtype.Numeric)
		if !ok || !numeric.Valid || numeric.NaN || numeric.InfinityModifier != pgtype.Finite || numeric.Int == nil {
			t.Fatal("invalid native numeric parameter")
		}
		got, err := decimal.New(numeric.Int.String(), numeric.Exp)
		if err != nil || !got.Equal(number) {
			t.Fatal("numeric parameter lost precision")
		}
		scanner := orm.NewNullableDecimalScanner(30, 12)
		if err := (decimalDestination{destination: &scanner}).Scan(raw); err != nil || !scanner.Valid || !scanner.Decimal.Equal(number) {
			t.Fatal("numeric driver text lost exact value")
		}
	}
	for _, raw := range []any{"NaN", "Infinity", "-Infinity", "1.001", "1000", float64(1.5), int64(1), []byte("bad")} {
		scanner := orm.NewNullableDecimalScanner(5, 2)
		scanner.Decimal = decimal.Decimal{Coefficient: "1"}
		scanner.Valid = true
		if err := (decimalDestination{destination: &scanner}).Scan(raw); err == nil || scanner.Valid || scanner.Decimal != (decimal.Decimal{}) {
			t.Fatalf("invalid driver value %v retained scanner state", raw)
		}
	}
	field := ir.Field{Name: "cost", GoName: "Cost", Column: "cost", Kind: ir.FieldDecimal, Nullable: true, Decimal: &ir.DecimalSpec{MaxDigits: 30, DecimalPlaces: 12}}
	ddl, err := compilePostgresMigrationColumn(field)
	if err != nil || ddl != `"cost" NUMERIC(30,12) NULL` {
		t.Fatalf("numeric DDL: %s %v", ddl, err)
	}
	column := postgresMigrationColumnCatalog{attributeNumber: 1, name: "cost", typeSchema: "pg_catalog", typeName: "numeric", typeModifier: 1966096, defaultCollation: true}
	if err := assertPostgresMigrationColumnCatalog(column, field); err != nil {
		t.Fatal(err)
	}
	for _, change := range []func(*postgresMigrationColumnCatalog){func(c *postgresMigrationColumnCatalog) { c.typeName = "float8" }, func(c *postgresMigrationColumnCatalog) { c.typeModifier = -1 }, func(c *postgresMigrationColumnCatalog) { c.typeModifier++ }, func(c *postgresMigrationColumnCatalog) { c.notNull = true }} {
		bad := column
		change(&bad)
		if err := assertPostgresMigrationColumnCatalog(bad, field); err == nil {
			t.Fatal("numeric physical precision drift accepted")
		}
	}
	id := query.NewFieldRef("id", "id", query.FieldInteger, false)
	reference := query.NewDecimalFieldRef("cost", "cost", true, 5, 2)
	for _, raw := range []string{"1.001", "1000"} {
		value, _ := decimal.Parse(raw)
		if _, _, err := compileInsert("public", query.NewInsertPlanReturningKey("records", []query.Assignment{query.NewAssignment(reference, query.Decimal(value))}, id)); err == nil {
			t.Fatal("native rounding allowed before execution")
		}
		plan, err := query.NewPlan("records", []query.FieldRef{reference}).WithConditions(query.NewCondition(reference, query.LookupLessThan, query.Decimal(value)))
		if err != nil {
			t.Fatal(err)
		}
		if _, _, err := compilePlan("public", plan); err != nil {
			t.Fatal("comparison was restricted to storage precision", err)
		}
	}
}

func TestPostgresDecimalRejectsForeignNumericAndAdaptsMixedRows(t *testing.T) {
	url := postgresIntegrationURL(t)
	ctx := t.Context()
	admin, err := pgx.Connect(ctx, url)
	if err != nil {
		t.Fatal("connect decimal test database")
	}
	name := fmt.Sprintf("godj_decimal_%d", time.Now().UnixNano())
	quoted := pgx.Identifier{name}.Sanitize()
	if _, err := admin.Exec(ctx, "CREATE SCHEMA "+quoted); err != nil {
		_ = admin.Close(ctx)
		t.Fatal(err)
	}
	t.Cleanup(func() {
		cleanup, cancel := context.WithTimeout(context.Background(), 20*time.Second)
		defer cancel()
		if _, err := admin.Exec(cleanup, "DROP SCHEMA "+quoted+" CASCADE"); err != nil {
			t.Error(err)
		}
		if err := admin.Close(cleanup); err != nil {
			t.Error(err)
		}
	})
	if _, err := admin.Exec(ctx, "CREATE TABLE "+quoted+`.records (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cost NUMERIC NULL, elapsed INTERVAL NULL)`); err != nil {
		t.Fatal(err)
	}
	backend, err := Open(ctx, Config{URL: url, Schema: name})
	if err != nil {
		t.Fatal(err)
	}
	defer func() {
		if err := backend.Close(); err != nil {
			t.Error(err)
		}
	}()
	id := query.NewFieldRef("id", "id", query.FieldInteger, false)
	cost := query.NewDecimalFieldRef("cost", "cost", true, 5, 2)
	elapsed := query.NewFieldRef("elapsed", "elapsed", query.FieldDuration, true)
	for _, raw := range []string{"NaN", "Infinity", "-Infinity", "1.001", "1000", "0.10"} {
		if _, err := admin.Exec(ctx, "INSERT INTO "+quoted+`.records (cost,elapsed) VALUES ($1::numeric, INTERVAL '1 second')`, raw); err != nil {
			t.Fatal(err)
		}
	}
	rows, err := backend.Query(ctx, query.NewPlan("records", []query.FieldRef{id, cost, elapsed}).WithOrderings(query.NewOrdering(id, query.Ascending)))
	if err != nil {
		t.Fatal(err)
	}
	defer rows.Close()
	count := 0
	for rows.Next() {
		var id int64
		value := orm.NewNullableDecimalScanner(5, 2)
		value.Valid = true
		value.Decimal = decimal.Decimal{Coefficient: "1"}
		var span orm.NullableDurationScanner
		err := rows.Scan(&id, &value, &span)
		if count < 5 {
			if err == nil || value.Valid {
				t.Fatal("foreign numeric accepted")
			}
		} else if err != nil || !value.Valid || value.Decimal != (decimal.Decimal{Coefficient: "1", Exponent: -1}) || !span.Valid || span.Duration != duration.FromMicroseconds(1000000) {
			t.Fatalf("mixed numeric/interval adapter: %v", err)
		}
		count++
	}
	if err := rows.Err(); err != nil || count != 6 {
		t.Fatalf("numeric foreign value coverage %d: %v", count, err)
	}
}
