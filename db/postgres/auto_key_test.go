func TestPostgresAutoKeyPhysicalAllocatorValidation(t *testing.T) {
	url := postgresIntegrationURL(t)
	namespace := postgresMigrationIntegrationSchema(t, t.Context(), url)
	backend := openPostgresMigrationIntegrationBackend(t, t.Context(), url, namespace)
	table, err := quoteTable(namespace, "reserved_keys")
	if err != nil {
		t.Fatal(err)
	}
	for _, test := range []struct{ name, definition string }{
		{"ordinary_integer", `(record_key BIGINT PRIMARY KEY, token BIGINT)`},
		{"serial_not_identity", `(record_key BIGSERIAL PRIMARY KEY, token BIGINT)`},
		{"integer_identity", `(record_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, token BIGINT)`},
		{"cycling", `(record_key BIGINT GENERATED BY DEFAULT AS IDENTITY (CYCLE) PRIMARY KEY, token BIGINT)`},
		{"composite_primary_key", `(record_key BIGINT GENERATED BY DEFAULT AS IDENTITY, token BIGINT, PRIMARY KEY(record_key,token))`},
		{"non_primary_identity", `(record_key BIGINT GENERATED BY DEFAULT AS IDENTITY, token BIGINT PRIMARY KEY)`},
		{"wrong_key", `(other_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, token BIGINT)`},
		{"partitioned", `(record_key BIGINT GENERATED BY DEFAULT AS IDENTITY, token BIGINT, PRIMARY KEY(record_key,token)) PARTITION BY RANGE(token)`},
	} {
		t.Run(test.name, func(t *testing.T) {
			if _, err := backend.database.ExecContext(t.Context(), "CREATE TABLE "+table+" "+test.definition); err != nil {
				t.Fatal(err)
			}
			t.Cleanup(func() {
				if _, err := backend.database.ExecContext(context.Background(), "DROP TABLE "+table); err != nil {
					t.Error(err)
				}
			})
			err := backend.Atomic(t.Context(), func(session db.Session) error {
				keys, err := session.(db.AutoKeyAllocator).ReserveAutoKeys(t.Context(), autokeytest.Plan(t, 1))
				if keys != nil || !errors.Is(err, &query.Error{Code: query.CodeInvalidPlan}) {
					t.Fatal("physical allocator drift accepted", keys, err)
				}
				return err
			})
			if err == nil {
				t.Fatal("invalid allocator succeeded")
			}
			var sequence string
			if err := backend.database.QueryRowContext(t.Context(), "SELECT COALESCE(pg_catalog.pg_get_serial_sequence($1, 'record_key'), '')", table).Scan(&sequence); err != nil {
				// A missing selected column is the negative control itself.
				if test.name != "wrong_key" {
					t.Fatal(err)
				}
			} else if sequence != "" {
				var called bool
				if err := backend.database.QueryRowContext(t.Context(), "SELECT is_called FROM "+sequence).Scan(&called); err != nil || called {
					t.Fatal("rejected metadata consumed sequence", called, err)
				}
			}
		})
	}
}

func TestPostgresAutoKeyNativeSequenceValues(t *testing.T) {
	url := postgresIntegrationURL(t)
	namespace := postgresMigrationIntegrationSchema(t, t.Context(), url)
	backend := openPostgresMigrationIntegrationBackend(t, t.Context(), url, namespace)
	table, err := quoteTable(namespace, "reserved_keys")
	if err != nil {
		t.Fatal(err)
	}
	for _, test := range []struct {
		name, parameters string
		want             []int64
	}{
		{"negative_and_zero", "MINVALUE -10 MAXVALUE 100 START WITH -2", []int64{-2, -1, 0}},
		{"descending_increment", "INCREMENT BY -3 MINVALUE -100 MAXVALUE 10 START WITH 9", []int64{9, 6, 3, 0}},
		{"nonunit_increment", "INCREMENT BY 5 MINVALUE 0 START WITH 0 CACHE 8", []int64{0, 5, 10}},
		{"above_float_precision", "START WITH 9007199254740993", []int64{9007199254740993, 9007199254740994}},
	} {
		t.Run(test.name, func(t *testing.T) {
			if _, err := backend.database.ExecContext(t.Context(), "CREATE TABLE "+table+" (record_key BIGINT GENERATED BY DEFAULT AS IDENTITY ("+test.parameters+") PRIMARY KEY, token BIGINT NOT NULL UNIQUE)"); err != nil {
				t.Fatal(err)
			}
			t.Cleanup(func() {
				if _, err := backend.database.ExecContext(context.Background(), "DROP TABLE "+table); err != nil {
					t.Error(err)
				}
			})
			if err := backend.Atomic(t.Context(), func(session db.Session) error {
				keys, err := session.(db.AutoKeyAllocator).ReserveAutoKeys(t.Context(), autokeytest.Plan(t, len(test.want)))
				if err != nil || !slices.Equal(keys, test.want) {
					t.Fatal("native allocator values were inferred or changed", keys, test.want, err)
				}
				tokens := make([]int64, len(keys))
				for index := range tokens {
					tokens[index] = int64(index + 1)
				}
				inserted, err := autokeytest.Insert(t, session, keys, tokens)
				if err != nil || !slices.Equal(inserted.Keys, keys) || inserted.RowsAffected != int64(len(keys)) {
					t.Fatal("actual INSERT lost native reserved values", inserted, err)
				}
				return nil
			}); err != nil {
				t.Fatal(err)
			}
			rows, err := backend.database.QueryContext(t.Context(), "SELECT record_key,token FROM "+table+" ORDER BY token")
			if err != nil {
				t.Fatal(err)
			}
			defer rows.Close()
			count := 0
			for rows.Next() {
				var key, token int64
				if err := rows.Scan(&key, &token); err != nil || count >= len(test.want) || key != test.want[count] || token != int64(count+1) {
					t.Fatal("durable native identity differs", key, token, err)
				}
				count++
			}
			if err := errors.Join(rows.Err(), rows.Close()); err != nil || count != len(test.want) {
				t.Fatal(count, err)
			}
		})
	}
}

func TestPostgresAutoKeyExhaustionAndOccupiedKeys(t *testing.T) {
	url := postgresIntegrationURL(t)
	namespace := postgresMigrationIntegrationSchema(t, t.Context(), url)
	backend := openPostgresMigrationIntegrationBackend(t, t.Context(), url, namespace)
	table, err := quoteTable(namespace, "reserved_keys")
	if err != nil {
		t.Fatal(err)
	}
	t.Run("partial_native_consumption_is_not_a_result", func(t *testing.T) {
		if _, err := backend.database.ExecContext(t.Context(), "CREATE TABLE "+table+" (record_key BIGINT GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 2) PRIMARY KEY, token BIGINT)"); err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { _, _ = backend.database.ExecContext(context.Background(), "DROP TABLE "+table) })
		err := backend.Atomic(t.Context(), func(session db.Session) error {
			keys, err := session.(db.AutoKeyAllocator).ReserveAutoKeys(t.Context(), autokeytest.Plan(t, 3))
			if keys != nil {
				t.Fatal("partial sequence result escaped", keys)
			}
			return err
		})
		if !errors.Is(err, &query.Error{Code: query.CodeAutoKeyExhausted}) {
			t.Fatal("native exhaustion classification lost", err)
		}
		var sequence string
		if err := backend.database.QueryRowContext(t.Context(), "SELECT pg_catalog.pg_get_serial_sequence($1,'record_key')", table).Scan(&sequence); err != nil {
			t.Fatal(err)
		}
		var last int64
		var called bool
		if err := backend.database.QueryRowContext(t.Context(), "SELECT last_value,is_called FROM "+sequence).Scan(&last, &called); err != nil || last != 2 || !called {
			t.Fatal("rolled-back native sequence consumption changed", last, called, err)
		}
		var count int
		if err := backend.database.QueryRowContext(t.Context(), "SELECT COUNT(*) FROM "+table).Scan(&count); err != nil || count != 0 {
			t.Fatal("reservation created rows", count, err)
		}
	})
	t.Run("existing_explicit_key_is_not_adopted", func(t *testing.T) {
		for _, statement := range []string{
			"CREATE TABLE " + table + " (record_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, token BIGINT)",
			"INSERT INTO " + table + " VALUES(1,99)",
		} {
			if _, err := backend.database.ExecContext(t.Context(), statement); err != nil {
				t.Fatal(err)
			}
		}
		t.Cleanup(func() { _, _ = backend.database.ExecContext(context.Background(), "DROP TABLE "+table) })
		err := backend.Atomic(t.Context(), func(session db.Session) error {
			keys, err := session.(db.AutoKeyAllocator).ReserveAutoKeys(t.Context(), autokeytest.Plan(t, 1))
			if keys != nil {
				t.Fatal("occupied native key was claimed", keys)
			}
			return err
		})
		if !errors.Is(err, &query.Error{Code: query.CodeUniquePrimaryKey}) {
			t.Fatal(err)
		}
		if err := backend.Atomic(t.Context(), func(session db.Session) error {
			keys, err := session.(db.AutoKeyAllocator).ReserveAutoKeys(t.Context(), autokeytest.Plan(t, 1))
			if err != nil || !slices.Equal(keys, []int64{2}) {
				t.Fatal(keys, err)
			}
			return nil
		}); err != nil {
			t.Fatal(err)
		}
		var token int64
		if err := backend.database.QueryRowContext(t.Context(), "SELECT token FROM "+table+" WHERE record_key=1").Scan(&token); err != nil || token != 99 {
			t.Fatal("existing row was changed", token, err)
		}
	})
}

