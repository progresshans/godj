type autoKeyFaultTransaction struct {
	*sql.Tx
	commitFailure, rollbackFailure error
}

func (transaction *autoKeyFaultTransaction) Commit() error {
	return errors.Join(transaction.Tx.Commit(), transaction.commitFailure)
}

func (transaction *autoKeyFaultTransaction) Rollback() error {
	return errors.Join(transaction.Tx.Rollback(), transaction.rollbackFailure)
}

func TestPostgresAutoKeyUncertainOwnerNeverReportsSuccess(t *testing.T) {
	url := postgresIntegrationURL(t)
	for _, outcome := range []string{"commit", "rollback"} {
		t.Run(outcome, func(t *testing.T) {
			namespace := postgresMigrationIntegrationSchema(t, t.Context(), url)
			backend := openPostgresMigrationIntegrationBackend(t, t.Context(), url, namespace)
			table, err := quoteTable(namespace, "reserved_keys")
			if err != nil {
				t.Fatal(err)
			}
			if _, err := backend.database.ExecContext(t.Context(), "CREATE TABLE "+table+" (record_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, token BIGINT NOT NULL UNIQUE)"); err != nil {
				t.Fatal(err)
			}
			failure, callbackFailure := errors.New("injected native acknowledgement failure"), errors.New("owner failed after insert")
			calls := 0
			var retained db.AutoKeyAllocator
			err = backend.atomic(t.Context(), func(ctx context.Context) (transactionHandle, error) {
				transaction, err := backend.database.BeginTx(ctx, nil)
				if err != nil {
					return nil, err
				}
				fault := &autoKeyFaultTransaction{Tx: transaction}
				if outcome == "commit" {
					fault.commitFailure = failure
				} else {
					fault.rollbackFailure = failure
				}
				return fault, nil
			}, func(session *transactionSession) error {
				calls++
				retained = session
				keys, err := retained.ReserveAutoKeys(t.Context(), autokeytest.Plan(t, 2))
				if err != nil {
					return err
				}
				if _, err := autokeytest.Insert(t, session, keys, []int64{1, 2}); err != nil {
					return err
				}
				if outcome == "rollback" {
					return callbackFailure
				}
				return nil
			})
			want, countWant := query.CodeTransactionOutcomeUnknown, 0
			if outcome == "commit" {
				want, countWant = query.CodeCommitOutcomeUnknown, 2
			}
			if calls != 1 || !errors.Is(err, failure) || !errors.Is(err, &query.Error{Code: want}) || (outcome == "rollback" && !errors.Is(err, callbackFailure)) {
				t.Fatal("uncertain reservation owner was retried or reported success", calls, err)
			}
			if keys, err := retained.ReserveAutoKeys(context.Background(), autokeytest.Plan(t, 1)); keys != nil || err == nil {
				t.Fatal("uncertain owner leaked a live allocator", keys, err)
			}
			var count int
			if err := backend.database.QueryRowContext(t.Context(), "SELECT COUNT(*) FROM "+table).Scan(&count); err != nil || count != countWant {
				t.Fatal("injected durable outcome differs", count, countWant, err)
			}
		})
	}
}

type autoKeyBlockingTransaction struct {
	*sql.Tx
	entered, release chan struct{}
	hold             sync.Once
}

func (transaction *autoKeyBlockingTransaction) QueryContext(ctx context.Context, statement string, arguments ...any) (*sql.Rows, error) {
	var interrupted error
	if strings.HasPrefix(statement, "SELECT pg_catalog.nextval") {
		transaction.hold.Do(func() {
			close(transaction.entered)
			select {
			case <-transaction.release:
			case <-ctx.Done():
				interrupted = ctx.Err()
			}
		})
	}
	if interrupted != nil {
		return nil, interrupted
	}
	return transaction.Tx.QueryContext(ctx, statement, arguments...)
}

