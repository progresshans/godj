func TestPostgresInsertGraphAlwaysIdentity(t *testing.T) {
	backend, observer := postgresInsertGraphFixture(t)
	for _, name := range []string{"graph_left", "graph_right"} {
		table, _ := quoteTable(backend.schema, name)
		if _, err := backend.database.ExecContext(t.Context(), "ALTER TABLE "+table+" ALTER COLUMN record_key SET GENERATED ALWAYS"); err != nil {
			t.Fatal(err)
		}
	}
	var left, right insertgraphtest.Row
	if err := backend.Atomic(t.Context(), func(session db.Session) error {
		plan, a, b := insertgraphtest.Cycle(t, session, "always")
		left, right = a, b
		keys, err := session.(db.GraphInserter).InsertGraph(t.Context(), plan)
		if err != nil || len(keys) != 2 || keys[0] != a.Key || keys[1] != b.Key {
			t.Fatal("native reserved ALWAYS keys were not inserted", keys, err)
		}
		return nil
	}); err != nil {
		t.Fatal(err)
	}
	insertgraphtest.RequireRows(t, observer, "graph_left", []insertgraphtest.Row{left})
	insertgraphtest.RequireRows(t, observer, "graph_right", []insertgraphtest.Row{right})
}

func TestPostgresInsertGraphTriggerResults(t *testing.T) {
	for _, behavior := range []string{"ignore", "replace_key", "delete_after_insert", "fail_after_previous_row", "ordinary_side_effect"} {
		t.Run(behavior, func(t *testing.T) {
			backend, observer := postgresInsertGraphFixture(t)
			table, _ := quoteTable(backend.schema, "graph_self")
			function, _ := quoteTable(backend.schema, "graph_trigger_fn")
			timing, body := "BEFORE", ""
			switch behavior {
			case "ignore":
				body = "RETURN NULL;"
			case "replace_key":
				body = "NEW.record_key := NEW.record_key+100; NEW.peer_key := NEW.peer_key+100; RETURN NEW;"
			case "delete_after_insert":
				timing = "AFTER"
				body = "DELETE FROM " + table + " WHERE record_key=NEW.record_key; RETURN NULL;"
			case "fail_after_previous_row":
				body = "IF NEW.token='second' THEN RAISE EXCEPTION 'injected graph failure'; END IF; RETURN NEW;"
			case "ordinary_side_effect":
				timing = "AFTER"
				log, _ := quoteTable(backend.schema, "graph_log")
				if _, err := backend.database.ExecContext(t.Context(), "CREATE TABLE "+log+" (id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY, token TEXT)"); err != nil {
					t.Fatal(err)
				}
				body = "INSERT INTO " + log + "(token) VALUES(NEW.token); RETURN NULL;"
			}
			for _, statement := range []string{
				"CREATE FUNCTION " + function + "() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN " + body + " END $$",
				"CREATE TRIGGER graph_trigger " + timing + " INSERT ON " + table + " FOR EACH ROW EXECUTE FUNCTION " + function + "()",
			} {
				if _, err := backend.database.ExecContext(t.Context(), statement); err != nil {
					t.Fatal(err)
				}
			}
			var expected []insertgraphtest.Row
			if err := backend.Atomic(t.Context(), func(session db.Session) error {
				requested := insertgraphtest.Reserve(t, session, "graph_self", 2)
				first := insertgraphtest.Row{Key: requested[0], Peer: requested[0], Token: "first"}
				second := insertgraphtest.Row{Key: requested[1], Peer: requested[1], Token: "second"}
				keys, err := session.(db.GraphInserter).InsertGraph(t.Context(), insertgraphtest.Plan(t,
					insertgraphtest.Insert("graph_self", first), insertgraphtest.Insert("graph_self", second)))
				if behavior == "ordinary_side_effect" {
					if err != nil || len(keys) != 2 || keys[0] != first.Key || keys[1] != second.Key {
						t.Fatal("trigger's identity leaked into graph result", keys, err)
					}
					expected = []insertgraphtest.Row{first, second}
					log, _ := quoteTable(backend.schema, "graph_log")
					var tokens string
					if err := session.(*transactionSession).transaction.QueryRowContext(t.Context(), "SELECT string_agg(token, ',' ORDER BY token) FROM "+log+" WHERE id IN (101,102)").Scan(&tokens); err != nil || tokens != "first,second" {
						t.Fatal("native trigger side effects differ", tokens, err)
					}
				} else if err == nil || keys != nil {
					t.Fatal("changed or suppressed INSERT was accepted", keys, err)
				}
				insertgraphtest.RequireRows(t, session, "graph_self", expected)
				return nil
			}); err != nil {
				t.Fatal(err)
			}
			insertgraphtest.RequireRows(t, observer, "graph_self", expected)
		})
	}
}

func TestPostgresInsertGraphRejectsNonAutoKeyBeforeWrites(t *testing.T) {
	backend, observer := postgresInsertGraphFixture(t)
	table, _ := quoteTable(backend.schema, "graph_self")
	if _, err := backend.database.ExecContext(t.Context(), "ALTER TABLE "+table+" ALTER COLUMN record_key DROP IDENTITY"); err != nil {
		t.Fatal(err)
	}
	if err := backend.Atomic(t.Context(), func(session db.Session) error {
		plan, _, _ := insertgraphtest.Cycle(t, session, "valid_but_unwritten")
		inserts := append(plan.Inserts(), insertgraphtest.Insert("graph_self", insertgraphtest.Row{Key: 77, Peer: 77, Token: "no_allocator"}))
		keys, err := session.(db.GraphInserter).InsertGraph(t.Context(), insertgraphtest.Plan(t, inserts...))
		if err == nil || keys != nil {
			t.Fatal("graph accepted a non-native identity", keys, err)
		}
		insertgraphtest.RequireRows(t, session, "graph_left", nil)
		insertgraphtest.RequireRows(t, session, "graph_right", nil)
		insertgraphtest.RequireRows(t, session, "graph_self", nil)
		return nil
	}); err != nil {
		t.Fatal(err)
	}
	insertgraphtest.RequireRows(t, observer, "graph_left", nil)
	insertgraphtest.RequireRows(t, observer, "graph_right", nil)
}

func TestPostgresInsertGraphCompilationKeepsValuesBound(t *testing.T) {
	const secret = "secret'\"; DROP TABLE graph_self;--"
	first := insertgraphtest.Insert("graph_self", insertgraphtest.Row{Key: -3, Peer: 0, Token: secret})
	second := insertgraphtest.Insert("graph_self", insertgraphtest.Row{Key: 0, Peer: -3, Token: "second"})
	compiled, err := compileInsertGraph("project", insertgraphtest.Plan(t, first, second))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(compiled.statement, secret) || strings.Contains(compiled.statement, "SET CONSTRAINTS") || !strings.Contains(compiled.statement, "$8") || len(compiled.arguments) != 8 || compiled.arguments[0] != secret || len(compiled.readKeys) != 2 || compiled.readKeys[1] != int64(0) {
		t.Fatal("graph lost bound values or changed constraint timing", compiled.statement, compiled.arguments, compiled.readKeys)
	}
	wrong := first.Assignments()
	wrong[0] = query.NewAssignment(insertgraphtest.Token, query.Integer(3))
	invalid := query.NewInsertPlanReturningKey("graph_self", wrong, insertgraphtest.Key)
	if _, err := compileInsertGraph("project", insertgraphtest.Plan(t, invalid)); err == nil {
		t.Fatal("graph bypassed scalar type validation")
	}
}
