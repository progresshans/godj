func postgresInsertGraphFixture(t *testing.T) (*Backend, *Backend) {
	t.Helper()
	url := postgresIntegrationURL(t)
	namespace := postgresMigrationIntegrationSchema(t, t.Context(), url)
	backend := openPostgresMigrationIntegrationBackend(t, t.Context(), url, namespace)
	observer := openPostgresMigrationIntegrationBackend(t, t.Context(), url, namespace)
	for _, name := range []string{"graph_left", "graph_right", "graph_self"} {
		table, err := quoteTable(namespace, name)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := backend.database.ExecContext(t.Context(), "CREATE TABLE "+table+" (record_key BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, peer_key BIGINT NOT NULL, token TEXT NOT NULL UNIQUE CHECK(token <> ''), optional_value BIGINT)"); err != nil {
			t.Fatal(err)
		}
	}
	for _, names := range [][2]string{{"graph_left", "graph_right"}, {"graph_right", "graph_left"}, {"graph_self", "graph_self"}} {
		table, _ := quoteTable(namespace, names[0])
		target, _ := quoteTable(namespace, names[1])
		if _, err := backend.database.ExecContext(t.Context(), "ALTER TABLE "+table+" ADD FOREIGN KEY (peer_key) REFERENCES "+target+" (record_key) NOT DEFERRABLE"); err != nil {
			t.Fatal(err)
		}
	}
	return backend, observer
}

