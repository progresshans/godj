func TestPostgreSQLEagerFilterJoinCompositionMatchDjango(t *testing.T) {
	databaseURL := postgresIntegrationURL(t)
	ctx := t.Context()
	admin, err := pgx.Connect(ctx, databaseURL)
	if err != nil {
		t.Fatal(redactConnectionError(err))
	}
	schema := fmt.Sprintf("godj_join_reference_%d", time.Now().UnixNano())
	quoted := pgx.Identifier{schema}.Sanitize()
	if _, err = admin.Exec(ctx, "CREATE SCHEMA "+quoted); err != nil {
		_ = admin.Close(ctx)
		t.Fatal(err)
	}
	t.Cleanup(func() {
		ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
		defer cancel()
		if _, err := admin.Exec(ctx, "DROP SCHEMA "+quoted+" CASCADE"); err != nil {
			t.Error(err)
		}
		if err := admin.Close(ctx); err != nil {
			t.Error(redactConnectionError(err))
		}
	})
	author := quoted + `."join_reference_person"`
	post := quoted + `."join_reference_post"`
	for _, statement := range []string{
		`CREATE TABLE ` + author + `(id BIGINT PRIMARY KEY, name TEXT NOT NULL, nickname TEXT NULL, active BOOLEAN NOT NULL)`,
		`CREATE TABLE ` + post + `(id BIGINT PRIMARY KEY, title TEXT NOT NULL, author_id BIGINT NOT NULL REFERENCES ` + author + `(id), reviewer_id BIGINT NULL REFERENCES ` + author + `(id))`,
		`CREATE TABLE ` + quoted + `."join_reference_comment"(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, post_id BIGINT NOT NULL REFERENCES ` + post + `(id), body TEXT NOT NULL)`,
	} {
		if _, err := admin.Exec(ctx, statement); err != nil {
			t.Fatal(err)
		}
	}
	for _, row := range [][]any{{int64(1), "Ada", nil, true}, {int64(2), "Bob", "B", false}, {int64(3), "Cleo", "", true}} {
		if _, err := admin.Exec(ctx, `INSERT INTO `+author+` VALUES($1,$2,$3,$4)`, row...); err != nil {
			t.Fatal(err)
		}
	}
	for _, row := range [][]any{{int64(1), "keep", int64(1), nil}, {int64(2), "drop", int64(2), nil}, {int64(3), "keep", int64(1), int64(1)}, {int64(4), "drop", int64(2), int64(1)}, {int64(5), "keep", int64(1), int64(2)}, {int64(6), "drop", int64(2), int64(2)}, {int64(7), "keep", int64(3), int64(3)}} {
		if _, err := admin.Exec(ctx, `INSERT INTO `+post+` VALUES($1,$2,$3,$4)`, row...); err != nil {
			t.Fatal(err)
		}
	}
	for _, row := range [][]any{{int64(1), "match"}, {int64(1), "match"}, {int64(2), "match"}, {int64(3), "other"}, {int64(4), "match"}, {int64(4), "match"}, {int64(5), "match"}, {int64(7), "match"}} {
		if _, err := admin.Exec(ctx, `INSERT INTO `+quoted+`."join_reference_comment"(post_id,body) VALUES($1,$2)`, row...); err != nil {
			t.Fatal(err)
		}
	}

	backend, err := Open(ctx, Config{URL: databaseURL, Schema: schema})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if err := backend.Close(); err != nil {
			t.Error(err)
		}
	})
	// Trace the production physical connection profile without retaining SQL
	// or credentials. Empty-result cases must avoid all connection I/O.
	config, err := currentConnectionConfig(databaseURL)
	if err != nil {
		t.Fatal("prepare traced PostgreSQL connection")
	}
	trace := &membershipTrace{table: post}
	config.Tracer = trace
	if err := backend.database.Close(); err != nil {
		t.Fatal(err)
	}
	backend.database = stdlib.OpenDB(*config,
		stdlib.OptionAfterConnect(validateAndCloseInvalidPostgresPhysicalSession),
		stdlib.OptionResetSession(func(ctx context.Context, connection *pgx.Conn) error {
			if err := validateCurrentPostgresPhysicalSession(ctx, connection); err != nil {
				return errors.Join(driver.ErrBadConn, err)
			}
			return nil
		}),
	)
	data, err := os.ReadFile("../../orm/testdata/eager-joins-django61.json")
	if err != nil {
		t.Fatal(err)
	}
	var reference nullableforwardproduct.EagerJoinReference
	if err := json.Unmarshal(data, &reference); err != nil {
		t.Fatal(err)
	}
	if reference.Django != "6.1" || len(reference.Observations) != 88 {
		t.Fatal("reference roster incomplete")
	}
	for _, observation := range reference.Observations {
		t.Run(observation.Name, func(t *testing.T) {
			plan, err := nullableforwardproduct.EagerJoinPlan(reference.Leaves, observation.EagerJoinInput)
			if err != nil {
				t.Fatal(err)
			}
			beforeReads, beforeTotal := trace.reads.Load(), trace.total.Load()
			count, first, rows, err := nullableforwardproduct.EvaluateEagerJoin(ctx, backend, plan)
			if err != nil || !reflect.DeepEqual(rows, observation.Rows) || !reflect.DeepEqual(first, observation.First) || count != observation.Count {
				t.Fatalf("rows=%v first=%v count=%d err=%v", rows, first, count, err)
			}
			expectedReads := uint64(len(observation.AllSQL) + len(observation.FirstSQL) + len(observation.CountSQL))
			if trace.reads.Load()-beforeReads != expectedReads || expectedReads == 0 && trace.total.Load() != beforeTotal {
				t.Fatalf("query count changed: reads=%d total=%d want reads=%d", trace.reads.Load()-beforeReads, trace.total.Load()-beforeTotal, expectedReads)
			}
			statement, _, err := compilePlan(schema, plan)
			if err != nil {
				t.Fatal(err)
			}
			if len(observation.AllSQL) > 0 && strings.Count(statement, "LEFT OUTER JOIN") != strings.Count(observation.AllSQL[0], "LEFT OUTER JOIN") {
				t.Fatalf("JOIN semantics differ: %s", statement)
			}
		})
	}
	for name, plan := range querytest.ConflictingEagerJoinPlans(t) {
		t.Run("invalid/"+name, func(t *testing.T) {
			before := trace.total.Load()
			statement, args, err := compilePlan(schema, plan)
			if !errors.Is(err, &query.Error{Code: query.CodeInvalidPlan}) || statement != "" || len(args) != 0 {
				t.Fatalf("invalid compilation=%q %v %v", statement, args, err)
			}
			rows, err := backend.Query(ctx, plan)
			if rows != nil {
				_ = rows.Close()
				t.Fatal("invalid projection returned rows")
			}
			if !errors.Is(err, &query.Error{Code: query.CodeInvalidPlan}) || trace.total.Load() != before {
				t.Fatalf("invalid query reached I/O: %v", err)
			}
		})
	}
}
