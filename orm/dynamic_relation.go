package orm

import (
	"strings"

	"github.com/progresshans/godj/query"
	"github.com/progresshans/godj/schema/ir"
)

// ParseDynamicRelations parses the bounded two-segment implicit-exact relation
// lookups owned by GDJ-0025. It builds the same RelationPath constructor used
// by typed related fields and publishes no partial predicate slice on error.
func ParseDynamicRelations[M any](
	model BoundModel[M],
	policy LookupPolicy,
	inputs []LookupInput,
) ([]Predicate[M], error) {
	if err := validateBoundModel(model); err != nil {
		return nil, err
	}

	result := make([]Predicate[M], 0, len(inputs))
	for _, input := range inputs {
		segments := strings.Split(input.Key, "__")
		if len(segments) != 2 || segments[0] == "" || segments[1] == "" {
			return nil, unsupportedRelationLookup(input.Key, "relation lookup must contain exactly two non-empty implicit-exact segments")
		}

		relationName, terminalName := segments[0], segments[1]
		if isRelationLookupSuffix(terminalName) {
			return nil, unsupportedRelationLookup(input.Key, "lookup suffixes on relations are not supported")
		}
		if hasReverseRelation(model.snapshot, model.identity, relationName) {
			return nil, unsupportedRelationLookup(input.Key, "reverse relation predicates are not supported")
		}
		state, err := resolveForwardRelation(model.snapshot, model.identity, model.model, relationName)
		if err != nil {
			return nil, err
		}
		terminal, ok := findField(state.targetModel.Fields, terminalName)
		if !ok {
			return nil, unknownRelatedField(terminalName)
		}
		if !supportedRelatedTerminal(terminal) {
			return nil, unsupportedRelationLookup(input.Key, "related field kind is not supported")
		}
		if policy != nil && !policy(terminal.Clone(), query.LookupExact) {
			return nil, &query.Error{
				Category: query.CategoryField,
				Code:     query.CodeDisallowedLookup,
				Field:    terminal.Name,
				Lookup:   string(query.LookupExact),
				Detail:   "lookup was rejected by policy",
			}
		}
		value, err := dynamicValue(terminal, query.LookupExact, input.Value)
		if err != nil {
			return nil, err
		}
		path, err := state.path(fieldReference(terminal))
		if err != nil {
			return nil, err
		}
		result = append(result, Predicate[M]{
			condition: query.NewRelatedCondition(path, query.LookupExact, value),
		})
	}
	return result, nil
}

// ParseDynamicReverseRelations parses only named reverse, two-segment,
// implicit-exact lookups. It is deliberately separate from
// ParseDynamicRelations so the existing forward delegate keeps its frozen
// behavior and generated bytes.
func ParseDynamicReverseRelations[M any](
	owner BoundModel[M],
	policy LookupPolicy,
	inputs []LookupInput,
) ([]Predicate[M], error) {
	if err := validateBoundModel(owner); err != nil {
		return nil, err
	}

	result := make([]Predicate[M], 0, len(inputs))
	for _, input := range inputs {
		segments := strings.Split(input.Key, "__")
		if len(segments) != 2 || segments[0] == "" || segments[1] == "" {
			return nil, unsupportedRelationLookup(input.Key, "reverse relation lookup must contain exactly two non-empty implicit-exact segments")
		}
		reverseName, terminalName := segments[0], segments[1]
		if isRelationLookupSuffix(terminalName) {
			return nil, unsupportedRelationLookup(input.Key, "lookup suffixes on reverse relations are not supported")
		}

		state, err := resolveReverseRelationState(owner.snapshot, owner.identity, owner.model, reverseName)
		if err != nil {
			return nil, err
		}
		terminal, ok := findField(state.forward.sourceModel.Fields, terminalName)
		if !ok {
			return nil, unknownRelatedField(terminalName)
		}
		if !supportedRelatedTerminal(terminal) {
			return nil, unsupportedRelationLookup(input.Key, "reverse related field kind is not supported")
		}
		if policy != nil && !policy(terminal.Clone(), query.LookupExact) {
			return nil, &query.Error{
				Category: query.CategoryField,
				Code:     query.CodeDisallowedLookup,
				Field:    terminal.Name,
				Lookup:   string(query.LookupExact),
				Detail:   "lookup was rejected by policy",
			}
		}
		value, err := dynamicValue(terminal, query.LookupExact, input.Value)
		if err != nil {
			return nil, err
		}
		path, err := state.path(fieldReference(terminal))
		if err != nil {
			return nil, err
		}
		result = append(result, Predicate[M]{
			condition: query.NewRelatedCondition(path, query.LookupExact, value),
		})
	}
	return result, nil
}

// ParseDynamicRelationObjects is the ordered additive object-surface parser.
// It preserves every GDJ-0025 required implicit-exact lookup and adds only a
// nullable forward relation's two-segment isnull form. Any failure discards
// the entire candidate slice.
func ParseDynamicRelationObjects[M any](
	model BoundModel[M],
	policy LookupPolicy,
	inputs []LookupInput,
) ([]Predicate[M], error) {
	if err := validateBoundModel(model); err != nil {
		return nil, err
	}

	result := make([]Predicate[M], 0, len(inputs))
	for _, input := range inputs {
		segments := strings.Split(input.Key, "__")
		if len(segments) == 2 && segments[0] != "" && segments[1] == string(query.LookupIsNull) {
			metadata, exists := ProjectBinding{snapshot: model.snapshot}.Relation(model.identity, segments[0])
			if exists && metadata.Nullable {
				predicate, err := parseDynamicNullableRelationIsNull(model, policy, input, metadata)
				if err != nil {
					return nil, err
				}
				result = append(result, predicate)
				continue
			}
		}

		predicates, err := ParseDynamicRelations(model, policy, []LookupInput{input})
		if err != nil {
			return nil, err
		}
		result = append(result, predicates[0])
	}
	return result, nil
}

func parseDynamicNullableRelationIsNull[M any](
	model BoundModel[M],
	policy LookupPolicy,
	input LookupInput,
	metadata RelationMetadata,
) (Predicate[M], error) {
	state, err := resolveForwardRelationState(model.snapshot, model.identity, model.model, metadata.Field)
	if err != nil {
		return Predicate[M]{}, err
	}
	if !state.metadata.Nullable {
		return Predicate[M]{}, unsupportedRelationLookup(input.Key, "required forward relation isnull is not supported")
	}
	sourceField, ok := findField(state.sourceModel.Fields, state.metadata.Field)
	if !ok || sourceField.Kind != ir.FieldForeignKey || !sourceField.Nullable || sourceField.Relation == nil ||
		sourceField.Relation.Target != state.metadata.Target {
		return Predicate[M]{}, relationInvalidPlan("nullable relation source field is not canonical")
	}
	if policy != nil && !policy(sourceField.Clone(), query.LookupIsNull) {
		return Predicate[M]{}, &query.Error{
			Category: query.CategoryField,
			Code:     query.CodeDisallowedLookup,
			Field:    sourceField.Name,
			Lookup:   string(query.LookupIsNull),
			Detail:   "lookup was rejected by policy",
		}
	}
	value, err := dynamicValue(sourceField, query.LookupIsNull, input.Value)
	if err != nil {
		return Predicate[M]{}, err
	}
	path, err := query.NewNullableForwardRelationIsNullPath(
		state.sourceIdentity,
		state.sourceModel.DBTable,
		fieldReference(sourceField),
		state.metadata.Target,
		state.targetModel.DBTable,
		state.targetPrimaryKey.Column,
	)
	if err != nil {
		return Predicate[M]{}, err
	}
	return Predicate[M]{condition: query.NewRelatedCondition(path, query.LookupIsNull, value)}, nil
}

func isRelationLookupSuffix(name string) bool {
	switch query.Lookup(name) {
	case query.LookupExact, query.LookupIsNull, query.LookupIContains:
		return true
	default:
		return false
	}
}

func supportedRelatedTerminal(field ir.Field) bool {
	if field.Relation != nil || field.Nullable {
		return false
	}
	switch field.Kind {
	case ir.FieldAuto, ir.FieldChar:
		return true
	default:
		return false
	}
}

func hasReverseRelation(snapshot *projectBindingSnapshot, owner ir.ModelIdentity, name string) bool {
	if snapshot == nil {
		return false
	}
	for _, relation := range snapshot.reverse {
		if relation.Owner == owner && relation.Name == name {
			return true
		}
	}
	return false
}

func unsupportedRelationLookup(field, detail string) *query.Error {
	return &query.Error{
		Category: query.CategoryField,
		Code:     query.CodeUnsupportedLookup,
		Field:    field,
		Lookup:   string(query.LookupExact),
		Detail:   detail,
	}
}
