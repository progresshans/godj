// GenerateProjectRelationDelete renders the additive project-only aggregate
// for relation-aware deletes. The supplied packages are the same authoritative
// declared project universe used by the generated Bind function.
func GenerateProjectRelationDelete(
	packageName string,
	packages []RelationObjectPackage,
) ([]byte, error) {
	if !validGeneratedPackageName(packageName) {
		return nil, fmt.Errorf("invalid generated package name %q", packageName)
	}
	canonical, err := canonicalRelationObjectPackages(packages)
	if err != nil {
		return nil, err
	}
	if err := validateProjectRelationSelectRelatedImports(canonical); err != nil {
		return nil, err
	}
	for _, app := range canonical {
		if err := validateRelationProjectionNames(app.schema); err != nil {
			return nil, fmt.Errorf("validate relation delete projection prerequisite %q: %w", app.alias, err)
		}
	}
	_, objectSources, err := buildProjectRelationObjectSurface(canonical)
	if err != nil {
		return nil, err
	}
	if err := validateProjectRelationObjectNamespaces(canonical, objectSources); err != nil {
		return nil, fmt.Errorf("validate project relation delete object prerequisites: %w", err)
	}
	if err := validateProjectRelationSelectRelatedNamespaces(canonical, objectSources); err != nil {
		return nil, fmt.Errorf("validate project relation delete immutable prerequisites: %w", err)
	}
	targets, err := buildProjectRelationDeleteSurface(canonical)
	if err != nil {
		return nil, err
	}
	if err := validateProjectRelationDeleteNamespaces(canonical, objectSources, targets); err != nil {
		return nil, fmt.Errorf("validate project relation delete names: %w", err)
	}
	usedApps := projectRelationDeleteUsedApps(canonical, targets)

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by GoDj. DO NOT EDIT.")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "package %s\n\n", packageName)
	fmt.Fprintln(&output, "import (")
	for _, app := range usedApps {
		fmt.Fprintf(&output, "\t%s %s\n", app.alias, strconv.Quote(app.importPath))
	}
	if len(targets) > 0 {
		fmt.Fprintln(&output, "\torm \"github.com/progresshans/godj/orm\"")
		fmt.Fprintln(&output, "\tir \"github.com/progresshans/godj/schema/ir\"")
	}
	fmt.Fprintln(&output, "\tquery \"github.com/progresshans/godj/query\"")
	fmt.Fprintln(&output, ")")
	fmt.Fprintln(&output)
	fmt.Fprintf(
		&output,
		"const GoDjProjectRelationDeleteGeneratorVersion = %s\n\n",
		strconv.Quote(ProjectRelationDeleteGeneratorVersion),
	)
	for _, target := range targets {
		fmt.Fprintf(
			&output,
			"var _ orm.WriteDescriptor[%s.%s] = %s.%sDescriptor{}\n",
			target.model.app.alias,
			target.model.model.GoName,
			target.model.app.alias,
			target.model.model.GoName,
		)
	}
	if len(targets) > 0 {
		fmt.Fprintln(&output)
	}
	fmt.Fprintln(&output, "type RelationDeleters struct {")
	for _, target := range targets {
		fmt.Fprintf(
			&output,
			"\t%s orm.RelationDeleter[%s.%s]\n",
			target.surface,
			target.model.app.alias,
			target.model.model.GoName,
		)
	}
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)
	renderBindRelationDeleters(&output, targets)

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated project relation delete companion: %w", err)
	}
	return formatted, nil
}

func buildProjectRelationDeleteSurface(
	apps []normalizedRelationObjectPackage,
) ([]projectRelationDeleteTarget, error) {
	models := make([]*projectRelationDeleteModel, 0)
	byIdentity := make(map[ir.ModelIdentity]*projectRelationDeleteModel)
	for _, app := range apps {
		for _, model := range app.schema.Models {
			identity := ir.ModelIdentity{AppLabel: app.schema.AppLabel, ModelName: model.Name}
			candidate := &projectRelationDeleteModel{
				app:           app,
				identity:      identity,
				model:         model.Clone(),
				formatVersion: app.schema.FormatVersion,
			}
			models = append(models, candidate)
			byIdentity[identity] = candidate
		}
	}
	sort.Slice(models, func(left, right int) bool {
		return compareProjectRelationDeleteIdentity(models[left].identity, models[right].identity) < 0
	})

	incoming := make(map[*projectRelationDeleteModel][]projectRelationDeleteEdge)
	for _, source := range models {
		for _, field := range source.model.Fields {
			if field.Relation == nil {
				continue
			}
			target, ok := byIdentity[field.Relation.Target]
			if !ok {
				return nil, fmt.Errorf(
					"resolve relation delete target %s.%s for %s.%s",
					field.Relation.Target.AppLabel,
					field.Relation.Target.ModelName,
					source.identity.AppLabel,
					field.Name,
				)
			}
			if target.formatVersion != ir.FormatVersion {
				return nil, fmt.Errorf(
					"relation delete target %s.%s uses schema format version %d, want %d",
					target.identity.AppLabel,
					target.identity.ModelName,
					target.formatVersion,
					ir.FormatVersion,
				)
			}
			if !projectRelationDeleteScalarTarget(target.model) {
				return nil, fmt.Errorf(
					"relation delete target %s.%s is not a relation-free scalar model",
					target.identity.AppLabel,
					target.identity.ModelName,
				)
			}
			if _, ok := projectRelationObjectAutoPrimaryKey(target.model); !ok {
				return nil, fmt.Errorf(
					"relation delete target %s.%s does not have exactly one non-null AutoField primary key",
					target.identity.AppLabel,
					target.identity.ModelName,
				)
			}
			sourcePrimaryKey, ok := projectRelationObjectAutoPrimaryKey(source.model)
			if !ok {
				return nil, fmt.Errorf(
					"relation delete source %s.%s does not have exactly one non-null AutoField primary key",
					source.identity.AppLabel,
					source.identity.ModelName,
				)
			}
			if err := validateProjectRelationDeleteEdge(field); err != nil {
				return nil, fmt.Errorf(
					"validate relation delete edge %s.%s: %w",
					source.identity.AppLabel,
					field.Name,
					err,
				)
			}
			incoming[target] = append(incoming[target], projectRelationDeleteEdge{
				source:     source,
				primaryKey: sourcePrimaryKey,
				foreignKey: field.Clone(),
			})
		}
	}

	targets := make([]projectRelationDeleteTarget, 0, len(incoming))
	for _, model := range models {
		edges := incoming[model]
		if len(edges) == 0 {
			continue
		}
		primaryKey, ok := projectRelationObjectAutoPrimaryKey(model.model)
		if !ok {
			return nil, fmt.Errorf(
				"relation delete target %s.%s does not have exactly one non-null AutoField primary key",
				model.identity.AppLabel,
				model.identity.ModelName,
			)
		}
		sort.Slice(edges, func(left, right int) bool {
			if comparison := compareProjectRelationDeleteIdentity(edges[left].source.identity, edges[right].source.identity); comparison != 0 {
				return comparison < 0
			}
			return edges[left].foreignKey.Name < edges[right].foreignKey.Name
		})
		target := projectRelationDeleteTarget{
			model:      model,
			primaryKey: primaryKey,
			edges:      append([]projectRelationDeleteEdge(nil), edges...),
			surface:    model.app.prefix + model.model.GoName,
		}
		target.fingerprint = projectRelationDeleteFingerprint(target)
		targets = append(targets, target)
	}
	return targets, nil
}

func projectRelationDeleteScalarTarget(model ir.Model) bool {
	for _, field := range model.Fields {
		if field.Relation != nil {
			return false
		}
		switch field.Kind {
		case ir.FieldAuto, ir.FieldChar, ir.FieldBoolean:
		default:
			return false
		}
	}
	return true
}

func validateProjectRelationDeleteEdge(field ir.Field) error {
	if field.Kind != ir.FieldForeignKey || field.Relation == nil {
		return fmt.Errorf("incoming field is not a ForeignKey")
	}
	if field.Relation.Cardinality != ir.RelationManyToOne {
		return fmt.Errorf("incoming relation cardinality %q is unsupported", field.Relation.Cardinality)
	}
	switch field.Relation.OnDelete {
	case ir.DeleteProtect:
		return nil
	case ir.DeleteSetNull:
		if !field.Nullable {
			return fmt.Errorf("SET_NULL requires a nullable ForeignKey")
		}
		return nil
	default:
		return fmt.Errorf("incoming delete policy %q is unsupported", field.Relation.OnDelete)
	}
}

func compareProjectRelationDeleteIdentity(left, right ir.ModelIdentity) int {
	if left.AppLabel < right.AppLabel {
		return -1
	}
	if left.AppLabel > right.AppLabel {
		return 1
	}
	if left.ModelName < right.ModelName {
		return -1
	}
	if left.ModelName > right.ModelName {
		return 1
	}
	return 0
}

func projectRelationDeleteFingerprint(target projectRelationDeleteTarget) string {
	values := []string{
		projectRelationDeletePolicyVersion,
		target.model.identity.AppLabel,
		target.model.identity.ModelName,
		target.model.model.DBTable,
		target.primaryKey.Name,
		target.primaryKey.Column,
		strconv.Itoa(len(target.edges)),
	}
	for _, edge := range target.edges {
		nullable := "0"
		if edge.foreignKey.Nullable {
			nullable = "1"
		}
		values = append(values,
			edge.source.identity.AppLabel,
			edge.source.identity.ModelName,
			edge.source.model.DBTable,
			edge.primaryKey.Name,
			edge.primaryKey.Column,
			edge.foreignKey.Name,
			edge.foreignKey.Column,
			nullable,
			string(edge.foreignKey.Relation.Cardinality),
			string(edge.foreignKey.Relation.OnDelete),
		)
	}

	var encoded bytes.Buffer
	var length [8]byte
	for _, value := range values {
		binary.BigEndian.PutUint64(length[:], uint64(len(value)))
		_, _ = encoded.Write(length[:])
		_, _ = encoded.WriteString(value)
	}
	digest := sha256.Sum256(encoded.Bytes())
	return hex.EncodeToString(digest[:])
}

func projectRelationDeleteUsedApps(
	apps []normalizedRelationObjectPackage,
	targets []projectRelationDeleteTarget,
) []normalizedRelationObjectPackage {
	used := make(map[string]struct{}, len(targets))
	for _, target := range targets {
		used[target.model.app.schema.AppLabel] = struct{}{}
	}
	result := make([]normalizedRelationObjectPackage, 0, len(used))
	for _, app := range apps {
		if _, ok := used[app.schema.AppLabel]; ok {
			result = append(result, app)
		}
	}
	return result
}

func validateProjectRelationDeleteNamespaces(
	apps []normalizedRelationObjectPackage,
	objectSources []projectRelationObjectSource,
	targets []projectRelationDeleteTarget,
) error {
	packageNames, err := projectRelationDeletePrerequisiteNames(apps, objectSources)
	if err != nil {
		return err
	}
	add := func(name, owner string) error {
		if previous, duplicate := packageNames[name]; duplicate {
			return fmt.Errorf("package symbol %s for %s conflicts with %s", name, owner, previous)
		}
		packageNames[name] = owner
		return nil
	}
	for _, candidate := range []struct {
		name  string
		owner string
	}{
		{name: "GoDjProjectRelationDeleteGeneratorVersion", owner: "project relation delete provenance constant"},
		{name: "RelationDeleters", owner: "project relation delete aggregate"},
		{name: "BindRelationDeleters", owner: "project relation delete binding function"},
	} {
		if err := add(candidate.name, candidate.owner); err != nil {
			return err
		}
	}
	aggregateFields := make(map[string]string, len(targets))
	for _, target := range targets {
		identity := target.model.identity.AppLabel + "." + target.model.identity.ModelName
		if previous, duplicate := aggregateFields[target.surface]; duplicate {
			return fmt.Errorf("RelationDeleters field %s for %s conflicts with %s", target.surface, identity, previous)
		}
		aggregateFields[target.surface] = identity
	}
	return nil
}

func projectRelationDeletePrerequisiteNames(
	apps []normalizedRelationObjectPackage,
	objectSources []projectRelationObjectSource,
) (map[string]string, error) {
	names := make(map[string]string)
	add := func(name, owner string) error {
		if previous, duplicate := names[name]; duplicate {
			return fmt.Errorf("package symbol %s for %s conflicts with %s", name, owner, previous)
		}
		names[name] = owner
		return nil
	}
	for _, candidate := range []struct {
		name  string
		owner string
	}{
		{name: "GoDjProjectBindingGeneratorVersion", owner: "project binding provenance constant"},
		{name: "Bind", owner: "project binding function"},
		{name: "GoDjProjectRelationQueryGeneratorVersion", owner: "project relation query provenance constant"},
		{name: "Relations", owner: "project relation query aggregate"},
		{name: "BindRelations", owner: "project relation query binding function"},
		{name: "GoDjProjectRelationObjectGeneratorVersion", owner: "project relation object provenance constant"},
		{name: "Objects", owner: "project relation object aggregate"},
		{name: "BindObjects", owner: "project relation object binding function"},
		{name: "GoDjProjectRelationReverseGeneratorVersion", owner: "project reverse provenance constant"},
		{name: "ReverseRelations", owner: "project reverse relation aggregate"},
		{name: "BindReverseRelations", owner: "project reverse relation binding function"},
		{name: "ReverseObjects", owner: "project reverse object aggregate"},
		{name: "BindReverseObjects", owner: "project reverse object binding function"},
		{name: "GoDjProjectRelationPrefetchGeneratorVersion", owner: "project prefetch provenance constant"},
		{name: "ReversePrefetches", owner: "project prefetch aggregate"},
		{name: "BindReversePrefetches", owner: "project prefetch binding function"},
		{name: "GoDjProjectRelationSelectRelatedGeneratorVersion", owner: "project select-related provenance constant"},
	} {
		if err := add(candidate.name, candidate.owner); err != nil {
			return nil, err
		}
	}
	for _, app := range apps {
		if err := add(app.alias, "import alias for "+app.schema.AppLabel); err != nil {
			return nil, err
		}
	}

	queryApps := make([]normalizedRelationQueryPackage, len(apps))
	reverseApps := make([]normalizedRelationReversePackage, len(apps))
	for index, app := range apps {
		queryApps[index] = normalizedRelationQueryPackage{
			alias: app.alias, prefix: app.prefix, importPath: app.importPath, schema: app.schema.Clone(),
		}
		reverseApps[index] = normalizedRelationReversePackage{
			alias: app.alias, prefix: app.prefix, importPath: app.importPath, schema: app.schema.Clone(),
		}
	}
	_, querySources, err := buildProjectRelationQuerySurface(queryApps)
	if err != nil {
		return nil, fmt.Errorf("build immutable project relation query namespace: %w", err)
	}
	for _, source := range querySources {
		identity := source.model.identity.AppLabel + "." + source.model.identity.ModelName
		if err := add(source.relationsType, "relation query surface for "+identity); err != nil {
			return nil, err
		}
		for _, relation := range source.relations {
			if err := add(relation.typeName, "relation query edge "+identity+"."+relation.field.Name); err != nil {
				return nil, err
			}
		}
	}
	_, reverseOwners, err := buildProjectRelationReverseSurface(reverseApps)
	if err != nil {
		return nil, fmt.Errorf("build immutable project reverse namespace: %w", err)
	}
	reverseObjectOwners := projectRelationReverseObjectOwners(reverseOwners)
	reverseObjectSet := make(map[*projectRelationReverseModel]struct{}, len(reverseObjectOwners))
	for index := range reverseObjectOwners {
		reverseObjectSet[reverseObjectOwners[index].model] = struct{}{}
	}
	for _, owner := range reverseOwners {
		identity := owner.model.identity.AppLabel + "." + owner.model.identity.ModelName
		if err := add(owner.relationsType, "reverse relation surface for "+identity); err != nil {
			return nil, err
		}
		if _, objectCapable := reverseObjectSet[owner.model]; objectCapable {
			if err := add(owner.factoryType, "reverse object factory for "+identity); err != nil {
				return nil, err
			}
			if err := add(owner.objectType, "reverse object wrapper for "+identity); err != nil {
				return nil, err
			}
			if err := add(owner.surface+"ReversePrefetches", "reverse prefetches for "+identity); err != nil {
				return nil, err
			}
		}
		for _, relation := range owner.relations {
			if err := add(relation.typeName, "reverse relation "+identity+"."+relation.name); err != nil {
				return nil, err
			}
		}
	}
	for _, source := range objectSources {
		identity := source.model.identity.AppLabel + "." + source.model.identity.ModelName
		if err := add(source.factoryType, "object factory for "+identity); err != nil {
			return nil, err
		}
		if err := add(source.objectType, "object wrapper for "+identity); err != nil {
			return nil, err
		}
		for _, relation := range source.relations {
			if relation.field.Nullable {
				if err := add(relation.typeName, "nullable object relation "+identity+"."+relation.field.Name); err != nil {
					return nil, err
				}
			}
		}
		if err := add(source.surface+"SelectRelated", "select-related builder for "+identity); err != nil {
			return nil, err
		}
		if err := add(source.surface+"DynamicSelectRelatedQuery", "dynamic select-related query for "+identity); err != nil {
			return nil, err
		}
		for _, relation := range source.relations {
			if err := add(
				source.surface+relation.selector+"SelectRelatedQuery",
				"select-related query for "+identity+"."+relation.field.Name,
			); err != nil {
				return nil, err
			}
		}
	}
	return names, nil
}

func renderBindRelationDeleters(output *bytes.Buffer, targets []projectRelationDeleteTarget) {
	fmt.Fprintln(output, "func BindRelationDeleters() (RelationDeleters, error) {")
	fmt.Fprintln(output, "\t_binding, _err := Bind()")
	fmt.Fprintln(output, "\tif _err != nil {")
	fmt.Fprintln(output, "\t\treturn RelationDeleters{}, _err")
	fmt.Fprintln(output, "\t}")
	if len(targets) == 0 {
		fmt.Fprintln(output, "\tif len(_binding.ForwardRelations()) != 0 {")
		fmt.Fprintln(output, "\t\treturn RelationDeleters{}, &query.Error{")
		fmt.Fprintln(output, "\t\t\tCategory: query.CategoryQuery,")
		fmt.Fprintln(output, "\t\t\tCode:     query.CodeInvalidPlan,")
		fmt.Fprintln(output, "\t\t\tDetail:   \"generated relation deleter target set does not match project binding\",")
		fmt.Fprintln(output, "\t\t}")
		fmt.Fprintln(output, "\t}")
		fmt.Fprintln(output, "\treturn RelationDeleters{}, nil")
		fmt.Fprintln(output, "}")
		return
	}

	fmt.Fprintln(output, "\t_targets := make(map[ir.ModelIdentity]struct{})")
	fmt.Fprintln(output, "\tfor _, _relation := range _binding.ForwardRelations() {")
	fmt.Fprintln(output, "\t\t_targets[_relation.Target] = struct{}{}")
	fmt.Fprintln(output, "\t}")
	fmt.Fprintf(output, "\tif len(_targets) != %d {\n", len(targets))
	fmt.Fprintln(output, "\t\treturn RelationDeleters{}, &query.Error{")
	fmt.Fprintln(output, "\t\t\tCategory: query.CategoryQuery,")
	fmt.Fprintln(output, "\t\t\tCode:     query.CodeInvalidPlan,")
	fmt.Fprintln(output, "\t\t\tDetail:   \"generated relation deleter target set does not match project binding\",")
	fmt.Fprintln(output, "\t\t}")
	fmt.Fprintln(output, "\t}")
	for _, target := range targets {
		fmt.Fprintf(
			output,
			"\tif _, _ok := _targets[ir.ModelIdentity{AppLabel: %s, ModelName: %s}]; !_ok {\n",
			strconv.Quote(target.model.identity.AppLabel),
			strconv.Quote(target.model.identity.ModelName),
		)
		fmt.Fprintln(output, "\t\treturn RelationDeleters{}, &query.Error{")
		fmt.Fprintln(output, "\t\t\tCategory: query.CategoryQuery,")
		fmt.Fprintln(output, "\t\t\tCode:     query.CodeInvalidPlan,")
		fmt.Fprintln(output, "\t\t\tDetail:   \"generated relation deleter target set does not match project binding\",")
		fmt.Fprintln(output, "\t\t}")
		fmt.Fprintln(output, "\t}")
	}
	for index, target := range targets {
		fmt.Fprintf(output, "\t_deleter%d, _err := orm.BindRelationDeleter(\n", index)
		fmt.Fprintln(output, "\t\t_binding,")
		fmt.Fprintf(
			output,
			"\t\tir.ModelIdentity{AppLabel: %s, ModelName: %s},\n",
			strconv.Quote(target.model.identity.AppLabel),
			strconv.Quote(target.model.identity.ModelName),
		)
		fmt.Fprintf(
			output,
			"\t\t%s.%sDescriptor{},\n",
			target.model.app.alias,
			target.model.model.GoName,
		)
		fmt.Fprintf(output, "\t\t%s,\n", strconv.Quote(target.fingerprint))
		fmt.Fprintln(output, "\t)")
		fmt.Fprintln(output, "\tif _err != nil {")
		fmt.Fprintln(output, "\t\treturn RelationDeleters{}, _err")
		fmt.Fprintln(output, "\t}")
	}
	fmt.Fprintln(output, "\treturn RelationDeleters{")
	for index, target := range targets {
		fmt.Fprintf(output, "\t\t%s: _deleter%d,\n", target.surface, index)
	}
	fmt.Fprintln(output, "\t}, nil")
	fmt.Fprintln(output, "}")
}
