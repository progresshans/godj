const ProjectRelationQueryGeneratorVersion = "godj-codegen-rel-query-project-v1"

type RelationQueryPackage struct {
	Alias      string
	ImportPath string
	Schema     ir.Schema
}

type projectRelationQueryTerminal struct {
	field ir.Field
	kind  ir.FieldKind
	bind  int
}

type projectRelationQueryEdge struct {
	field     ir.Field
	selector  string
	typeName  string
	target    *projectRelationModel
	terminals []projectRelationQueryTerminal
	bind      int
}

type projectRelationQuerySource struct {
	model         *projectRelationModel
	surface       string
	relationsType string
	relations     []projectRelationQueryEdge
}

// GenerateProjectRelationQuery renders project-owned typed relation wiring for
// current app schemas. Only normalized symbolic model identities cross into
// generated runtime code.
func GenerateProjectRelationQuery(packageName string, packages []RelationQueryPackage) ([]byte, error) {
	if !validGeneratedPackageName(packageName) {
		return nil, fmt.Errorf("invalid generated package name %q", packageName)
	}
	canonical, err := canonicalRelationQueryPackages(packages)
	if err != nil {
		return nil, err
	}
	return generateProjectCompanion(packageName, newRelationProjectPlan(canonical), companionQuery)
}

func generateProjectRelationQuery(packageName string, plan *relationProjectPlan) ([]byte, error) {
	canonical := plan.apps
	models, sources, err := plan.querySurface()
	if err != nil {
		return nil, err
	}

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by GoDj. DO NOT EDIT.")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "package %s\n\n", packageName)
	if len(sources) > 0 {
		fmt.Fprintln(&output, "import (")
		fmt.Fprintln(&output, "\torm \"github.com/progresshans/godj/orm\"")
		fmt.Fprintln(&output, "\tir \"github.com/progresshans/godj/schema/ir\"")
		for _, app := range canonical {
			fmt.Fprintf(&output, "\t%s %s\n", app.alias, strconv.Quote(app.importPath))
		}
		fmt.Fprintln(&output, ")")
		fmt.Fprintln(&output)
	}
	fmt.Fprintf(
		&output,
		"const GoDjProjectRelationQueryGeneratorVersion = %s\n\n",
		strconv.Quote(ProjectRelationQueryGeneratorVersion),
	)

	for _, source := range sources {
		renderProjectRelationQueryTypes(&output, source)
	}
	fmt.Fprintln(&output, "type Relations struct {")
	for _, source := range sources {
		fmt.Fprintf(&output, "\t%s %s\n", source.surface, source.relationsType)
	}
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)

	renderBindRelations(&output, models, sources)
	return output.Bytes(), nil
}

func canonicalRelationQueryPackages(packages []RelationQueryPackage) ([]normalizedRelationPackage, error) {
	inputs := make([]relationPackageInput, len(packages))
	for index, candidate := range packages {
		inputs[index] = relationPackageInput{alias: candidate.Alias, importPath: candidate.ImportPath, schema: candidate.Schema}
	}
	return canonicalRelationPackages(inputs, relationPackagePolicy{
		name: "query", validAlias: validRelationQueryAlias, objectNames: false,
		reservedPaths: []string{"github.com/progresshans/godj/orm", "github.com/progresshans/godj/schema/ir"},
	})
}

func validRelationQueryAlias(alias string) bool {
	return validRelationAlias(alias, "orm", "ir", "error", "nil")
}

func exportedRelationQueryPrefix(alias string) string {
	return string(alias[0]-'a'+'A') + alias[1:]
}

func buildProjectRelationQuerySurface(
	plan *relationProjectPlan,
) ([]*projectRelationModel, []projectRelationQuerySource, error) {
	models := plan.models
	byIdentity := plan.byIdentity

	sources := make([]projectRelationQuerySource, 0)
	nextEdgeBind := 0
	nextTerminalBind := 0
	for _, sourceModel := range models {
		relations := make([]projectRelationQueryEdge, 0)
		for _, field := range sourceModel.model.Fields {
			if field.Relation == nil || field.Nullable {
				continue
			}
			selector, err := relationQuerySelector(field)
			if err != nil {
				return nil, nil, fmt.Errorf(
					"derive relation selector for %s.%s: %w",
					sourceModel.identity.AppLabel,
					sourceModel.identity.ModelName,
					err,
				)
			}
			target, ok := byIdentity[field.Relation.Target]
			if !ok {
				return nil, nil, fmt.Errorf(
					"resolve relation query target %s.%s for %s.%s",
					field.Relation.Target.AppLabel,
					field.Relation.Target.ModelName,
					sourceModel.identity.AppLabel,
					field.Name,
				)
			}
			terminals := make([]projectRelationQueryTerminal, 0)
			for _, terminal := range target.model.Fields {
				if !supportedProjectRelationQueryTerminal(terminal) {
					continue
				}
				terminals = append(terminals, projectRelationQueryTerminal{
					field: terminal.Clone(),
					kind:  terminal.Kind,
					bind:  nextTerminalBind,
				})
				nextTerminalBind++
			}
			surface := sourceModel.app.prefix + sourceModel.model.GoName
			relations = append(relations, projectRelationQueryEdge{
				field:     field.Clone(),
				selector:  selector,
				typeName:  surface + selector + "Relation",
				target:    target,
				terminals: terminals,
				bind:      nextEdgeBind,
			})
			nextEdgeBind++
		}
		if len(relations) == 0 {
			continue
		}
		sort.Slice(relations, func(left, right int) bool {
			if relations[left].field.Name != relations[right].field.Name {
				return relations[left].field.Name < relations[right].field.Name
			}
			return relations[left].selector < relations[right].selector
		})
		surface := sourceModel.app.prefix + sourceModel.model.GoName
		sources = append(sources, projectRelationQuerySource{
			model:         sourceModel,
			surface:       surface,
			relationsType: surface + "Relations",
			relations:     relations,
		})
	}
	return models, sources, nil
}

func relationQuerySelector(field ir.Field) (string, error) {
	if !strings.HasSuffix(field.GoName, "ID") {
		return "", fmt.Errorf("ForeignKey Go name %q must end in ID", field.GoName)
	}
	selector := strings.TrimSuffix(field.GoName, "ID")
	if selector == "" || !token.IsIdentifier(selector) {
		return "", fmt.Errorf("ForeignKey Go name %q has no valid selector before ID", field.GoName)
	}
	first, _ := utf8.DecodeRuneInString(selector)
	if !unicode.IsUpper(first) {
		return "", fmt.Errorf("ForeignKey selector %q is not exported", selector)
	}
	if selector == "ParseDynamic" {
		return "", fmt.Errorf("ForeignKey selector %q conflicts with generated method", selector)
	}
	return selector, nil
}

func supportedProjectRelationQueryTerminal(field ir.Field) bool {
	if field.Relation != nil || field.Nullable {
		return false
	}
	return field.Kind == ir.FieldAuto || field.Kind == ir.FieldChar
}

func renderProjectRelationQueryTypes(output *bytes.Buffer, source projectRelationQuerySource) {
	for _, relation := range source.relations {
		fmt.Fprintf(output, "type %s struct {\n", relation.typeName)
		for _, terminal := range relation.terminals {
			switch terminal.kind {
			case ir.FieldAuto:
				fmt.Fprintf(
					output,
					"\t%s orm.RelatedIntegerField[%s.%s]\n",
					terminal.field.GoName,
					source.model.app.alias,
					source.model.model.GoName,
				)
			case ir.FieldChar:
				fmt.Fprintf(
					output,
					"\t%s orm.RelatedStringField[%s.%s]\n",
					terminal.field.GoName,
					source.model.app.alias,
					source.model.model.GoName,
				)
			}
		}
		fmt.Fprintln(output, "}")
		fmt.Fprintln(output)
	}

	fmt.Fprintf(output, "type %s struct {\n", source.relationsType)
	for _, relation := range source.relations {
		fmt.Fprintf(output, "\t%s %s\n", relation.selector, relation.typeName)
	}
	fmt.Fprintf(
		output,
		"\tmodel orm.BoundModel[%s.%s]\n",
		source.model.app.alias,
		source.model.model.GoName,
	)
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(output, "func (_relations %s) ParseDynamic(\n", source.relationsType)
	fmt.Fprintln(output, "\t_policy orm.LookupPolicy,")
	fmt.Fprintln(output, "\t_inputs []orm.LookupInput,")
	fmt.Fprintf(
		output,
		") ([]orm.Predicate[%s.%s], error) {\n",
		source.model.app.alias,
		source.model.model.GoName,
	)
	fmt.Fprintln(output, "\treturn orm.ParseDynamicRelations(_relations.model, _policy, _inputs)")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
}

func renderBindRelations(
	output *bytes.Buffer,
	models []*projectRelationModel,
	sources []projectRelationQuerySource,
) {
	fmt.Fprintln(output, "func BindRelations() (Relations, error) {")
	if len(models) == 0 || len(sources) == 0 {
		fmt.Fprintln(output, "\tif _, _err := Bind(); _err != nil {")
		fmt.Fprintln(output, "\t\treturn Relations{}, _err")
		fmt.Fprintln(output, "\t}")
		fmt.Fprintln(output, "\treturn Relations{}, nil")
		fmt.Fprintln(output, "}")
		return
	}
	fmt.Fprintln(output, "\t_binding, _err := Bind()")
	fmt.Fprintln(output, "\tif _err != nil {")
	fmt.Fprintln(output, "\t\treturn Relations{}, _err")
	fmt.Fprintln(output, "\t}")
	usedModels := make(map[int]struct{}, len(models))
	for _, source := range sources {
		usedModels[source.model.bind] = struct{}{}
		for _, relation := range source.relations {
			usedModels[relation.target.bind] = struct{}{}
		}
	}
	for _, model := range models {
		fmt.Fprintf(output, "\t_model%d, _err := orm.BindModel(\n", model.bind)
		fmt.Fprintln(output, "\t\t_binding,")
		fmt.Fprintf(
			output,
			"\t\tir.ModelIdentity{AppLabel: %s, ModelName: %s},\n",
			strconv.Quote(model.identity.AppLabel),
			strconv.Quote(model.identity.ModelName),
		)
		fmt.Fprintf(output, "\t\t%s.%sDescriptor{},\n", model.app.alias, model.model.GoName)
		fmt.Fprintln(output, "\t)")
		fmt.Fprintln(output, "\tif _err != nil {")
		fmt.Fprintln(output, "\t\treturn Relations{}, _err")
		fmt.Fprintln(output, "\t}")
		if _, used := usedModels[model.bind]; !used {
			fmt.Fprintf(output, "\t_ = _model%d\n", model.bind)
		}
	}

	for _, source := range sources {
		for _, relation := range source.relations {
			fmt.Fprintf(
				output,
				"\t_relation%d, _err := orm.BindForward(_model%d, %s, _model%d)\n",
				relation.bind,
				source.model.bind,
				strconv.Quote(relation.field.Name),
				relation.target.bind,
			)
			fmt.Fprintln(output, "\tif _err != nil {")
			fmt.Fprintln(output, "\t\treturn Relations{}, _err")
			fmt.Fprintln(output, "\t}")
			for _, terminal := range relation.terminals {
				method := "String"
				if terminal.kind == ir.FieldAuto {
					method = "Integer"
				}
				fmt.Fprintf(
					output,
					"\t_terminal%d, _err := _relation%d.%s(%s.%sFields.%s)\n",
					terminal.bind,
					relation.bind,
					method,
					relation.target.app.alias,
					relation.target.model.GoName,
					terminal.field.GoName,
				)
				fmt.Fprintln(output, "\tif _err != nil {")
				fmt.Fprintln(output, "\t\treturn Relations{}, _err")
				fmt.Fprintln(output, "\t}")
			}
		}
	}

	if len(sources) == 0 {
		fmt.Fprintln(output, "\treturn Relations{}, nil")
		fmt.Fprintln(output, "}")
		return
	}
	fmt.Fprintln(output, "\treturn Relations{")
	for _, source := range sources {
		fmt.Fprintf(output, "\t\t%s: %s{\n", source.surface, source.relationsType)
		for _, relation := range source.relations {
			fmt.Fprintf(output, "\t\t\t%s: %s{\n", relation.selector, relation.typeName)
			for _, terminal := range relation.terminals {
				fmt.Fprintf(output, "\t\t\t\t%s: _terminal%d,\n", terminal.field.GoName, terminal.bind)
			}
			fmt.Fprintln(output, "\t\t\t},")
		}
		fmt.Fprintf(output, "\t\t\tmodel: _model%d,\n", source.model.bind)
		fmt.Fprintln(output, "\t\t},")
	}
	fmt.Fprintln(output, "\t}, nil")
	fmt.Fprintln(output, "}")
}
