package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"sort"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/progresshans/godj/schema/ir"
)

const ProjectRelationQueryGeneratorVersion = "godj-codegen-rel-query-project-v1"

type RelationQueryPackage struct {
	Alias      string
	ImportPath string
	Schema     ir.Schema
}

type normalizedRelationQueryPackage struct {
	alias      string
	prefix     string
	importPath string
	schema     ir.Schema
}

type projectRelationQueryModel struct {
	app      normalizedRelationQueryPackage
	identity ir.ModelIdentity
	model    ir.Model
	bind     int
}

type projectRelationQueryTerminal struct {
	field ir.Field
	kind  ir.FieldKind
	bind  int
}

type projectRelationQueryEdge struct {
	field     ir.Field
	selector  string
	typeName  string
	target    *projectRelationQueryModel
	terminals []projectRelationQueryTerminal
	bind      int
}

type projectRelationQuerySource struct {
	model         *projectRelationQueryModel
	surface       string
	relationsType string
	relations     []projectRelationQueryEdge
}

// GenerateProjectRelationQuery renders project-owned typed relation wiring.
// It accepts mixed scalar-v2 target packages and relation-v3 source packages;
// only normalized symbolic model identities cross into generated runtime code.
func GenerateProjectRelationQuery(packageName string, packages []RelationQueryPackage) ([]byte, error) {
	if !validGeneratedPackageName(packageName) {
		return nil, fmt.Errorf("invalid generated package name %q", packageName)
	}
	canonical, err := canonicalRelationQueryPackages(packages)
	if err != nil {
		return nil, err
	}
	models, sources, err := buildProjectRelationQuerySurface(canonical)
	if err != nil {
		return nil, err
	}
	if err := validateProjectRelationQueryNamespaces(canonical, sources); err != nil {
		return nil, fmt.Errorf("validate project relation query names: %w", err)
	}

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by GoDj. DO NOT EDIT.")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "package %s\n\n", packageName)
	if len(canonical) > 0 {
		fmt.Fprintln(&output, "import (")
		fmt.Fprintln(&output, "\torm \"github.com/progresshans/godj/orm\"")
		fmt.Fprintln(&output, "\tir \"github.com/progresshans/godj/schema/ir\"")
		for _, app := range canonical {
			fmt.Fprintf(&output, "\t%s %s\n", app.alias, strconv.Quote(app.importPath))
		}
		fmt.Fprintln(&output, ")")
		fmt.Fprintln(&output)
	}
	fmt.Fprintf(
		&output,
		"const GoDjProjectRelationQueryGeneratorVersion = %s\n\n",
		strconv.Quote(ProjectRelationQueryGeneratorVersion),
	)

	for _, source := range sources {
		renderProjectRelationQueryTypes(&output, source)
	}
	fmt.Fprintln(&output, "type Relations struct {")
	for _, source := range sources {
		fmt.Fprintf(&output, "\t%s %s\n", source.surface, source.relationsType)
	}
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)

	renderBindRelations(&output, models, sources)
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated project relation query bridge: %w", err)
	}
	return formatted, nil
}

func canonicalRelationQueryPackages(packages []RelationQueryPackage) ([]normalizedRelationQueryPackage, error) {
	canonical := make([]normalizedRelationQueryPackage, len(packages))
	for index := range packages {
		candidate := packages[index]
		schema, err := ir.Normalize(candidate.Schema.Clone())
		if err != nil {
			return nil, fmt.Errorf("normalize relation query package %q: %w", candidate.Alias, err)
		}
		if !validRelationQueryAlias(candidate.Alias) {
			return nil, fmt.Errorf("invalid relation query package alias %q", candidate.Alias)
		}
		if !validImportPath(candidate.ImportPath) {
			return nil, fmt.Errorf("invalid relation query import path %q", candidate.ImportPath)
		}
		if schema.FormatVersion == ir.RelationFormatVersion {
			if err := validateRelationQueryNames(schema); err != nil {
				return nil, fmt.Errorf("validate relation query package %q: %w", candidate.Alias, err)
			}
		} else if err := validateGeneratedNames(schema); err != nil {
			return nil, fmt.Errorf("validate scalar query package %q: %w", candidate.Alias, err)
		}
		canonical[index] = normalizedRelationQueryPackage{
			alias:      candidate.Alias,
			prefix:     exportedRelationQueryPrefix(candidate.Alias),
			importPath: candidate.ImportPath,
			schema:     schema,
		}
	}

	sort.Slice(canonical, func(left, right int) bool {
		if canonical[left].schema.AppLabel != canonical[right].schema.AppLabel {
			return canonical[left].schema.AppLabel < canonical[right].schema.AppLabel
		}
		if canonical[left].alias != canonical[right].alias {
			return canonical[left].alias < canonical[right].alias
		}
		return canonical[left].importPath < canonical[right].importPath
	})

	aliases := map[string]struct{}{"orm": {}, "ir": {}}
	paths := map[string]struct{}{
		"github.com/progresshans/godj/orm":       {},
		"github.com/progresshans/godj/schema/ir": {},
	}
	prefixes := make(map[string]struct{}, len(canonical))
	apps := make(map[string]struct{}, len(canonical))
	for _, app := range canonical {
		if _, duplicate := aliases[app.alias]; duplicate {
			return nil, fmt.Errorf("duplicate relation query package alias %q", app.alias)
		}
		aliases[app.alias] = struct{}{}
		if _, duplicate := paths[app.importPath]; duplicate {
			return nil, fmt.Errorf("duplicate relation query import path %q", app.importPath)
		}
		paths[app.importPath] = struct{}{}
		if _, duplicate := prefixes[app.prefix]; duplicate {
			return nil, fmt.Errorf("duplicate relation query exported prefix %q", app.prefix)
		}
		prefixes[app.prefix] = struct{}{}
		if _, duplicate := apps[app.schema.AppLabel]; duplicate {
			return nil, fmt.Errorf("duplicate relation query app label %q", app.schema.AppLabel)
		}
		apps[app.schema.AppLabel] = struct{}{}
	}
	return canonical, nil
}

func validRelationQueryAlias(alias string) bool {
	if alias == "" || alias == "init" || alias == "orm" || alias == "ir" || alias == "error" || alias == "nil" ||
		token.Lookup(alias).IsKeyword() || alias[0] < 'a' || alias[0] > 'z' {
		return false
	}
	for index := 1; index < len(alias); index++ {
		current := alias[index]
		if !('a' <= current && current <= 'z') &&
			!('A' <= current && current <= 'Z') &&
			!('0' <= current && current <= '9') {
			return false
		}
	}
	return true
}

func exportedRelationQueryPrefix(alias string) string {
	return string(alias[0]-'a'+'A') + alias[1:]
}

func buildProjectRelationQuerySurface(
	apps []normalizedRelationQueryPackage,
) ([]*projectRelationQueryModel, []projectRelationQuerySource, error) {
	models := make([]*projectRelationQueryModel, 0)
	byIdentity := make(map[ir.ModelIdentity]*projectRelationQueryModel)
	for _, app := range apps {
		for _, model := range app.schema.Models {
			identity := ir.ModelIdentity{AppLabel: app.schema.AppLabel, ModelName: model.Name}
			candidate := &projectRelationQueryModel{app: app, identity: identity, model: model.Clone()}
			models = append(models, candidate)
			byIdentity[identity] = candidate
		}
	}
	sort.Slice(models, func(left, right int) bool {
		if models[left].identity.AppLabel != models[right].identity.AppLabel {
			return models[left].identity.AppLabel < models[right].identity.AppLabel
		}
		return models[left].identity.ModelName < models[right].identity.ModelName
	})
	for index := range models {
		models[index].bind = index
	}

	sources := make([]projectRelationQuerySource, 0)
	nextEdgeBind := 0
	nextTerminalBind := 0
	for _, sourceModel := range models {
		relations := make([]projectRelationQueryEdge, 0)
		for _, field := range sourceModel.model.Fields {
			if field.Relation == nil || field.Nullable {
				continue
			}
			selector, err := relationQuerySelector(field)
			if err != nil {
				return nil, nil, fmt.Errorf(
					"derive relation selector for %s.%s: %w",
					sourceModel.identity.AppLabel,
					sourceModel.identity.ModelName,
					err,
				)
			}
			target, ok := byIdentity[field.Relation.Target]
			if !ok {
				return nil, nil, fmt.Errorf(
					"resolve relation query target %s.%s for %s.%s",
					field.Relation.Target.AppLabel,
					field.Relation.Target.ModelName,
					sourceModel.identity.AppLabel,
					field.Name,
				)
			}
			terminals := make([]projectRelationQueryTerminal, 0)
			for _, terminal := range target.model.Fields {
				if !supportedProjectRelationQueryTerminal(terminal) {
					continue
				}
				terminals = append(terminals, projectRelationQueryTerminal{
					field: terminal.Clone(),
					kind:  terminal.Kind,
					bind:  nextTerminalBind,
				})
				nextTerminalBind++
			}
			surface := sourceModel.app.prefix + sourceModel.model.GoName
			relations = append(relations, projectRelationQueryEdge{
				field:     field.Clone(),
				selector:  selector,
				typeName:  surface + selector + "Relation",
				target:    target,
				terminals: terminals,
				bind:      nextEdgeBind,
			})
			nextEdgeBind++
		}
		if len(relations) == 0 {
			continue
		}
		sort.Slice(relations, func(left, right int) bool {
			if relations[left].field.Name != relations[right].field.Name {
				return relations[left].field.Name < relations[right].field.Name
			}
			return relations[left].selector < relations[right].selector
		})
		surface := sourceModel.app.prefix + sourceModel.model.GoName
		sources = append(sources, projectRelationQuerySource{
			model:         sourceModel,
			surface:       surface,
			relationsType: surface + "Relations",
			relations:     relations,
		})
	}
	return models, sources, nil
}

func relationQuerySelector(field ir.Field) (string, error) {
	if !strings.HasSuffix(field.GoName, "ID") {
		return "", fmt.Errorf("ForeignKey Go name %q must end in ID", field.GoName)
	}
	selector := strings.TrimSuffix(field.GoName, "ID")
	if selector == "" || !token.IsIdentifier(selector) {
		return "", fmt.Errorf("ForeignKey Go name %q has no valid selector before ID", field.GoName)
	}
	first, _ := utf8.DecodeRuneInString(selector)
	if !unicode.IsUpper(first) {
		return "", fmt.Errorf("ForeignKey selector %q is not exported", selector)
	}
	if selector == "ParseDynamic" {
		return "", fmt.Errorf("ForeignKey selector %q conflicts with generated method", selector)
	}
	return selector, nil
}

func supportedProjectRelationQueryTerminal(field ir.Field) bool {
	if field.Relation != nil || field.Nullable {
		return false
	}
	return field.Kind == ir.FieldAuto || field.Kind == ir.FieldChar
}

func validateProjectRelationQueryNamespaces(
	apps []normalizedRelationQueryPackage,
	sources []projectRelationQuerySource,
) error {
	packageNames := map[string]string{
		"GoDjProjectBindingGeneratorVersion": "project binding provenance constant",
		"Bind":                               "project binding function",
		"GoDjProjectRelationQueryGeneratorVersion": "project relation query provenance constant",
		"Relations":     "project relation aggregate",
		"BindRelations": "project relation binding function",
	}
	addPackageName := func(name, owner string) error {
		if previous, duplicate := packageNames[name]; duplicate {
			return fmt.Errorf("package symbol %s for %s conflicts with %s", name, owner, previous)
		}
		packageNames[name] = owner
		return nil
	}
	for _, app := range apps {
		if previous, collision := packageNames[app.alias]; collision {
			return fmt.Errorf("import alias %s conflicts with %s", app.alias, previous)
		}
	}

	aggregateFields := make(map[string]string, len(sources))
	for _, source := range sources {
		owner := source.model.identity.AppLabel + "." + source.model.identity.ModelName
		if err := addPackageName(source.relationsType, "relations for "+owner); err != nil {
			return err
		}
		if previous, duplicate := aggregateFields[source.surface]; duplicate {
			return fmt.Errorf("Relations field %s for %s conflicts with %s", source.surface, owner, previous)
		}
		aggregateFields[source.surface] = owner

		relationFields := map[string]string{"ParseDynamic": "generated ParseDynamic method"}
		for _, relation := range source.relations {
			if err := addPackageName(relation.typeName, "relation "+owner+"."+relation.field.Name); err != nil {
				return err
			}
			if previous, duplicate := relationFields[relation.selector]; duplicate {
				return fmt.Errorf(
					"relation field %s for %s.%s conflicts with %s",
					relation.selector,
					owner,
					relation.field.Name,
					previous,
				)
			}
			relationFields[relation.selector] = relation.field.Name
		}
	}
	return nil
}

func renderProjectRelationQueryTypes(output *bytes.Buffer, source projectRelationQuerySource) {
	for _, relation := range source.relations {
		fmt.Fprintf(output, "type %s struct {\n", relation.typeName)
		for _, terminal := range relation.terminals {
			switch terminal.kind {
			case ir.FieldAuto:
				fmt.Fprintf(
					output,
					"\t%s orm.RelatedIntegerField[%s.%s]\n",
					terminal.field.GoName,
					source.model.app.alias,
					source.model.model.GoName,
				)
			case ir.FieldChar:
				fmt.Fprintf(
					output,
					"\t%s orm.RelatedStringField[%s.%s]\n",
					terminal.field.GoName,
					source.model.app.alias,
					source.model.model.GoName,
				)
			}
		}
		fmt.Fprintln(output, "}")
		fmt.Fprintln(output)
	}

	fmt.Fprintf(output, "type %s struct {\n", source.relationsType)
	for _, relation := range source.relations {
		fmt.Fprintf(output, "\t%s %s\n", relation.selector, relation.typeName)
	}
	fmt.Fprintf(
		output,
		"\tmodel orm.BoundModel[%s.%s]\n",
		source.model.app.alias,
		source.model.model.GoName,
	)
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(output, "func (_relations %s) ParseDynamic(\n", source.relationsType)
	fmt.Fprintln(output, "\t_policy orm.LookupPolicy,")
	fmt.Fprintln(output, "\t_inputs []orm.LookupInput,")
	fmt.Fprintf(
		output,
		") ([]orm.Predicate[%s.%s], error) {\n",
		source.model.app.alias,
		source.model.model.GoName,
	)
	fmt.Fprintln(output, "\treturn orm.ParseDynamicRelations(_relations.model, _policy, _inputs)")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
}

func renderBindRelations(
	output *bytes.Buffer,
	models []*projectRelationQueryModel,
	sources []projectRelationQuerySource,
) {
	fmt.Fprintln(output, "func BindRelations() (Relations, error) {")
	if len(models) == 0 {
		fmt.Fprintln(output, "\tif _, _err := Bind(); _err != nil {")
		fmt.Fprintln(output, "\t\treturn Relations{}, _err")
		fmt.Fprintln(output, "\t}")
		fmt.Fprintln(output, "\treturn Relations{}, nil")
		fmt.Fprintln(output, "}")
		return
	}
	fmt.Fprintln(output, "\t_binding, _err := Bind()")
	fmt.Fprintln(output, "\tif _err != nil {")
	fmt.Fprintln(output, "\t\treturn Relations{}, _err")
	fmt.Fprintln(output, "\t}")
	for _, model := range models {
		fmt.Fprintf(output, "\t_model%d, _err := orm.BindModel(\n", model.bind)
		fmt.Fprintln(output, "\t\t_binding,")
		fmt.Fprintf(
			output,
			"\t\tir.ModelIdentity{AppLabel: %s, ModelName: %s},\n",
			strconv.Quote(model.identity.AppLabel),
			strconv.Quote(model.identity.ModelName),
		)
		fmt.Fprintf(output, "\t\t%s.%sDescriptor{},\n", model.app.alias, model.model.GoName)
		fmt.Fprintln(output, "\t)")
		fmt.Fprintln(output, "\tif _err != nil {")
		fmt.Fprintln(output, "\t\treturn Relations{}, _err")
		fmt.Fprintln(output, "\t}")
	}

	for _, source := range sources {
		for _, relation := range source.relations {
			fmt.Fprintf(
				output,
				"\t_relation%d, _err := orm.BindForward(_model%d, %s, _model%d)\n",
				relation.bind,
				source.model.bind,
				strconv.Quote(relation.field.Name),
				relation.target.bind,
			)
			fmt.Fprintln(output, "\tif _err != nil {")
			fmt.Fprintln(output, "\t\treturn Relations{}, _err")
			fmt.Fprintln(output, "\t}")
			for _, terminal := range relation.terminals {
				method := "String"
				if terminal.kind == ir.FieldAuto {
					method = "Integer"
				}
				fmt.Fprintf(
					output,
					"\t_terminal%d, _err := _relation%d.%s(%s.%sFields.%s)\n",
					terminal.bind,
					relation.bind,
					method,
					relation.target.app.alias,
					relation.target.model.GoName,
					terminal.field.GoName,
				)
				fmt.Fprintln(output, "\tif _err != nil {")
				fmt.Fprintln(output, "\t\treturn Relations{}, _err")
				fmt.Fprintln(output, "\t}")
			}
		}
	}

	if len(sources) == 0 {
		fmt.Fprintln(output, "\treturn Relations{}, nil")
		fmt.Fprintln(output, "}")
		return
	}
	fmt.Fprintln(output, "\treturn Relations{")
	for _, source := range sources {
		fmt.Fprintf(output, "\t\t%s: %s{\n", source.surface, source.relationsType)
		for _, relation := range source.relations {
			fmt.Fprintf(output, "\t\t\t%s: %s{\n", relation.selector, relation.typeName)
			for _, terminal := range relation.terminals {
				fmt.Fprintf(output, "\t\t\t\t%s: _terminal%d,\n", terminal.field.GoName, terminal.bind)
			}
			fmt.Fprintln(output, "\t\t\t},")
		}
		fmt.Fprintf(output, "\t\t\tmodel: _model%d,\n", source.model.bind)
		fmt.Fprintln(output, "\t\t},")
	}
	fmt.Fprintln(output, "\t}, nil")
	fmt.Fprintln(output, "}")
}
