const ProjectRelationReverseGeneratorVersion = "godj-codegen-rel-reverse-project-v1"

type RelationReversePackage struct {
	Alias      string
	ImportPath string
	Schema     ir.Schema
}

type normalizedRelationReversePackage struct {
	alias      string
	prefix     string
	importPath string
	schema     ir.Schema
}

type projectRelationReverseModel struct {
	app      normalizedRelationReversePackage
	identity ir.ModelIdentity
	model    ir.Model
	bind     int
}

type projectRelationReverseTerminal struct {
	field ir.Field
	bind  int
}

type projectRelationReverseEdge struct {
	name      string
	selector  string
	typeName  string
	source    *projectRelationReverseModel
	terminals []projectRelationReverseTerminal
	bind      int
}

type projectRelationReverseOwner struct {
	model         *projectRelationReverseModel
	surface       string
	relationsType string
	factoryType   string
	objectType    string
	relations     []projectRelationReverseEdge
}

// GenerateProjectRelationReverse renders the project-only reverse relation
// query and owner-object companion. It clones and normalizes every input and
// publishes bytes only after the complete namespace has been validated and
// gofmt has succeeded.
func GenerateProjectRelationReverse(packageName string, packages []RelationReversePackage) ([]byte, error) {
	if !validGeneratedPackageName(packageName) {
		return nil, fmt.Errorf("invalid generated package name %q", packageName)
	}
	canonical, err := canonicalRelationReversePackages(packages)
	if err != nil {
		return nil, err
	}
	models, owners, err := buildProjectRelationReverseSurface(canonical)
	if err != nil {
		return nil, err
	}
	objectOwners := projectRelationReverseObjectOwners(owners)
	queryModels := projectRelationReverseUsedModels(models, owners)
	objectModels := projectRelationReverseUsedModels(models, objectOwners)
	usedApps := projectRelationReverseUsedApps(canonical, queryModels)
	if err := validateProjectRelationReverseNamespaces(canonical, owners); err != nil {
		return nil, fmt.Errorf("validate project relation reverse names: %w", err)
	}

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by GoDj. DO NOT EDIT.")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "package %s\n\n", packageName)
	if len(queryModels) > 0 {
		fmt.Fprintln(&output, "import (")
		for _, app := range usedApps {
			fmt.Fprintf(&output, "\t%s %s\n", app.alias, strconv.Quote(app.importPath))
		}
		fmt.Fprintln(&output, "\torm \"github.com/progresshans/godj/orm\"")
		fmt.Fprintln(&output, "\tir \"github.com/progresshans/godj/schema/ir\"")
		if len(objectOwners) > 0 {
			fmt.Fprintln(&output, "\tdb \"github.com/progresshans/godj/db\"")
			fmt.Fprintln(&output, "\tquery \"github.com/progresshans/godj/query\"")
		}
		fmt.Fprintln(&output, ")")
		fmt.Fprintln(&output)
	}
	fmt.Fprintf(
		&output,
		"const GoDjProjectRelationReverseGeneratorVersion = %s\n\n",
		strconv.Quote(ProjectRelationReverseGeneratorVersion),
	)
	renderProjectRelationReversePrerequisiteAssertions(&output, queryModels, objectOwners)

	for _, owner := range owners {
		renderProjectRelationReverseTypes(&output, owner)
	}
	fmt.Fprintln(&output, "type ReverseRelations struct {")
	for _, owner := range owners {
		fmt.Fprintf(&output, "\t%s %s\n", owner.surface, owner.relationsType)
	}
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)
	renderBindReverseRelations(&output, queryModels, owners)
	fmt.Fprintln(&output)

	for _, owner := range objectOwners {
		renderProjectRelationReverseObjectTypes(&output, owner)
	}
	fmt.Fprintln(&output, "type ReverseObjects struct {")
	for _, owner := range objectOwners {
		fmt.Fprintf(&output, "\t%s %s\n", owner.surface, owner.factoryType)
	}
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)
	renderBindReverseObjects(&output, objectModels, objectOwners)

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated project relation reverse companion: %w", err)
	}
	return formatted, nil
}

func canonicalRelationReversePackages(packages []RelationReversePackage) ([]normalizedRelationReversePackage, error) {
	canonical := make([]normalizedRelationReversePackage, len(packages))
	for index := range packages {
		candidate := packages[index]
		schema, err := ir.Normalize(candidate.Schema.Clone())
		if err != nil {
			return nil, fmt.Errorf("normalize relation reverse package %q: %w", candidate.Alias, err)
		}
		if err := validateGeneratedNames(schema); err != nil {
			return nil, fmt.Errorf("validate reverse package %q: %w", candidate.Alias, err)
		}
		if err := validateRelationMetadataNames(schema); err != nil {
			return nil, fmt.Errorf("validate reverse metadata package %q: %w", candidate.Alias, err)
		}
		if err := validateRelationObjectNames(schema); err != nil {
			return nil, fmt.Errorf("validate relation reverse object prerequisite %q: %w", candidate.Alias, err)
		}
		if !validRelationReverseAlias(candidate.Alias) {
			return nil, fmt.Errorf("invalid relation reverse package alias %q", candidate.Alias)
		}
		if !validImportPath(candidate.ImportPath) {
			return nil, fmt.Errorf("invalid relation reverse import path %q", candidate.ImportPath)
		}
		canonical[index] = normalizedRelationReversePackage{
			alias:      candidate.Alias,
			prefix:     exportedRelationQueryPrefix(candidate.Alias),
			importPath: candidate.ImportPath,
			schema:     schema,
		}
	}
	sort.Slice(canonical, func(left, right int) bool {
		if canonical[left].schema.AppLabel != canonical[right].schema.AppLabel {
			return canonical[left].schema.AppLabel < canonical[right].schema.AppLabel
		}
		if canonical[left].alias != canonical[right].alias {
			return canonical[left].alias < canonical[right].alias
		}
		return canonical[left].importPath < canonical[right].importPath
	})

	aliases := map[string]struct{}{"db": {}, "orm": {}, "query": {}, "ir": {}}
	paths := map[string]struct{}{
		"github.com/progresshans/godj/db":        {},
		"github.com/progresshans/godj/orm":       {},
		"github.com/progresshans/godj/query":     {},
		"github.com/progresshans/godj/schema/ir": {},
	}
	prefixes := make(map[string]struct{}, len(canonical))
	apps := make(map[string]struct{}, len(canonical))
	for _, app := range canonical {
		if _, duplicate := aliases[app.alias]; duplicate {
			return nil, fmt.Errorf("duplicate relation reverse package alias %q", app.alias)
		}
		aliases[app.alias] = struct{}{}
		if _, duplicate := paths[app.importPath]; duplicate {
			return nil, fmt.Errorf("duplicate relation reverse import path %q", app.importPath)
		}
		paths[app.importPath] = struct{}{}
		if _, duplicate := prefixes[app.prefix]; duplicate {
			return nil, fmt.Errorf("duplicate relation reverse exported prefix %q", app.prefix)
		}
		prefixes[app.prefix] = struct{}{}
		if _, duplicate := apps[app.schema.AppLabel]; duplicate {
			return nil, fmt.Errorf("duplicate relation reverse app label %q", app.schema.AppLabel)
		}
		apps[app.schema.AppLabel] = struct{}{}
	}
	return canonical, nil
}

func validRelationReverseAlias(alias string) bool {
	if alias == "" || alias == "init" || alias == "db" || alias == "orm" || alias == "query" || alias == "ir" ||
		alias == "bool" || alias == "error" || alias == "false" || alias == "nil" || alias == "true" ||
		token.Lookup(alias).IsKeyword() || alias[0] < 'a' || alias[0] > 'z' {
		return false
	}
	for index := 1; index < len(alias); index++ {
		current := alias[index]
		if !('a' <= current && current <= 'z') &&
			!('A' <= current && current <= 'Z') &&
			!('0' <= current && current <= '9') {
			return false
		}
	}
	return true
}

func buildProjectRelationReverseSurface(
	apps []normalizedRelationReversePackage,
) ([]*projectRelationReverseModel, []projectRelationReverseOwner, error) {
	models := make([]*projectRelationReverseModel, 0)
	byIdentity := make(map[ir.ModelIdentity]*projectRelationReverseModel)
	for _, app := range apps {
		for _, model := range app.schema.Models {
			identity := ir.ModelIdentity{AppLabel: app.schema.AppLabel, ModelName: model.Name}
			candidate := &projectRelationReverseModel{app: app, identity: identity, model: model.Clone()}
			models = append(models, candidate)
			byIdentity[identity] = candidate
		}
	}
	sort.Slice(models, func(left, right int) bool {
		if models[left].identity.AppLabel != models[right].identity.AppLabel {
			return models[left].identity.AppLabel < models[right].identity.AppLabel
		}
		return models[left].identity.ModelName < models[right].identity.ModelName
	})
	for index := range models {
		models[index].bind = index
	}

	edgesByOwner := make(map[ir.ModelIdentity][]projectRelationReverseEdge)
	for _, source := range models {
		for _, field := range source.model.Fields {
			if field.Relation == nil || field.Relation.Reverse.Disabled {
				continue
			}
			owner, ok := byIdentity[field.Relation.Target]
			if !ok {
				return nil, nil, fmt.Errorf(
					"resolve reverse owner %s.%s for %s.%s",
					field.Relation.Target.AppLabel,
					field.Relation.Target.ModelName,
					source.identity.AppLabel,
					field.Name,
				)
			}
			if _, ok := projectRelationObjectAutoPrimaryKey(owner.model); !ok {
				return nil, nil, fmt.Errorf(
					"reverse owner %s.%s does not have exactly one non-null AutoField primary key",
					owner.identity.AppLabel,
					owner.identity.ModelName,
				)
			}
			selector, err := relationReverseSelector(field.Relation.Reverse.Name)
			if err != nil {
				return nil, nil, fmt.Errorf(
					"derive reverse selector for %s.%s: %w",
					source.identity.AppLabel,
					field.Name,
					err,
				)
			}
			terminals := make([]projectRelationReverseTerminal, 0)
			for _, terminal := range source.model.Fields {
				if supportedProjectRelationQueryTerminal(terminal) {
					terminals = append(terminals, projectRelationReverseTerminal{field: terminal.Clone()})
				}
			}
			edgesByOwner[owner.identity] = append(edgesByOwner[owner.identity], projectRelationReverseEdge{
				name:      field.Relation.Reverse.Name,
				selector:  selector,
				source:    source,
				terminals: terminals,
			})
		}
	}

	owners := make([]projectRelationReverseOwner, 0, len(edgesByOwner))
	nextRelationBind := 0
	nextTerminalBind := 0
	for _, model := range models {
		relations := edgesByOwner[model.identity]
		if len(relations) == 0 {
			continue
		}
		sort.Slice(relations, func(left, right int) bool {
			if relations[left].name != relations[right].name {
				return relations[left].name < relations[right].name
			}
			if relations[left].source.identity.AppLabel != relations[right].source.identity.AppLabel {
				return relations[left].source.identity.AppLabel < relations[right].source.identity.AppLabel
			}
			return relations[left].source.identity.ModelName < relations[right].source.identity.ModelName
		})
		surface := model.app.prefix + model.model.GoName
		for index := range relations {
			relations[index].bind = nextRelationBind
			relations[index].typeName = surface + relations[index].selector + "ReverseRelation"
			nextRelationBind++
			for terminalIndex := range relations[index].terminals {
				relations[index].terminals[terminalIndex].bind = nextTerminalBind
				nextTerminalBind++
			}
		}
		owners = append(owners, projectRelationReverseOwner{
			model:         model,
			surface:       surface,
			relationsType: surface + "ReverseRelations",
			factoryType:   surface + "ReverseObjectFactory",
			objectType:    surface + "ReverseObject",
			relations:     relations,
		})
	}
	return models, owners, nil
}

func projectRelationReverseObjectOwners(owners []projectRelationReverseOwner) []projectRelationReverseOwner {
	return append([]projectRelationReverseOwner(nil), owners...)
}

func projectRelationReverseUsedModels(
	models []*projectRelationReverseModel,
	owners []projectRelationReverseOwner,
) []*projectRelationReverseModel {
	required := make(map[ir.ModelIdentity]struct{})
	for _, owner := range owners {
		required[owner.model.identity] = struct{}{}
		for _, relation := range owner.relations {
			required[relation.source.identity] = struct{}{}
		}
	}
	result := make([]*projectRelationReverseModel, 0, len(required))
	for _, model := range models {
		if _, ok := required[model.identity]; ok {
			result = append(result, model)
		}
	}
	return result
}

func projectRelationReverseUsedApps(
	apps []normalizedRelationReversePackage,
	models []*projectRelationReverseModel,
) []normalizedRelationReversePackage {
	required := make(map[string]struct{})
	for _, model := range models {
		required[model.app.schema.AppLabel] = struct{}{}
	}
	result := make([]normalizedRelationReversePackage, 0, len(required))
	for _, app := range apps {
		if _, ok := required[app.schema.AppLabel]; ok {
			result = append(result, app)
		}
	}
	return result
}

func relationReverseSelector(name string) (string, error) {
	if name == "" || strings.HasPrefix(name, "_") || strings.HasSuffix(name, "_") {
		return "", fmt.Errorf("reverse name %q is not strict lower-snake", name)
	}
	segments := strings.Split(name, "_")
	var result strings.Builder
	for _, segment := range segments {
		if segment == "" || segment == "init" || token.Lookup(segment).IsKeyword() {
			return "", fmt.Errorf("reverse name %q has an empty or reserved segment", name)
		}
		if segment[0] < 'a' || segment[0] > 'z' {
			return "", fmt.Errorf("reverse name %q has a non-lowercase segment", name)
		}
		for index := 1; index < len(segment); index++ {
			current := segment[index]
			if !('a' <= current && current <= 'z') && !('0' <= current && current <= '9') {
				return "", fmt.Errorf("reverse name %q is not ASCII lower-snake", name)
			}
		}
		result.WriteByte(segment[0] - 'a' + 'A')
		result.WriteString(segment[1:])
	}
	selector := result.String()
	if selector == "" || !token.IsIdentifier(selector) {
		return "", fmt.Errorf("reverse name %q has no generated selector", name)
	}
	return selector, nil
}

func validateProjectRelationReverseNamespaces(
	apps []normalizedRelationReversePackage,
	owners []projectRelationReverseOwner,
) error {
	packageNames := map[string]string{
		"GoDjProjectBindingGeneratorVersion": "project binding provenance constant",
		"Bind":                               "project binding function",
		"GoDjProjectRelationReverseGeneratorVersion": "project reverse provenance constant",
		"ReverseRelations":                           "project reverse relation aggregate",
		"BindReverseRelations":                       "project reverse relation binding function",
		"ReverseObjects":                             "project reverse object aggregate",
		"BindReverseObjects":                         "project reverse object binding function",
	}
	addPackageName := func(name, owner string) error {
		if previous, duplicate := packageNames[name]; duplicate {
			return fmt.Errorf("package symbol %s for %s conflicts with %s", name, owner, previous)
		}
		packageNames[name] = owner
		return nil
	}
	for _, app := range apps {
		if previous, collision := packageNames[app.alias]; collision {
			return fmt.Errorf("import alias %s conflicts with %s", app.alias, previous)
		}
	}
	if err := seedProjectRelationReversePrerequisiteNames(apps, addPackageName); err != nil {
		return err
	}

	aggregateFields := make(map[string]string, len(owners))
	for _, owner := range owners {
		identity := owner.model.identity.AppLabel + "." + owner.model.identity.ModelName
		if previous, duplicate := aggregateFields[owner.surface]; duplicate {
			return fmt.Errorf("reverse aggregate field %s for %s conflicts with %s", owner.surface, identity, previous)
		}
		aggregateFields[owner.surface] = identity
		names := map[string]string{
			owner.relationsType: "reverse relations for " + identity,
		}
		names[owner.factoryType] = "reverse object factory for " + identity
		names[owner.objectType] = "reverse object wrapper for " + identity
		for name, kind := range names {
			if err := addPackageName(name, kind); err != nil {
				return err
			}
		}

		selectors := map[string]string{
			"ParseDynamic": "generated reverse query method",
		}
		selectors["Model"] = "generated reverse object method"
		selectors["Fresh"] = "generated reverse object method"
		selectors["From"] = "generated reverse object factory method"
		privateFields := map[string]string{
			"model":   "generated model field",
			"factory": "generated factory field",
			"backend": "generated backend field",
			"_self":   "generated self sentinel",
		}
		for _, relation := range owner.relations {
			if err := addPackageName(relation.typeName, "reverse relation "+identity+"."+relation.name); err != nil {
				return err
			}
			if previous, duplicate := selectors[relation.selector]; duplicate {
				return fmt.Errorf("reverse selector %s for %s.%s conflicts with %s", relation.selector, identity, relation.name, previous)
			}
			selectors[relation.selector] = relation.name
			private := lowerFirst(relation.selector)
			if previous, duplicate := privateFields[private]; duplicate {
				return fmt.Errorf("private reverse field %s for %s.%s conflicts with %s", private, identity, relation.name, previous)
			}
			privateFields[private] = relation.name
		}
	}
	return nil
}

func seedProjectRelationReversePrerequisiteNames(
	apps []normalizedRelationReversePackage,
	add func(string, string) error,
) error {
	queryApps := make([]normalizedRelationQueryPackage, len(apps))
	objectApps := make([]normalizedRelationObjectPackage, len(apps))
	for index, app := range apps {
		queryApps[index] = normalizedRelationQueryPackage{
			alias:      app.alias,
			prefix:     app.prefix,
			importPath: app.importPath,
			schema:     app.schema.Clone(),
		}
		objectApps[index] = normalizedRelationObjectPackage{
			alias:      app.alias,
			prefix:     app.prefix,
			importPath: app.importPath,
			schema:     app.schema.Clone(),
		}
	}

	if err := add("GoDjProjectRelationQueryGeneratorVersion", "project relation query provenance constant"); err != nil {
		return err
	}
	if err := add("Relations", "project relation query aggregate"); err != nil {
		return err
	}
	if err := add("BindRelations", "project relation query binding function"); err != nil {
		return err
	}
	_, querySources, err := buildProjectRelationQuerySurface(queryApps)
	if err != nil {
		return fmt.Errorf("build immutable project relation query namespace: %w", err)
	}
	if err := validateProjectRelationQueryNamespaces(queryApps, querySources); err != nil {
		return fmt.Errorf("validate immutable project relation query namespace: %w", err)
	}
	for _, source := range querySources {
		owner := source.model.identity.AppLabel + "." + source.model.identity.ModelName
		if err := add(source.relationsType, "project relation query surface for "+owner); err != nil {
			return err
		}
		for _, relation := range source.relations {
			if err := add(relation.typeName, "project relation query edge "+owner+"."+relation.field.Name); err != nil {
				return err
			}
		}
	}

	if err := add("GoDjProjectRelationObjectGeneratorVersion", "project relation object provenance constant"); err != nil {
		return err
	}
	if err := add("Objects", "project relation object aggregate"); err != nil {
		return err
	}
	if err := add("BindObjects", "project relation object binding function"); err != nil {
		return err
	}
	_, objectSources, err := buildProjectRelationObjectSurface(objectApps)
	if err != nil {
		return fmt.Errorf("build immutable project relation object namespace: %w", err)
	}
	if err := validateProjectRelationObjectNamespaces(objectApps, objectSources); err != nil {
		return fmt.Errorf("validate immutable project relation object namespace: %w", err)
	}
	for _, source := range objectSources {
		owner := source.model.identity.AppLabel + "." + source.model.identity.ModelName
		if err := add(source.factoryType, "project relation object factory for "+owner); err != nil {
			return err
		}
		if err := add(source.objectType, "project relation object wrapper for "+owner); err != nil {
			return err
		}
		for _, relation := range source.relations {
			if relation.typeName == "" {
				continue
			}
			if err := add(relation.typeName, "project nullable relation object "+owner+"."+relation.field.Name); err != nil {
				return err
			}
		}
	}
	return nil
}

func renderProjectRelationReverseTypes(output *bytes.Buffer, owner projectRelationReverseOwner) {
	ownerType := owner.model.app.alias + "." + owner.model.model.GoName
	for _, relation := range owner.relations {
		fmt.Fprintf(output, "type %s struct {\n", relation.typeName)
		for _, terminal := range relation.terminals {
			fieldType := "orm.RelatedStringField"
			if terminal.field.Kind == ir.FieldAuto {
				fieldType = "orm.RelatedIntegerField"
			}
			fmt.Fprintf(output, "\t%s %s[%s]\n", terminal.field.GoName, fieldType, ownerType)
		}
		fmt.Fprintln(output, "}")
		fmt.Fprintln(output)
	}
	fmt.Fprintf(output, "type %s struct {\n", owner.relationsType)
	for _, relation := range owner.relations {
		fmt.Fprintf(output, "\t%s %s\n", relation.selector, relation.typeName)
	}
	fmt.Fprintf(output, "\tmodel orm.BoundModel[%s]\n", ownerType)
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(output, "func (_relations %s) ParseDynamic(\n", owner.relationsType)
	fmt.Fprintln(output, "\t_policy orm.LookupPolicy,")
	fmt.Fprintln(output, "\t_inputs []orm.LookupInput,")
	fmt.Fprintf(output, ") ([]orm.Predicate[%s], error) {\n", ownerType)
	fmt.Fprintln(output, "\treturn orm.ParseDynamicReverseRelations(_relations.model, _policy, _inputs)")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
}

func renderProjectRelationReversePrerequisiteAssertions(
	output *bytes.Buffer,
	models []*projectRelationReverseModel,
	objectOwners []projectRelationReverseOwner,
) {
	if len(models) == 0 {
		return
	}
	primaryKeyOwners := make(map[ir.ModelIdentity]struct{}, len(objectOwners))
	for _, owner := range objectOwners {
		primaryKeyOwners[owner.model.identity] = struct{}{}
	}
	for _, model := range models {
		modelType := model.app.alias + "." + model.model.GoName
		descriptor := model.app.alias + "." + model.model.GoName + "Descriptor{}"
		fmt.Fprintf(output, "var _ orm.RelationObjectDescriptor[%s] = %s\n", modelType, descriptor)
		if _, ok := primaryKeyOwners[model.identity]; ok {
			fmt.Fprintf(output, "var _ orm.PrimaryKeyObjectDescriptor[%s] = %s\n", modelType, descriptor)
		}
	}
	fmt.Fprintln(output)
}

func renderBindReverseRelations(
	output *bytes.Buffer,
	models []*projectRelationReverseModel,
	owners []projectRelationReverseOwner,
) {
	fmt.Fprintln(output, "func BindReverseRelations() (ReverseRelations, error) {")
	if len(owners) == 0 {
		fmt.Fprintln(output, "\tif _, _err := Bind(); _err != nil {")
		fmt.Fprintln(output, "\t\treturn ReverseRelations{}, _err")
		fmt.Fprintln(output, "\t}")
		fmt.Fprintln(output, "\treturn ReverseRelations{}, nil")
		fmt.Fprintln(output, "}")
		return
	}
	renderProjectRelationReverseModelBindings(output, models, "ReverseRelations")
	for _, owner := range owners {
		for _, relation := range owner.relations {
			fmt.Fprintf(
				output,
				"\t_relation%d, _err := orm.BindReverse(_model%d, %s, _model%d)\n",
				relation.bind,
				owner.model.bind,
				strconv.Quote(relation.name),
				relation.source.bind,
			)
			fmt.Fprintln(output, "\tif _err != nil {")
			fmt.Fprintln(output, "\t\treturn ReverseRelations{}, _err")
			fmt.Fprintln(output, "\t}")
			for _, terminal := range relation.terminals {
				method := "String"
				if terminal.field.Kind == ir.FieldAuto {
					method = "Integer"
				}
				fmt.Fprintf(
					output,
					"\t_terminal%d, _err := _relation%d.%s(%s.%sFields.%s)\n",
					terminal.bind,
					relation.bind,
					method,
					relation.source.app.alias,
					relation.source.model.GoName,
					terminal.field.GoName,
				)
				fmt.Fprintln(output, "\tif _err != nil {")
				fmt.Fprintln(output, "\t\treturn ReverseRelations{}, _err")
				fmt.Fprintln(output, "\t}")
			}
		}
	}
	fmt.Fprintln(output, "\treturn ReverseRelations{")
	for _, owner := range owners {
		fmt.Fprintf(output, "\t\t%s: %s{\n", owner.surface, owner.relationsType)
		for _, relation := range owner.relations {
			fmt.Fprintf(output, "\t\t\t%s: %s{\n", relation.selector, relation.typeName)
			for _, terminal := range relation.terminals {
				fmt.Fprintf(output, "\t\t\t\t%s: _terminal%d,\n", terminal.field.GoName, terminal.bind)
			}
			fmt.Fprintln(output, "\t\t\t},")
		}
		fmt.Fprintf(output, "\t\t\tmodel: _model%d,\n", owner.model.bind)
		fmt.Fprintln(output, "\t\t},")
	}
	fmt.Fprintln(output, "\t}, nil")
	fmt.Fprintln(output, "}")
}

