const ProjectRelationReverseGeneratorVersion = "godj-codegen-rel-reverse-project-v1"

type RelationReversePackage struct {
	Alias      string
	ImportPath string
	Schema     ir.Schema
}

type projectRelationReverseTerminal struct {
	field ir.Field
	bind  int
}

type projectRelationReverseEdge struct {
	name      string
	selector  string
	typeName  string
	source    *projectRelationModel
	terminals []projectRelationReverseTerminal
	bind      int
}

type projectRelationReverseOwner struct {
	model         *projectRelationModel
	surface       string
	relationsType string
	factoryType   string
	objectType    string
	relations     []projectRelationReverseEdge
}

// GenerateProjectRelationReverse renders the project-only reverse relation
// query and owner-object companion. It clones and normalizes every input and
// publishes bytes only after the complete namespace has been validated and
// gofmt has succeeded.
func GenerateProjectRelationReverse(packageName string, packages []RelationReversePackage) ([]byte, error) {
	if !validGeneratedPackageName(packageName) {
		return nil, fmt.Errorf("invalid generated package name %q", packageName)
	}
	canonical, err := canonicalRelationReversePackages(packages)
	if err != nil {
		return nil, err
	}
	return generateProjectCompanion(packageName, newRelationProjectPlan(canonical), companionReverse)
}

func generateProjectRelationReverse(packageName string, plan *relationProjectPlan) ([]byte, error) {
	canonical := plan.apps
	models, owners, err := plan.reverseSurface()
	if err != nil {
		return nil, err
	}
	objectOwners := projectRelationReverseObjectOwners(owners)
	queryModels := projectRelationReverseUsedModels(models, owners)
	objectModels := projectRelationReverseUsedModels(models, objectOwners)
	usedApps := projectRelationReverseUsedApps(canonical, queryModels)

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by GoDj. DO NOT EDIT.")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "package %s\n\n", packageName)
	if len(queryModels) > 0 {
		fmt.Fprintln(&output, "import (")
		for _, app := range usedApps {
			fmt.Fprintf(&output, "\t%s %s\n", app.alias, strconv.Quote(app.importPath))
		}
		fmt.Fprintln(&output, "\torm \"github.com/progresshans/godj/orm\"")
		fmt.Fprintln(&output, "\tir \"github.com/progresshans/godj/schema/ir\"")
		if len(objectOwners) > 0 {
			fmt.Fprintln(&output, "\tdb \"github.com/progresshans/godj/db\"")
			fmt.Fprintln(&output, "\tquery \"github.com/progresshans/godj/query\"")
		}
		fmt.Fprintln(&output, ")")
		fmt.Fprintln(&output)
	}
	fmt.Fprintf(
		&output,
		"const GoDjProjectRelationReverseGeneratorVersion = %s\n\n",
		strconv.Quote(ProjectRelationReverseGeneratorVersion),
	)
	renderProjectRelationReversePrerequisiteAssertions(&output, queryModels, objectOwners)

	for _, owner := range owners {
		renderProjectRelationReverseTypes(&output, owner)
	}
	fmt.Fprintln(&output, "type ReverseRelations struct {")
	for _, owner := range owners {
		fmt.Fprintf(&output, "\t%s %s\n", owner.surface, owner.relationsType)
	}
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)
	renderBindReverseRelations(&output, queryModels, owners)
	fmt.Fprintln(&output)

	for _, owner := range objectOwners {
		renderProjectRelationReverseObjectTypes(&output, owner)
	}
	fmt.Fprintln(&output, "type ReverseObjects struct {")
	for _, owner := range objectOwners {
		fmt.Fprintf(&output, "\t%s %s\n", owner.surface, owner.factoryType)
	}
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)
	renderBindReverseObjects(&output, objectModels, objectOwners)

	return output.Bytes(), nil
}

func canonicalRelationReversePackages(packages []RelationReversePackage) ([]normalizedRelationPackage, error) {
	inputs := make([]relationPackageInput, len(packages))
	for index, candidate := range packages {
		inputs[index] = relationPackageInput{alias: candidate.Alias, importPath: candidate.ImportPath, schema: candidate.Schema}
	}
	return canonicalRelationPackages(inputs, relationPackagePolicy{
		name: "reverse", validAlias: validRelationReverseAlias,
		reservedPaths: []string{"github.com/progresshans/godj/db", "github.com/progresshans/godj/orm", "github.com/progresshans/godj/query", "github.com/progresshans/godj/schema/ir"},
	})
}

func validRelationReverseAlias(alias string) bool {
	return validRelationAlias(alias, "db", "orm", "query", "ir", "bool", "error", "false", "nil", "true")
}

func buildProjectRelationReverseSurface(
	plan *relationProjectPlan,
) ([]*projectRelationModel, []projectRelationReverseOwner, error) {
	models := plan.models
	byIdentity := plan.byIdentity

	edgesByOwner := make(map[ir.ModelIdentity][]projectRelationReverseEdge)
	for _, source := range models {
		for _, field := range source.model.Fields {
			if field.Relation == nil || field.Relation.Reverse.Disabled {
				continue
			}
			owner, ok := byIdentity[field.Relation.Target]
			if !ok {
				return nil, nil, fmt.Errorf(
					"resolve reverse owner %s.%s for %s.%s",
					field.Relation.Target.AppLabel,
					field.Relation.Target.ModelName,
					source.identity.AppLabel,
					field.Name,
				)
			}
			if _, ok := projectRelationObjectAutoPrimaryKey(owner.model); !ok {
				return nil, nil, fmt.Errorf(
					"reverse owner %s.%s does not have exactly one non-null AutoField primary key",
					owner.identity.AppLabel,
					owner.identity.ModelName,
				)
			}
			selector, err := relationReverseSelector(field.Relation.Reverse.Name)
			if err != nil {
				return nil, nil, fmt.Errorf(
					"derive reverse selector for %s.%s: %w",
					source.identity.AppLabel,
					field.Name,
					err,
				)
			}
			terminals := make([]projectRelationReverseTerminal, 0)
			for _, terminal := range source.model.Fields {
				if supportedProjectRelationQueryTerminal(terminal) {
					terminals = append(terminals, projectRelationReverseTerminal{field: terminal.Clone()})
				}
			}
			edgesByOwner[owner.identity] = append(edgesByOwner[owner.identity], projectRelationReverseEdge{
				name:      field.Relation.Reverse.Name,
				selector:  selector,
				source:    source,
				terminals: terminals,
			})
		}
	}

	owners := make([]projectRelationReverseOwner, 0, len(edgesByOwner))
	nextRelationBind := 0
	nextTerminalBind := 0
	for _, model := range models {
		relations := edgesByOwner[model.identity]
		if len(relations) == 0 {
			continue
		}
		sort.Slice(relations, func(left, right int) bool {
			if relations[left].name != relations[right].name {
				return relations[left].name < relations[right].name
			}
			if relations[left].source.identity.AppLabel != relations[right].source.identity.AppLabel {
				return relations[left].source.identity.AppLabel < relations[right].source.identity.AppLabel
			}
			return relations[left].source.identity.ModelName < relations[right].source.identity.ModelName
		})
		surface := model.app.prefix + model.model.GoName
		for index := range relations {
			relations[index].bind = nextRelationBind
			relations[index].typeName = surface + relations[index].selector + "ReverseRelation"
			nextRelationBind++
			for terminalIndex := range relations[index].terminals {
				relations[index].terminals[terminalIndex].bind = nextTerminalBind
				nextTerminalBind++
			}
		}
		owners = append(owners, projectRelationReverseOwner{
			model:         model,
			surface:       surface,
			relationsType: surface + "ReverseRelations",
			factoryType:   surface + "ReverseObjectFactory",
			objectType:    surface + "ReverseObject",
			relations:     relations,
		})
	}
	return models, owners, nil
}

func projectRelationReverseObjectOwners(owners []projectRelationReverseOwner) []projectRelationReverseOwner {
	return append([]projectRelationReverseOwner(nil), owners...)
}

func projectRelationReverseUsedModels(
	models []*projectRelationModel,
	owners []projectRelationReverseOwner,
) []*projectRelationModel {
	required := make(map[ir.ModelIdentity]struct{})
	for _, owner := range owners {
		required[owner.model.identity] = struct{}{}
		for _, relation := range owner.relations {
			required[relation.source.identity] = struct{}{}
		}
	}
	result := make([]*projectRelationModel, 0, len(required))
	for _, model := range models {
		if _, ok := required[model.identity]; ok {
			result = append(result, model)
		}
	}
	return result
}

func projectRelationReverseUsedApps(
	apps []normalizedRelationPackage,
	models []*projectRelationModel,
) []normalizedRelationPackage {
	required := make(map[string]struct{})
	for _, model := range models {
		required[model.app.schema.AppLabel] = struct{}{}
	}
	result := make([]normalizedRelationPackage, 0, len(required))
	for _, app := range apps {
		if _, ok := required[app.schema.AppLabel]; ok {
			result = append(result, app)
		}
	}
	return result
}

func relationReverseSelector(name string) (string, error) {
	if name == "" || strings.HasPrefix(name, "_") || strings.HasSuffix(name, "_") {
		return "", fmt.Errorf("reverse name %q is not strict lower-snake", name)
	}
	segments := strings.Split(name, "_")
	var result strings.Builder
	for _, segment := range segments {
		if segment == "" || segment == "init" || token.Lookup(segment).IsKeyword() {
			return "", fmt.Errorf("reverse name %q has an empty or reserved segment", name)
		}
		if segment[0] < 'a' || segment[0] > 'z' {
			return "", fmt.Errorf("reverse name %q has a non-lowercase segment", name)
		}
		for index := 1; index < len(segment); index++ {
			current := segment[index]
			if !('a' <= current && current <= 'z') && !('0' <= current && current <= '9') {
				return "", fmt.Errorf("reverse name %q is not ASCII lower-snake", name)
			}
		}
		result.WriteByte(segment[0] - 'a' + 'A')
		result.WriteString(segment[1:])
	}
	selector := result.String()
	if selector == "" || !token.IsIdentifier(selector) {
		return "", fmt.Errorf("reverse name %q has no generated selector", name)
	}
	return selector, nil
}

func renderProjectRelationReverseTypes(output *bytes.Buffer, owner projectRelationReverseOwner) {
	ownerType := owner.model.app.alias + "." + owner.model.model.GoName
	for _, relation := range owner.relations {
		fmt.Fprintf(output, "type %s struct {\n", relation.typeName)
		for _, terminal := range relation.terminals {
			fieldType := "orm.RelatedStringField"
			if terminal.field.Kind == ir.FieldAuto {
				fieldType = "orm.RelatedIntegerField"
			}
			fmt.Fprintf(output, "\t%s %s[%s]\n", terminal.field.GoName, fieldType, ownerType)
		}
		fmt.Fprintln(output, "}")
		fmt.Fprintln(output)
	}
	fmt.Fprintf(output, "type %s struct {\n", owner.relationsType)
	for _, relation := range owner.relations {
		fmt.Fprintf(output, "\t%s %s\n", relation.selector, relation.typeName)
	}
	fmt.Fprintf(output, "\tmodel orm.BoundModel[%s]\n", ownerType)
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(output, "func (_relations %s) ParseDynamic(\n", owner.relationsType)
	fmt.Fprintln(output, "\t_policy orm.LookupPolicy,")
	fmt.Fprintln(output, "\t_inputs []orm.LookupInput,")
	fmt.Fprintf(output, ") ([]orm.Predicate[%s], error) {\n", ownerType)
	fmt.Fprintln(output, "\treturn orm.ParseDynamicReverseRelations(_relations.model, _policy, _inputs)")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
}

func renderProjectRelationReversePrerequisiteAssertions(
	output *bytes.Buffer,
	models []*projectRelationModel,
	objectOwners []projectRelationReverseOwner,
) {
	if len(models) == 0 {
		return
	}
	primaryKeyOwners := make(map[ir.ModelIdentity]struct{}, len(objectOwners))
	for _, owner := range objectOwners {
		primaryKeyOwners[owner.model.identity] = struct{}{}
	}
	for _, model := range models {
		modelType := model.app.alias + "." + model.model.GoName
		descriptor := model.app.alias + "." + model.model.GoName + "Descriptor{}"
		fmt.Fprintf(output, "var _ orm.RelationObjectDescriptor[%s] = %s\n", modelType, descriptor)
		if _, ok := primaryKeyOwners[model.identity]; ok {
			fmt.Fprintf(output, "var _ orm.PrimaryKeyObjectDescriptor[%s] = %s\n", modelType, descriptor)
		}
	}
	fmt.Fprintln(output)
}

func renderBindReverseRelations(
	output *bytes.Buffer,
	models []*projectRelationModel,
	owners []projectRelationReverseOwner,
) {
	fmt.Fprintln(output, "func BindReverseRelations() (ReverseRelations, error) {")
	if len(owners) == 0 {
		fmt.Fprintln(output, "\tif _, _err := Bind(); _err != nil {")
		fmt.Fprintln(output, "\t\treturn ReverseRelations{}, _err")
		fmt.Fprintln(output, "\t}")
		fmt.Fprintln(output, "\treturn ReverseRelations{}, nil")
		fmt.Fprintln(output, "}")
		return
	}
	renderProjectModelBindings(output, models, "ReverseRelations", nil)
	for _, owner := range owners {
		for _, relation := range owner.relations {
			fmt.Fprintf(
				output,
				"\t_relation%d, _err := orm.BindReverse(_model%d, %s, _model%d)\n",
				relation.bind,
				owner.model.bind,
				strconv.Quote(relation.name),
				relation.source.bind,
			)
			fmt.Fprintln(output, "\tif _err != nil {")
			fmt.Fprintln(output, "\t\treturn ReverseRelations{}, _err")
			fmt.Fprintln(output, "\t}")
			for _, terminal := range relation.terminals {
				method := "String"
				if terminal.field.Kind == ir.FieldAuto {
					method = "Integer"
				}
				fmt.Fprintf(
					output,
					"\t_terminal%d, _err := _relation%d.%s(%s.%sFields.%s)\n",
					terminal.bind,
					relation.bind,
					method,
					relation.source.app.alias,
					relation.source.model.GoName,
					terminal.field.GoName,
				)
				fmt.Fprintln(output, "\tif _err != nil {")
				fmt.Fprintln(output, "\t\treturn ReverseRelations{}, _err")
				fmt.Fprintln(output, "\t}")
			}
		}
	}
	fmt.Fprintln(output, "\treturn ReverseRelations{")
	for _, owner := range owners {
		fmt.Fprintf(output, "\t\t%s: %s{\n", owner.surface, owner.relationsType)
		for _, relation := range owner.relations {
			fmt.Fprintf(output, "\t\t\t%s: %s{\n", relation.selector, relation.typeName)
			for _, terminal := range relation.terminals {
				fmt.Fprintf(output, "\t\t\t\t%s: _terminal%d,\n", terminal.field.GoName, terminal.bind)
			}
			fmt.Fprintln(output, "\t\t\t},")
		}
		fmt.Fprintf(output, "\t\t\tmodel: _model%d,\n", owner.model.bind)
		fmt.Fprintln(output, "\t\t},")
	}
	fmt.Fprintln(output, "\t}, nil")
	fmt.Fprintln(output, "}")
}

func renderProjectRelationReverseObjectTypes(output *bytes.Buffer, owner projectRelationReverseOwner) {
	ownerType := owner.model.app.alias + "." + owner.model.model.GoName
	fmt.Fprintf(output, "type %s struct {\n", owner.factoryType)
	for _, relation := range owner.relations {
		fmt.Fprintf(
			output,
			"\t%s orm.ReverseObject[%s, %s.%s]\n",
			lowerFirst(relation.selector),
			ownerType,
			relation.source.app.alias,
			relation.source.model.GoName,
		)
	}
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(output, "func (_factory %s) From(_backend db.Queryer, _value %s) (*%s, error) {\n", owner.factoryType, ownerType, owner.objectType)
	fmt.Fprintf(output, "\t_snapshot := (%s.%sDescriptor{}).CloneModel(_value)\n", owner.model.app.alias, owner.model.model.GoName)
	for _, relation := range owner.relations {
		fmt.Fprintf(output, "\t_related%d, _err := _factory.%s.From(_backend, _snapshot)\n", relation.bind, lowerFirst(relation.selector))
		fmt.Fprintln(output, "\tif _err != nil {")
		fmt.Fprintln(output, "\t\treturn nil, _err")
		fmt.Fprintln(output, "\t}")
	}
	fmt.Fprintf(output, "\t_result := &%s{\n", owner.objectType)
	fmt.Fprintln(output, "\t\tmodel:   _snapshot,")
	fmt.Fprintln(output, "\t\tfactory: _factory,")
	fmt.Fprintln(output, "\t\tbackend: _backend,")
	for _, relation := range owner.relations {
		fmt.Fprintf(output, "\t\t%s: _related%d,\n", lowerFirst(relation.selector), relation.bind)
	}
	fmt.Fprintln(output, "\t}")
	fmt.Fprintln(output, "\t_result._self = _result")
	fmt.Fprintln(output, "\treturn _result, nil")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	fmt.Fprintf(output, "type %s struct {\n", owner.objectType)
	fmt.Fprintf(output, "\tmodel %s\n", ownerType)
	fmt.Fprintf(output, "\tfactory %s\n", owner.factoryType)
	fmt.Fprintln(output, "\tbackend db.Queryer")
	for _, relation := range owner.relations {
		fmt.Fprintf(
			output,
			"\t%s *orm.RelatedSet[%s.%s]\n",
			lowerFirst(relation.selector),
			relation.source.app.alias,
			relation.source.model.GoName,
		)
	}
	fmt.Fprintf(output, "\t_self *%s\n", owner.objectType)
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(output, "func (_object *%s) _validate() error {\n", owner.objectType)
	fmt.Fprintln(output, "\tif _object == nil || _object._self != _object {")
	fmt.Fprintln(output, "\t\treturn &query.Error{")
	fmt.Fprintln(output, "\t\t\tCategory: query.CategoryQuery,")
	fmt.Fprintln(output, "\t\t\tCode:     query.CodeInvalidPlan,")
	fmt.Fprintln(output, "\t\t\tDetail:   \"generated reverse relation object is nil, zero, or copied\",")
	fmt.Fprintln(output, "\t\t}")
	fmt.Fprintln(output, "\t}")
	fmt.Fprintln(output, "\treturn nil")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(output, "func (_object *%s) Model() (%s, error) {\n", owner.objectType, ownerType)
	fmt.Fprintln(output, "\tif _err := _object._validate(); _err != nil {")
	fmt.Fprintf(output, "\t\treturn %s{}, _err\n", ownerType)
	fmt.Fprintln(output, "\t}")
	fmt.Fprintf(output, "\treturn (%s.%sDescriptor{}).CloneModel(_object.model), nil\n", owner.model.app.alias, owner.model.model.GoName)
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	for _, relation := range owner.relations {
		setType := "*orm.RelatedSet[" + relation.source.app.alias + "." + relation.source.model.GoName + "]"
		fmt.Fprintf(output, "func (_object *%s) %s() (%s, error) {\n", owner.objectType, relation.selector, setType)
		fmt.Fprintln(output, "\tif _err := _object._validate(); _err != nil {")
		fmt.Fprintln(output, "\t\treturn nil, _err")
		fmt.Fprintln(output, "\t}")
		fmt.Fprintf(output, "\treturn _object.%s, nil\n", lowerFirst(relation.selector))
		fmt.Fprintln(output, "}")
		fmt.Fprintln(output)
	}
	fmt.Fprintf(output, "func (_object *%s) Fresh() (*%s, error) {\n", owner.objectType, owner.objectType)
	fmt.Fprintln(output, "\tif _err := _object._validate(); _err != nil {")
	fmt.Fprintln(output, "\t\treturn nil, _err")
	fmt.Fprintln(output, "\t}")
	fmt.Fprintln(output, "\treturn _object.factory.From(_object.backend, _object.model)")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
}

func renderBindReverseObjects(
	output *bytes.Buffer,
	models []*projectRelationModel,
	owners []projectRelationReverseOwner,
) {
	fmt.Fprintln(output, "func BindReverseObjects() (ReverseObjects, error) {")
	if len(owners) == 0 {
		fmt.Fprintln(output, "\tif _, _err := Bind(); _err != nil {")
		fmt.Fprintln(output, "\t\treturn ReverseObjects{}, _err")
		fmt.Fprintln(output, "\t}")
		fmt.Fprintln(output, "\treturn ReverseObjects{}, nil")
		fmt.Fprintln(output, "}")
		return
	}
	renderProjectModelBindings(output, models, "ReverseObjects", nil)
	for _, owner := range owners {
		for _, relation := range owner.relations {
			fmt.Fprintf(
				output,
				"\t_relation%d, _err := orm.BindReverseObject(_model%d, %s, _model%d)\n",
				relation.bind,
				owner.model.bind,
				strconv.Quote(relation.name),
				relation.source.bind,
			)
			fmt.Fprintln(output, "\tif _err != nil {")
			fmt.Fprintln(output, "\t\treturn ReverseObjects{}, _err")
			fmt.Fprintln(output, "\t}")
		}
	}
	fmt.Fprintln(output, "\treturn ReverseObjects{")
	for _, owner := range owners {
		fmt.Fprintf(output, "\t\t%s: %s{\n", owner.surface, owner.factoryType)
		for _, relation := range owner.relations {
			fmt.Fprintf(output, "\t\t\t%s: _relation%d,\n", lowerFirst(relation.selector), relation.bind)
		}
		fmt.Fprintln(output, "\t\t},")
	}
	fmt.Fprintln(output, "\t}, nil")
	fmt.Fprintln(output, "}")
}
