package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"sort"
	"strconv"

	"github.com/progresshans/godj/schema/ir"
)

const ProjectRelationObjectGeneratorVersion = "godj-codegen-rel-object-project-v1"

type RelationObjectPackage struct {
	Alias      string
	ImportPath string
	Schema     ir.Schema
}

type normalizedRelationObjectPackage struct {
	alias      string
	prefix     string
	importPath string
	schema     ir.Schema
}

type projectRelationObjectModel struct {
	app      normalizedRelationObjectPackage
	identity ir.ModelIdentity
	model    ir.Model
	bind     int
}

type projectRelationObjectEdge struct {
	field    ir.Field
	selector string
	typeName string
	target   *projectRelationObjectModel
	bind     int
}

type projectRelationObjectSource struct {
	model       *projectRelationObjectModel
	surface     string
	factoryType string
	objectType  string
	relations   []projectRelationObjectEdge
}

// GenerateProjectRelationObject renders project-owned concrete relation-object
// wiring. Generated app packages remain independent: only this project package
// imports both a source and its target.
func GenerateProjectRelationObject(packageName string, packages []RelationObjectPackage) ([]byte, error) {
	if !validGeneratedPackageName(packageName) {
		return nil, fmt.Errorf("invalid generated package name %q", packageName)
	}
	canonical, err := canonicalRelationObjectPackages(packages)
	if err != nil {
		return nil, err
	}
	models, sources, err := buildProjectRelationObjectSurface(canonical)
	if err != nil {
		return nil, err
	}
	if err := validateProjectRelationObjectNamespaces(canonical, sources); err != nil {
		return nil, fmt.Errorf("validate project relation object names: %w", err)
	}

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by GoDj. DO NOT EDIT.")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "package %s\n\n", packageName)
	if len(models) > 0 {
		fmt.Fprintln(&output, "import (")
		if len(sources) > 0 {
			fmt.Fprintln(&output, "\tcontext \"context\"")
		}
		for _, app := range canonical {
			fmt.Fprintf(&output, "\t%s %s\n", app.alias, strconv.Quote(app.importPath))
		}
		if len(sources) > 0 {
			fmt.Fprintln(&output, "\tdb \"github.com/progresshans/godj/db\"")
		}
		fmt.Fprintln(&output, "\torm \"github.com/progresshans/godj/orm\"")
		fmt.Fprintln(&output, "\tir \"github.com/progresshans/godj/schema/ir\"")
		if len(sources) > 0 {
			fmt.Fprintln(&output, "\tquery \"github.com/progresshans/godj/query\"")
		}
		fmt.Fprintln(&output, ")")
		fmt.Fprintln(&output)
	}
	fmt.Fprintf(
		&output,
		"const GoDjProjectRelationObjectGeneratorVersion = %s\n\n",
		strconv.Quote(ProjectRelationObjectGeneratorVersion),
	)

	for _, source := range sources {
		renderProjectRelationObjectTypes(&output, source)
	}
	fmt.Fprintln(&output, "type Objects struct {")
	for _, source := range sources {
		fmt.Fprintf(&output, "\t%s %s\n", source.surface, source.factoryType)
	}
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)
	renderBindObjects(&output, models, sources)

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated project relation object bridge: %w", err)
	}
	return formatted, nil
}

func canonicalRelationObjectPackages(packages []RelationObjectPackage) ([]normalizedRelationObjectPackage, error) {
	canonical := make([]normalizedRelationObjectPackage, len(packages))
	for index := range packages {
		candidate := packages[index]
		schema, err := ir.Normalize(candidate.Schema.Clone())
		if err != nil {
			return nil, fmt.Errorf("normalize relation object package %q: %w", candidate.Alias, err)
		}
		switch schema.FormatVersion {
		case ir.FormatVersion:
			if err := validateGeneratedNames(schema); err != nil {
				return nil, fmt.Errorf("validate scalar object package %q: %w", candidate.Alias, err)
			}
			if err := validateRelationMetadataNames(schema); err != nil {
				return nil, fmt.Errorf("validate scalar object metadata package %q: %w", candidate.Alias, err)
			}
		case ir.RelationFormatVersion:
			if err := validateRelationQueryNames(schema); err != nil {
				return nil, fmt.Errorf("validate relation object package %q: %w", candidate.Alias, err)
			}
		default:
			return nil, fmt.Errorf("relation object package %q has unsupported format version %d", candidate.Alias, schema.FormatVersion)
		}
		if err := validateRelationObjectNames(schema); err != nil {
			return nil, fmt.Errorf("validate relation object companion package %q: %w", candidate.Alias, err)
		}
		if !validRelationObjectAlias(candidate.Alias) {
			return nil, fmt.Errorf("invalid relation object package alias %q", candidate.Alias)
		}
		if !validImportPath(candidate.ImportPath) {
			return nil, fmt.Errorf("invalid relation object import path %q", candidate.ImportPath)
		}
		canonical[index] = normalizedRelationObjectPackage{
			alias:      candidate.Alias,
			prefix:     exportedRelationQueryPrefix(candidate.Alias),
			importPath: candidate.ImportPath,
			schema:     schema,
		}
	}

	sort.Slice(canonical, func(left, right int) bool {
		if canonical[left].schema.AppLabel != canonical[right].schema.AppLabel {
			return canonical[left].schema.AppLabel < canonical[right].schema.AppLabel
		}
		if canonical[left].alias != canonical[right].alias {
			return canonical[left].alias < canonical[right].alias
		}
		return canonical[left].importPath < canonical[right].importPath
	})

	aliases := map[string]struct{}{
		"context": {},
		"db":      {},
		"orm":     {},
		"ir":      {},
		"query":   {},
	}
	paths := map[string]struct{}{
		"context":                                {},
		"github.com/progresshans/godj/db":        {},
		"github.com/progresshans/godj/orm":       {},
		"github.com/progresshans/godj/query":     {},
		"github.com/progresshans/godj/schema/ir": {},
	}
	prefixes := make(map[string]struct{}, len(canonical))
	apps := make(map[string]struct{}, len(canonical))
	for _, app := range canonical {
		if _, duplicate := aliases[app.alias]; duplicate {
			return nil, fmt.Errorf("duplicate relation object package alias %q", app.alias)
		}
		aliases[app.alias] = struct{}{}
		if _, duplicate := paths[app.importPath]; duplicate {
			return nil, fmt.Errorf("duplicate relation object import path %q", app.importPath)
		}
		paths[app.importPath] = struct{}{}
		if _, duplicate := prefixes[app.prefix]; duplicate {
			return nil, fmt.Errorf("duplicate relation object exported prefix %q", app.prefix)
		}
		prefixes[app.prefix] = struct{}{}
		if _, duplicate := apps[app.schema.AppLabel]; duplicate {
			return nil, fmt.Errorf("duplicate relation object app label %q", app.schema.AppLabel)
		}
		apps[app.schema.AppLabel] = struct{}{}
	}
	return canonical, nil
}

func validRelationObjectAlias(alias string) bool {
	if alias == "" || alias == "init" || alias == "context" || alias == "db" || alias == "orm" || alias == "ir" ||
		alias == "query" || alias == "bool" || alias == "error" || alias == "false" || alias == "nil" ||
		token.Lookup(alias).IsKeyword() || alias[0] < 'a' || alias[0] > 'z' {
		return false
	}
	for index := 1; index < len(alias); index++ {
		current := alias[index]
		if !('a' <= current && current <= 'z') &&
			!('A' <= current && current <= 'Z') &&
			!('0' <= current && current <= '9') {
			return false
		}
	}
	return true
}

func buildProjectRelationObjectSurface(
	apps []normalizedRelationObjectPackage,
) ([]*projectRelationObjectModel, []projectRelationObjectSource, error) {
	models := make([]*projectRelationObjectModel, 0)
	byIdentity := make(map[ir.ModelIdentity]*projectRelationObjectModel)
	for _, app := range apps {
		for _, model := range app.schema.Models {
			identity := ir.ModelIdentity{AppLabel: app.schema.AppLabel, ModelName: model.Name}
			candidate := &projectRelationObjectModel{app: app, identity: identity, model: model.Clone()}
			models = append(models, candidate)
			byIdentity[identity] = candidate
		}
	}
	sort.Slice(models, func(left, right int) bool {
		if models[left].identity.AppLabel != models[right].identity.AppLabel {
			return models[left].identity.AppLabel < models[right].identity.AppLabel
		}
		return models[left].identity.ModelName < models[right].identity.ModelName
	})
	for index := range models {
		models[index].bind = index
	}

	sources := make([]projectRelationObjectSource, 0)
	nextRelationBind := 0
	for _, sourceModel := range models {
		relations := make([]projectRelationObjectEdge, 0)
		for _, field := range sourceModel.model.Fields {
			if field.Relation == nil {
				continue
			}
			selector, err := relationQuerySelector(field)
			if err != nil {
				return nil, nil, fmt.Errorf(
					"derive relation object selector for %s.%s: %w",
					sourceModel.identity.AppLabel,
					sourceModel.identity.ModelName,
					err,
				)
			}
			target, ok := byIdentity[field.Relation.Target]
			if !ok {
				return nil, nil, fmt.Errorf(
					"resolve relation object target %s.%s for %s.%s",
					field.Relation.Target.AppLabel,
					field.Relation.Target.ModelName,
					sourceModel.identity.AppLabel,
					field.Name,
				)
			}
			if _, ok := projectRelationObjectAutoPrimaryKey(target.model); !ok {
				return nil, nil, fmt.Errorf(
					"relation object target %s.%s does not have exactly one non-null AutoField primary key",
					target.identity.AppLabel,
					target.identity.ModelName,
				)
			}
			surface := sourceModel.app.prefix + sourceModel.model.GoName
			typeName := ""
			if field.Nullable {
				typeName = surface + selector + "ObjectRelation"
			}
			relations = append(relations, projectRelationObjectEdge{
				field:    field.Clone(),
				selector: selector,
				typeName: typeName,
				target:   target,
			})
		}
		if len(relations) == 0 {
			continue
		}
		sort.Slice(relations, func(left, right int) bool {
			if relations[left].field.Name != relations[right].field.Name {
				return relations[left].field.Name < relations[right].field.Name
			}
			return relations[left].selector < relations[right].selector
		})
		for index := range relations {
			relations[index].bind = nextRelationBind
			nextRelationBind++
		}
		surface := sourceModel.app.prefix + sourceModel.model.GoName
		sources = append(sources, projectRelationObjectSource{
			model:       sourceModel,
			surface:     surface,
			factoryType: surface + "ObjectFactory",
			objectType:  surface + "Object",
			relations:   relations,
		})
	}
	return models, sources, nil
}

func projectRelationObjectAutoPrimaryKey(model ir.Model) (ir.Field, bool) {
	var result ir.Field
	found := false
	for _, field := range model.Fields {
		if !field.PrimaryKey {
			continue
		}
		if found || field.Kind != ir.FieldAuto || field.Nullable || field.Relation != nil {
			return ir.Field{}, false
		}
		result = field.Clone()
		found = true
	}
	return result, found
}

func validateProjectRelationObjectNamespaces(
	apps []normalizedRelationObjectPackage,
	sources []projectRelationObjectSource,
) error {
	packageNames := map[string]string{
		"GoDjProjectBindingGeneratorVersion": "project binding provenance constant",
		"Bind":                               "project binding function",
		"GoDjProjectRelationQueryGeneratorVersion": "project relation query provenance constant",
		"Relations":     "project relation query aggregate",
		"BindRelations": "project relation query binding function",
		"GoDjProjectRelationObjectGeneratorVersion": "project relation object provenance constant",
		"Objects":     "project relation object aggregate",
		"BindObjects": "project relation object binding function",
	}
	addPackageName := func(name, owner string) error {
		if previous, duplicate := packageNames[name]; duplicate {
			return fmt.Errorf("package symbol %s for %s conflicts with %s", name, owner, previous)
		}
		packageNames[name] = owner
		return nil
	}
	for _, app := range apps {
		if previous, collision := packageNames[app.alias]; collision {
			return fmt.Errorf("import alias %s conflicts with %s", app.alias, previous)
		}
	}
	// The immutable project relation-query v1 companion is published in the
	// same package. Seed every declaration it would emit so the additive object
	// generator fails before returning bytes on an old/new union collision.
	for _, source := range sources {
		owner := source.model.identity.AppLabel + "." + source.model.identity.ModelName
		hasRequired := false
		for _, relation := range source.relations {
			if relation.field.Nullable {
				continue
			}
			hasRequired = true
			name := source.surface + relation.selector + "Relation"
			if err := addPackageName(name, "existing required relation "+owner+"."+relation.field.Name); err != nil {
				return err
			}
		}
		if hasRequired {
			if err := addPackageName(source.surface+"Relations", "existing relations for "+owner); err != nil {
				return err
			}
		}
	}

	aggregateFields := make(map[string]string, len(sources))
	for _, source := range sources {
		owner := source.model.identity.AppLabel + "." + source.model.identity.ModelName
		if err := addPackageName(source.factoryType, "object factory for "+owner); err != nil {
			return err
		}
		if err := addPackageName(source.objectType, "object wrapper for "+owner); err != nil {
			return err
		}
		if previous, duplicate := aggregateFields[source.surface]; duplicate {
			return fmt.Errorf("Objects field %s for %s conflicts with %s", source.surface, owner, previous)
		}
		aggregateFields[source.surface] = owner

		wrapperMethods := map[string]string{
			"Model": "generated Model method",
			"Fresh": "generated Fresh method",
		}
		factoryFields := map[string]string{
			"From":         "generated From method",
			"ParseDynamic": "generated ParseDynamic method",
		}
		privateFields := map[string]string{
			"model":   "generated model field",
			"factory": "generated factory field",
			"backend": "generated backend field",
			"_self":   "generated self sentinel",
		}
		for _, relation := range source.relations {
			if previous, duplicate := wrapperMethods[relation.selector]; duplicate {
				return fmt.Errorf("object method %s for %s.%s conflicts with %s", relation.selector, owner, relation.field.Name, previous)
			}
			wrapperMethods[relation.selector] = relation.field.Name
			private := lowerFirst(relation.selector)
			if previous, duplicate := privateFields[private]; duplicate {
				return fmt.Errorf("private object field %s for %s.%s conflicts with %s", private, owner, relation.field.Name, previous)
			}
			privateFields[private] = relation.field.Name
			if !relation.field.Nullable {
				continue
			}
			if err := addPackageName(relation.typeName, "nullable relation "+owner+"."+relation.field.Name); err != nil {
				return err
			}
			if previous, duplicate := factoryFields[relation.selector]; duplicate {
				return fmt.Errorf("object factory field %s for %s.%s conflicts with %s", relation.selector, owner, relation.field.Name, previous)
			}
			factoryFields[relation.selector] = relation.field.Name
		}
	}
	return nil
}

func renderProjectRelationObjectTypes(output *bytes.Buffer, source projectRelationObjectSource) {
	sourceType := source.model.app.alias + "." + source.model.model.GoName
	for _, relation := range source.relations {
		if !relation.field.Nullable {
			continue
		}
		targetType := relation.target.app.alias + "." + relation.target.model.GoName
		fmt.Fprintf(output, "type %s struct {\n", relation.typeName)
		fmt.Fprintf(output, "\trelation orm.NullableForwardObject[%s, %s]\n", sourceType, targetType)
		fmt.Fprintln(output, "}")
		fmt.Fprintln(output)
		fmt.Fprintf(output, "func (_relation %s) IsNull(_value bool) orm.Predicate[%s] {\n", relation.typeName, sourceType)
		fmt.Fprintln(output, "\treturn _relation.relation.IsNull(_value)")
		fmt.Fprintln(output, "}")
		fmt.Fprintln(output)
	}

	fmt.Fprintf(output, "type %s struct {\n", source.factoryType)
	for _, relation := range source.relations {
		if relation.field.Nullable {
			fmt.Fprintf(output, "\t%s %s\n", relation.selector, relation.typeName)
		}
	}
	fmt.Fprintf(output, "\tmodel orm.BoundModel[%s]\n", sourceType)
	for _, relation := range source.relations {
		targetType := relation.target.app.alias + "." + relation.target.model.GoName
		handle := "orm.RequiredForwardObject"
		if relation.field.Nullable {
			handle = "orm.NullableForwardObject"
		}
		fmt.Fprintf(output, "\t%s %s[%s, %s]\n", lowerFirst(relation.selector), handle, sourceType, targetType)
	}
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(output, "func (_factory %s) ParseDynamic(\n", source.factoryType)
	fmt.Fprintln(output, "\t_policy orm.LookupPolicy,")
	fmt.Fprintln(output, "\t_inputs []orm.LookupInput,")
	fmt.Fprintf(output, ") ([]orm.Predicate[%s], error) {\n", sourceType)
	fmt.Fprintln(output, "\treturn orm.ParseDynamicRelationObjects(_factory.model, _policy, _inputs)")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(output, "func (_factory %s) From(_backend db.Queryer, _value %s) (*%s, error) {\n", source.factoryType, sourceType, source.objectType)
	fmt.Fprintf(output, "\t_snapshot := (%s.%sDescriptor{}).CloneModel(_value)\n", source.model.app.alias, source.model.model.GoName)
	for _, relation := range source.relations {
		fmt.Fprintf(output, "\t_related%d, _err := _factory.%s.From(_backend, _snapshot)\n", relation.bind, lowerFirst(relation.selector))
		fmt.Fprintln(output, "\tif _err != nil {")
		fmt.Fprintln(output, "\t\treturn nil, _err")
		fmt.Fprintln(output, "\t}")
	}
	fmt.Fprintf(output, "\t_result := &%s{\n", source.objectType)
	fmt.Fprintln(output, "\t\tmodel:   _snapshot,")
	fmt.Fprintln(output, "\t\tfactory: _factory,")
	fmt.Fprintln(output, "\t\tbackend: _backend,")
	for _, relation := range source.relations {
		fmt.Fprintf(output, "\t\t%s: _related%d,\n", lowerFirst(relation.selector), relation.bind)
	}
	fmt.Fprintln(output, "\t}")
	fmt.Fprintln(output, "\t_result._self = _result")
	fmt.Fprintln(output, "\treturn _result, nil")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	fmt.Fprintf(output, "type %s struct {\n", source.objectType)
	fmt.Fprintf(output, "\tmodel %s\n", sourceType)
	fmt.Fprintf(output, "\tfactory %s\n", source.factoryType)
	fmt.Fprintln(output, "\tbackend db.Queryer")
	for _, relation := range source.relations {
		targetType := relation.target.app.alias + "." + relation.target.model.GoName
		fmt.Fprintf(output, "\t%s *orm.RelatedObject[%s]\n", lowerFirst(relation.selector), targetType)
	}
	fmt.Fprintf(output, "\t_self *%s\n", source.objectType)
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(output, "func (_object *%s) _validate() error {\n", source.objectType)
	fmt.Fprintln(output, "\tif _object == nil || _object._self != _object {")
	fmt.Fprintln(output, "\t\treturn &query.Error{")
	fmt.Fprintln(output, "\t\t\tCategory: query.CategoryQuery,")
	fmt.Fprintln(output, "\t\t\tCode:     query.CodeInvalidPlan,")
	fmt.Fprintln(output, "\t\t\tDetail:   \"generated relation object is nil, zero, or copied\",")
	fmt.Fprintln(output, "\t\t}")
	fmt.Fprintln(output, "\t}")
	fmt.Fprintln(output, "\treturn nil")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(output, "func (_object *%s) Model() (%s, error) {\n", source.objectType, sourceType)
	fmt.Fprintln(output, "\tif _err := _object._validate(); _err != nil {")
	fmt.Fprintf(output, "\t\treturn %s{}, _err\n", sourceType)
	fmt.Fprintln(output, "\t}")
	fmt.Fprintf(output, "\treturn (%s.%sDescriptor{}).CloneModel(_object.model), nil\n", source.model.app.alias, source.model.model.GoName)
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	for _, relation := range source.relations {
		targetType := relation.target.app.alias + "." + relation.target.model.GoName
		private := lowerFirst(relation.selector)
		if relation.field.Nullable {
			fmt.Fprintf(output, "func (_object *%s) %s(_ctx context.Context) (%s, bool, error) {\n", source.objectType, relation.selector, targetType)
			fmt.Fprintln(output, "\tif _err := _object._validate(); _err != nil {")
			fmt.Fprintf(output, "\t\treturn %s{}, false, _err\n", targetType)
			fmt.Fprintln(output, "\t}")
			fmt.Fprintf(output, "\treturn _object.%s.Get(_ctx)\n", private)
			fmt.Fprintln(output, "}")
			fmt.Fprintln(output)
			continue
		}
		fmt.Fprintf(output, "func (_object *%s) %s(_ctx context.Context) (%s, error) {\n", source.objectType, relation.selector, targetType)
		fmt.Fprintln(output, "\tif _err := _object._validate(); _err != nil {")
		fmt.Fprintf(output, "\t\treturn %s{}, _err\n", targetType)
		fmt.Fprintln(output, "\t}")
		fmt.Fprintf(output, "\t_value, _ok, _err := _object.%s.Get(_ctx)\n", private)
		fmt.Fprintln(output, "\tif _err != nil {")
		fmt.Fprintf(output, "\t\treturn %s{}, _err\n", targetType)
		fmt.Fprintln(output, "\t}")
		fmt.Fprintln(output, "\tif !_ok {")
		fmt.Fprintf(output, "\t\treturn %s{}, &query.Error{\n", targetType)
		fmt.Fprintln(output, "\t\t\tCategory: query.CategoryQuery,")
		fmt.Fprintln(output, "\t\t\tCode:     query.CodeInvalidPlan,")
		fmt.Fprintln(output, "\t\t\tDetail:   \"required relation object returned an absent result\",")
		fmt.Fprintln(output, "\t\t}")
		fmt.Fprintln(output, "\t}")
		fmt.Fprintln(output, "\treturn _value, nil")
		fmt.Fprintln(output, "}")
		fmt.Fprintln(output)
	}
	fmt.Fprintf(output, "func (_object *%s) Fresh() (*%s, error) {\n", source.objectType, source.objectType)
	fmt.Fprintln(output, "\tif _err := _object._validate(); _err != nil {")
	fmt.Fprintln(output, "\t\treturn nil, _err")
	fmt.Fprintln(output, "\t}")
	fmt.Fprintln(output, "\treturn _object.factory.From(_object.backend, _object.model)")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
}

func renderBindObjects(
	output *bytes.Buffer,
	models []*projectRelationObjectModel,
	sources []projectRelationObjectSource,
) {
	fmt.Fprintln(output, "func BindObjects() (Objects, error) {")
	if len(models) == 0 {
		fmt.Fprintln(output, "\tif _, _err := Bind(); _err != nil {")
		fmt.Fprintln(output, "\t\treturn Objects{}, _err")
		fmt.Fprintln(output, "\t}")
		fmt.Fprintln(output, "\treturn Objects{}, nil")
		fmt.Fprintln(output, "}")
		return
	}
	fmt.Fprintln(output, "\t_binding, _err := Bind()")
	fmt.Fprintln(output, "\tif _err != nil {")
	fmt.Fprintln(output, "\t\treturn Objects{}, _err")
	fmt.Fprintln(output, "\t}")
	usedModels := make(map[int]struct{}, len(models))
	for _, source := range sources {
		usedModels[source.model.bind] = struct{}{}
		for _, relation := range source.relations {
			usedModels[relation.target.bind] = struct{}{}
		}
	}
	for _, model := range models {
		fmt.Fprintf(output, "\t_model%d, _err := orm.BindModel(\n", model.bind)
		fmt.Fprintln(output, "\t\t_binding,")
		fmt.Fprintf(
			output,
			"\t\tir.ModelIdentity{AppLabel: %s, ModelName: %s},\n",
			strconv.Quote(model.identity.AppLabel),
			strconv.Quote(model.identity.ModelName),
		)
		fmt.Fprintf(output, "\t\t%s.%sDescriptor{},\n", model.app.alias, model.model.GoName)
		fmt.Fprintln(output, "\t)")
		fmt.Fprintln(output, "\tif _err != nil {")
		fmt.Fprintln(output, "\t\treturn Objects{}, _err")
		fmt.Fprintln(output, "\t}")
		if _, used := usedModels[model.bind]; !used {
			fmt.Fprintf(output, "\t_ = _model%d\n", model.bind)
		}
	}
	for _, source := range sources {
		for _, relation := range source.relations {
			binder := "orm.BindRequiredForwardObject"
			if relation.field.Nullable {
				binder = "orm.BindNullableForwardObject"
			}
			fmt.Fprintf(
				output,
				"\t_relation%d, _err := %s(_model%d, %s, _model%d)\n",
				relation.bind,
				binder,
				source.model.bind,
				strconv.Quote(relation.field.Name),
				relation.target.bind,
			)
			fmt.Fprintln(output, "\tif _err != nil {")
			fmt.Fprintln(output, "\t\treturn Objects{}, _err")
			fmt.Fprintln(output, "\t}")
		}
	}
	if len(sources) == 0 {
		fmt.Fprintln(output, "\treturn Objects{}, nil")
		fmt.Fprintln(output, "}")
		return
	}
	fmt.Fprintln(output, "\treturn Objects{")
	for _, source := range sources {
		fmt.Fprintf(output, "\t\t%s: %s{\n", source.surface, source.factoryType)
		for _, relation := range source.relations {
			if relation.field.Nullable {
				fmt.Fprintf(output, "\t\t\t%s: %s{relation: _relation%d},\n", relation.selector, relation.typeName, relation.bind)
			}
		}
		fmt.Fprintf(output, "\t\t\tmodel: _model%d,\n", source.model.bind)
		for _, relation := range source.relations {
			fmt.Fprintf(output, "\t\t\t%s: _relation%d,\n", lowerFirst(relation.selector), relation.bind)
		}
		fmt.Fprintln(output, "\t\t},")
	}
	fmt.Fprintln(output, "\t}, nil")
	fmt.Fprintln(output, "}")
}
