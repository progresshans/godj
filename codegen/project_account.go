package codegen

import (
	"bytes"
	"fmt"
	"strconv"

	"github.com/progresshans/godj/schema/ir"
)

const ProjectAccountGeneratorVersion = "godj-codegen-account-project-v7"

func generateProjectAccount(input normalizedProjectSpec, plan *relationProjectPlan) ([]byte, error) {
	if input.account == nil {
		return []byte(fmt.Sprintf("// Code generated by GoDj. DO NOT EDIT.\n\npackage %s\n\nconst GoDjProjectAccountGeneratorVersion = %q\n", input.project.PackageName, ProjectAccountGeneratorVersion)), nil
	}
	role := *input.account
	resolve := func(identity ir.ModelIdentity) (preparedProjectApp, ir.Model) {
		for _, app := range input.apps {
			if app.schema.AppLabel == identity.AppLabel {
				for _, model := range app.schema.Models {
					if model.Name == identity.ModelName {
						return app, model
					}
				}
			}
		}
		return preparedProjectApp{}, ir.Model{}
	}
	accountApp, accountModel := resolve(role.Model)
	groupApp, groupModel := resolve(role.Catalog.Group)
	permissionApp, permissionModel := resolve(role.Catalog.Permission)
	if accountModel.GoName == "" || groupModel.GoName == "" || permissionModel.GoName == "" {
		return nil, fmt.Errorf("project account or catalog model is unresolved")
	}
	collections, _, err := buildProjectManyToMany(plan)
	if err != nil {
		return nil, err
	}
	deletes, err := plan.deleteSurface()
	if err != nil {
		return nil, err
	}
	var groupCollection, accountGroups, accountPermissions, groupDelete, permissionDelete string
	for _, relation := range collections {
		if !relation.reverse && relation.owner.identity == role.Catalog.Group && relation.target.identity == role.Catalog.Permission && relation.name == role.Catalog.GroupPermissions {
			groupCollection = relation.surface
		}
		if !relation.reverse && relation.owner.identity == role.Model {
			if relation.target.identity == role.Catalog.Group && relation.name == role.Groups {
				accountGroups = relation.surface
			}
			if relation.target.identity == role.Catalog.Permission && relation.name == role.Permissions {
				accountPermissions = relation.surface
			}
		}
	}
	for _, policy := range deletes {
		if policy.model.identity == role.Catalog.Group {
			groupDelete = policy.surface
		}
		if policy.model.identity == role.Catalog.Permission {
			permissionDelete = policy.surface
		}
	}
	if groupCollection == "" || accountGroups == "" || accountPermissions == "" || groupDelete == "" || permissionDelete == "" {
		return nil, fmt.Errorf("project account catalog relation capabilities are unresolved")
	}
	for _, app := range input.apps {
		switch app.Package.ImportPath {
		case "context", "github.com/progresshans/godj/auth", "github.com/progresshans/godj/db", "github.com/progresshans/godj/identity/model", "github.com/progresshans/godj/schema/ir", "github.com/progresshans/godj/sessions/database":
			return nil, fmt.Errorf("project account import path conflicts with framework binding")
		}
	}
	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by GoDj. DO NOT EDIT.")
	fmt.Fprintf(&output, "\npackage %s\n\n", input.project.PackageName)
	fmt.Fprintln(&output, "import (")
	fmt.Fprintln(&output, "\t_godjaccountcontext \"context\"")
	fmt.Fprintln(&output, "\t_godjaccountauth \"github.com/progresshans/godj/auth\"")
	fmt.Fprintln(&output, "\t_godjaccountdb \"github.com/progresshans/godj/db\"")
	fmt.Fprintln(&output, "\t_godjaccountmodel \"github.com/progresshans/godj/identity/model\"")
	fmt.Fprintln(&output, "\t_godjaccountsessiondb \"github.com/progresshans/godj/sessions/database\"")
	fmt.Fprintln(&output, "\tir \"github.com/progresshans/godj/schema/ir\"")
	for _, app := range input.apps {
		fmt.Fprintf(&output, "\t%s %s\n", app.Alias, strconv.Quote(app.Package.ImportPath))
	}
	fmt.Fprintln(&output, ")")
	fmt.Fprintf(&output, "\nconst GoDjProjectAccountGeneratorVersion = %s\n", strconv.Quote(ProjectAccountGeneratorVersion))
	fmt.Fprintln(&output, "\n// BindAccount validates the selected typed model and complete host relation graph.")
	fmt.Fprintln(&output, "// It does not provision or transition the persisted credential domain.")
	fmt.Fprintf(&output, "func BindAccount() (_godjaccountmodel.Binding[%s.%s], error) {\n", accountApp.Alias, accountModel.GoName)
	for _, item := range []struct {
		name string
		role ir.AccountBoolean
	}{{"active", role.Active}, {"staff", role.Staff}, {"superuser", role.Superuser}} {
		if item.role.Constant != nil {
			fmt.Fprintf(&output, "\t_%s := %t\n", item.name, *item.role.Constant)
		}
	}
	fmt.Fprintf(&output, "\treturn _godjaccountmodel.Bind[%s.%s](ir.AccountRole{\n", accountApp.Alias, accountModel.GoName)
	fmt.Fprintf(&output, "\t\tModel: ir.ModelIdentity{AppLabel: %q, ModelName: %q},\n", role.Model.AppLabel, role.Model.ModelName)
	fmt.Fprintf(&output, "\t\tPrincipalID: %q, Login: %q, Password: %q, Revision: %q, LastLogin: %q, CreatedAt: %q, Email: %q,\n", role.PrincipalID, role.Login, role.Password, role.Revision, role.LastLogin, role.CreatedAt, role.Email)
	for _, item := range []struct {
		name string
		role ir.AccountBoolean
	}{{"Active", role.Active}, {"Staff", role.Staff}, {"Superuser", role.Superuser}} {
		if item.role.Constant == nil {
			fmt.Fprintf(&output, "\t\t%s: ir.AccountBoolean{Field: %q},\n", item.name, item.role.Field)
		} else {
			variable := map[string]string{"Active": "active", "Staff": "staff", "Superuser": "superuser"}[item.name]
			fmt.Fprintf(&output, "\t\t%s: ir.AccountBoolean{Constant: &_%s},\n", item.name, variable)
		}
	}
	fmt.Fprintf(&output, "\t\tGroups: %q, Permissions: %q, WriteLoginNormalization: %q, AuthenticateNormalization: %q, WriteEmailNormalization: %q,\n", role.Groups, role.Permissions, role.WriteLoginNormalization, role.AuthenticateNormalization, role.WriteEmailNormalization)
	fmt.Fprintln(&output, "\t\tCatalog: ir.AccountCatalog{")
	fmt.Fprintf(&output, "\t\t\tGroup: ir.ModelIdentity{AppLabel: %q, ModelName: %q}, GroupName: %q, GroupRevision: %q, GroupPermissions: %q,\n", role.Catalog.Group.AppLabel, role.Catalog.Group.ModelName, role.Catalog.GroupName, role.Catalog.GroupRevision, role.Catalog.GroupPermissions)
	fmt.Fprintf(&output, "\t\t\tPermission: ir.ModelIdentity{AppLabel: %q, ModelName: %q}, PermissionCode: %q, PermissionName: %q, PermissionRevision: %q,\n", role.Catalog.Permission.AppLabel, role.Catalog.Permission.ModelName, role.Catalog.PermissionCode, role.Catalog.PermissionName, role.Catalog.PermissionRevision)
	fmt.Fprintln(&output, "\t\t},")
	fmt.Fprintf(&output, "\t}, %s.%sDescriptor{},\n", accountApp.Alias, accountModel.GoName)
	for _, app := range input.apps {
		fmt.Fprintf(&output, "\t\t%s.GoDjRelationSchema(),\n", app.Alias)
	}
	fmt.Fprintln(&output, "\t)")
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output, "\n// NewAccountCredentialStore reads the selected typed account and effective permissions in one snapshot.")
	fmt.Fprintf(&output, "func NewAccountCredentialStore(backend _godjaccountdb.SnapshotReader) (*_godjaccountmodel.CredentialStore[%s.%s], error) {\n", accountApp.Alias, accountModel.GoName)
	fmt.Fprintln(&output, "\tbinding, err := BindAccount()")
	fmt.Fprintln(&output, "\tif err != nil { return nil, err }")
	fmt.Fprintf(&output, "\treturn _godjaccountmodel.NewCredentialStore(backend, binding, %s.%sDescriptor{}, %s.%sDescriptor{})\n", groupApp.Alias, groupModel.GoName, permissionApp.Alias, permissionModel.GoName)
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output, "\n// NewAccountSessionStore binds every session operation to the selected durable domain and the same native database owner.")
	fmt.Fprintf(&output, "func NewAccountSessionStore(backend _godjaccountsessiondb.Backend, config _godjaccountsessiondb.Config) (*_godjaccountmodel.SessionStore[%s.%s], error) {\n", accountApp.Alias, accountModel.GoName)
	fmt.Fprintln(&output, "\tstore, err := NewAccountCredentialStore(backend)")
	fmt.Fprintln(&output, "\tif err != nil { return nil, err }")
	fmt.Fprintln(&output, "\treturn _godjaccountmodel.NewSessionStore(store, config)")
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output, "\n// NewAccountAuthenticator applies the selected login policy and the shared current-credential verifier.")
	fmt.Fprintf(&output, "func NewAccountAuthenticator(ctx _godjaccountcontext.Context, backend _godjaccountdb.SnapshotReader, hasher _godjaccountauth.PasswordHasher) (*_godjaccountmodel.Authenticator[%s.%s], error) {\n", accountApp.Alias, accountModel.GoName)
	fmt.Fprintln(&output, "\tstore, err := NewAccountCredentialStore(backend)")
	fmt.Fprintln(&output, "\tif err != nil { return nil, err }")
	fmt.Fprintln(&output, "\treturn _godjaccountmodel.NewAuthenticator(ctx, store, hasher)")
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output, "\n// NewAccountProfileEditor shares one backend owner for current authorization, profile writes and account audit.")
	fmt.Fprintf(&output, "func NewAccountProfileEditor(backend _godjaccountdb.SnapshotReader, overlay _godjaccountauth.Authorizer, config _godjaccountmodel.ProfileConfig[%s.%s]) (*_godjaccountmodel.ProfileEditor[%s.%s], error) {\n", accountApp.Alias, accountModel.GoName, accountApp.Alias, accountModel.GoName)
	fmt.Fprintln(&output, "\tstore, err := NewAccountCredentialStore(backend)")
	fmt.Fprintln(&output, "\tif err != nil { return nil, err }")
	fmt.Fprintln(&output, "\treturn _godjaccountmodel.NewProfileEditor(store, overlay, config)")
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output, "\n// NewAccountRoleEditor uses the existing session owner for current roles, memberships, audit and deactivation.")
	fmt.Fprintf(&output, "func NewAccountRoleEditor(sessions *_godjaccountmodel.SessionStore[%s.%s], overlay _godjaccountauth.Authorizer, config _godjaccountmodel.RoleConfig[%s.%s]) (*_godjaccountmodel.RoleEditor[%s.%s], error) {\n", accountApp.Alias, accountModel.GoName, accountApp.Alias, accountModel.GoName, accountApp.Alias, accountModel.GoName)
	fmt.Fprintln(&output, "\tbinding, err := BindAccount()")
	fmt.Fprintln(&output, "\tif err != nil { return nil, err }")
	fmt.Fprintln(&output, "\tsource, err := binding.Project()")
	fmt.Fprintln(&output, "\tif err != nil { return nil, err }")
	fmt.Fprintln(&output, "\tcollections, err := BindCollectionsIn(source)")
	fmt.Fprintln(&output, "\tif err != nil { return nil, err }")
	fmt.Fprintf(&output, "\treturn _godjaccountmodel.NewRoleEditor(sessions, binding, collections.%s, collections.%s, overlay, config)\n", accountGroups, accountPermissions)
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output, "\n// NewAccountProfileReader binds current account authority, selected profile data and domain history to one snapshot owner.")
	fmt.Fprintf(&output, "func NewAccountProfileReader(backend _godjaccountdb.SnapshotReader, overlay _godjaccountauth.Authorizer, config _godjaccountmodel.ProfileReadConfig) (*_godjaccountmodel.ProfileReader[%s.%s], error) {\n", accountApp.Alias, accountModel.GoName)
	fmt.Fprintln(&output, "\tstore, err := NewAccountCredentialStore(backend)")
	fmt.Fprintln(&output, "\tif err != nil { return nil, err }")
	fmt.Fprintln(&output, "\treturn _godjaccountmodel.NewProfileReader(store, overlay, config)")
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output, "\n// NewAccountCatalog composes current account authority with the selected catalog and complete host relation policies.")
	fmt.Fprintf(&output, "func NewAccountCatalog(backend _godjaccountdb.SnapshotReader, overlay _godjaccountauth.Authorizer, config _godjaccountmodel.CatalogConfig[%s.%s, %s.%s]) (*_godjaccountmodel.Catalog[%s.%s, %s.%s], error) {\n", groupApp.Alias, groupModel.GoName, permissionApp.Alias, permissionModel.GoName, groupApp.Alias, groupModel.GoName, permissionApp.Alias, permissionModel.GoName)
	fmt.Fprintln(&output, "\tbinding, err := BindAccount()")
	fmt.Fprintln(&output, "\tif err != nil { return nil, err }")
	fmt.Fprintf(&output, "\tstore, err := _godjaccountmodel.NewCredentialStore(backend, binding, %s.%sDescriptor{}, %s.%sDescriptor{})\n", groupApp.Alias, groupModel.GoName, permissionApp.Alias, permissionModel.GoName)
	fmt.Fprintln(&output, "\tif err != nil { return nil, err }")
	fmt.Fprintln(&output, "\tsource, err := binding.Project()")
	fmt.Fprintln(&output, "\tif err != nil { return nil, err }")
	fmt.Fprintln(&output, "\tcollections, err := BindCollectionsIn(source)")
	fmt.Fprintln(&output, "\tif err != nil { return nil, err }")
	fmt.Fprintln(&output, "\tpolicies, err := BindRelationDeleters()")
	fmt.Fprintln(&output, "\tif err != nil { return nil, err }")
	fmt.Fprintf(&output, "\treturn _godjaccountmodel.NewCatalog(store, %s.%sDescriptor{}, %s.%sDescriptor{}, collections.%s, policies.%s, policies.%s, overlay, config)\n", groupApp.Alias, groupModel.GoName, permissionApp.Alias, permissionModel.GoName, groupCollection, groupDelete, permissionDelete)
	fmt.Fprintln(&output, "}")
	return output.Bytes(), nil
}
