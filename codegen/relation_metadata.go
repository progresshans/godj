package codegen

import (
	"bytes"
	"fmt"
	"strconv"

	"github.com/progresshans/godj/schema/ir"
)

const RelationMetadataGeneratorVersion = "godj-codegen-rel-metadata-current-v1"

// GenerateRelationMetadata renders the current per-app schema companion. The
// returned GoDjRelationSchema function constructs a fresh IR value on every
// call, so generated project bindings never share caller-mutable slices or
// relation pointers.
func GenerateRelationMetadata(packageName string, input ir.Schema) ([]byte, error) {
	if !validGeneratedPackageName(packageName) {
		return nil, fmt.Errorf("invalid generated package name %q", packageName)
	}
	prepared, err := prepareSchema(input)
	if err != nil {
		return nil, fmt.Errorf("normalize relation metadata schema: %w", err)
	}
	return generateAppCompanion(packageName, prepared, appMetadata)
}

func generateRelationMetadata(packageName string, prepared preparedSchema) ([]byte, error) {
	schema, hash := prepared.schema, prepared.hash

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by GoDj. DO NOT EDIT.")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "package %s\n\n", packageName)
	fmt.Fprintln(&output, `import "github.com/progresshans/godj/schema/ir"`)
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "const GoDjRelationMetadataGeneratorVersion = %s\n", strconv.Quote(RelationMetadataGeneratorVersion))
	fmt.Fprintf(&output, "const GoDjRelationSchemaSHA256 = %s\n\n", strconv.Quote(hash))
	fmt.Fprintln(&output, "func GoDjRelationSchema() ir.Schema {")
	fmt.Fprintln(&output, "\treturn ir.Schema{")
	renderSchemaLiteralBody(&output, schema, "\t\t")
	fmt.Fprintln(&output, "\t}")
	fmt.Fprintln(&output, "}")

	return output.Bytes(), nil
}

func renderSchemaLiteralBody(output *bytes.Buffer, schema ir.Schema, indent string) {
	fmt.Fprintf(output, "%sFormatVersion: %s,\n", indent, schemaFormatLiteral(schema.FormatVersion))
	fmt.Fprintf(output, "%sAppLabel: %s,\n", indent, strconv.Quote(schema.AppLabel))
	fmt.Fprintf(output, "%sModels: []ir.Model{\n", indent)
	for _, model := range schema.Models {
		fmt.Fprintf(output, "%s\t{\n", indent)
		renderModelLiteralBody(output, model, indent+"\t\t")
		fmt.Fprintf(output, "%s\t},\n", indent)
	}
	fmt.Fprintf(output, "%s},\n", indent)
}

func renderModelLiteralBody(output *bytes.Buffer, model ir.Model, indent string) {
	fmt.Fprintf(output, "%sName: %s,\n", indent, strconv.Quote(model.Name))
	fmt.Fprintf(output, "%sGoName: %s,\n", indent, strconv.Quote(model.GoName))
	fmt.Fprintf(output, "%sDBTable: %s,\n", indent, strconv.Quote(model.DBTable))
	fmt.Fprintf(output, "%sFields: []ir.Field{\n", indent)
	for _, field := range model.Fields {
		fmt.Fprintf(output, "%s\t{\n", indent)
		renderFieldLiteralBody(output, field, indent+"\t\t")
		fmt.Fprintf(output, "%s\t},\n", indent)
	}
	fmt.Fprintf(output, "%s},\n", indent)
}

func renderFieldLiteralBody(output *bytes.Buffer, field ir.Field, indent string) {
	fmt.Fprintf(output, "%sName: %s,\n", indent, strconv.Quote(field.Name))
	fmt.Fprintf(output, "%sGoName: %s,\n", indent, strconv.Quote(field.GoName))
	fmt.Fprintf(output, "%sColumn: %s,\n", indent, strconv.Quote(field.Column))
	fmt.Fprintf(output, "%sKind: %s,\n", indent, irKind(field.Kind))
	if field.PrimaryKey {
		fmt.Fprintf(output, "%sPrimaryKey: true,\n", indent)
	}
	if field.Nullable {
		fmt.Fprintf(output, "%sNullable: true,\n", indent)
	}
	if field.MaxLength != 0 {
		fmt.Fprintf(output, "%sMaxLength: %d,\n", indent, field.MaxLength)
	}
	if field.Default != nil {
		fmt.Fprintf(output, "%sDefault: %s,\n", indent, defaultLiteral(*field.Default))
	}
	if field.Relation != nil {
		renderRelationLiteral(output, *field.Relation, indent)
	}
}

func renderRelationLiteral(output *bytes.Buffer, relation ir.ForeignKeyRelation, indent string) {
	fmt.Fprintf(output, "%sRelation: &ir.ForeignKeyRelation{\n", indent)
	fmt.Fprintf(
		output,
		"%s\tTarget: ir.ModelIdentity{AppLabel: %s, ModelName: %s},\n",
		indent,
		strconv.Quote(relation.Target.AppLabel),
		strconv.Quote(relation.Target.ModelName),
	)
	fmt.Fprintf(output, "%s\tCardinality: %s,\n", indent, relationCardinalityLiteral(relation.Cardinality))
	fmt.Fprintf(output, "%s\tReverse: ir.ReverseRelation{", indent)
	if relation.Reverse.Name != "" {
		fmt.Fprintf(output, "Name: %s", strconv.Quote(relation.Reverse.Name))
	} else if relation.Reverse.Disabled {
		fmt.Fprint(output, "Disabled: true")
	}
	fmt.Fprintln(output, "},")
	fmt.Fprintf(output, "%s\tOnDelete: %s,\n", indent, deletePolicyLiteral(relation.OnDelete))
	fmt.Fprintf(output, "%s},\n", indent)
}

func schemaFormatLiteral(version int) string {
	switch version {
	case ir.CurrentFormatVersion:
		return "ir.CurrentFormatVersion"
	default:
		return strconv.Itoa(version)
	}
}

func relationCardinalityLiteral(cardinality ir.RelationCardinality) string {
	switch cardinality {
	case ir.RelationManyToOne:
		return "ir.RelationManyToOne"
	case ir.RelationOneToMany:
		return "ir.RelationOneToMany"
	default:
		return strconv.Quote(string(cardinality))
	}
}

func deletePolicyLiteral(policy ir.DeletePolicy) string {
	switch policy {
	case ir.DeleteProtect:
		return "ir.DeleteProtect"
	case ir.DeleteSetNull:
		return "ir.DeleteSetNull"
	default:
		return strconv.Quote(string(policy))
	}
}
