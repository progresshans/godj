package codegen

import (
	"bytes"
	"fmt"
	"sort"
	"strconv"

	"github.com/progresshans/godj/internal/identifiers"
)

const projectBindingGeneratorVersion = "godj-codegen-rel-project-v1"

type BridgePackage struct {
	Alias      string
	ImportPath string
}

// GenerateProjectBridge renders the import-cycle-free project owner that
// passes every generated app schema companion to orm.BindProject at once.
func GenerateProjectBridge(packageName string, packages []BridgePackage) ([]byte, error) {
	return finalizeSource(generateProjectBridge(packageName, packages))
}

func generateProjectBridge(packageName string, packages []BridgePackage) ([]byte, error) {
	if !validGeneratedPackageName(packageName) {
		return nil, fmt.Errorf("invalid generated package name %q", packageName)
	}
	canonical, err := canonicalBridgePackages(packages)
	if err != nil {
		return nil, err
	}

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by GoDj. DO NOT EDIT.")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "package %s\n\n", packageName)
	fmt.Fprintln(&output, "import (")
	fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/orm\"")
	for _, app := range canonical {
		fmt.Fprintf(&output, "\t%s %s\n", app.Alias, strconv.Quote(app.ImportPath))
	}
	fmt.Fprintln(&output, ")")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "const GoDjProjectBindingGeneratorVersion = %s\n\n", strconv.Quote(projectBindingGeneratorVersion))
	fmt.Fprintln(&output, "func Bind() (orm.ProjectBinding, error) {")
	if len(canonical) == 0 {
		fmt.Fprintln(&output, "\treturn orm.BindProject()")
	} else {
		fmt.Fprintln(&output, "\treturn orm.BindProject(")
		for _, app := range canonical {
			fmt.Fprintf(&output, "\t\t%s.GoDjRelationSchema(),\n", app.Alias)
		}
		fmt.Fprintln(&output, "\t)")
	}
	fmt.Fprintln(&output, "}")

	return output.Bytes(), nil
}

func canonicalBridgePackages(packages []BridgePackage) ([]BridgePackage, error) {
	canonical := append([]BridgePackage(nil), packages...)
	sort.Slice(canonical, func(left, right int) bool {
		if canonical[left].Alias != canonical[right].Alias {
			return canonical[left].Alias < canonical[right].Alias
		}
		return canonical[left].ImportPath < canonical[right].ImportPath
	})

	aliases := map[string]struct{}{
		"orm":                                {},
		"Bind":                               {},
		"GoDjProjectBindingGeneratorVersion": {},
	}
	paths := map[string]struct{}{
		"github.com/progresshans/godj/orm": {},
	}
	for _, app := range canonical {
		if !validGeneratedPackageName(app.Alias) || app.Alias == "init" {
			return nil, fmt.Errorf("invalid bridge package alias %q", app.Alias)
		}
		if _, duplicate := aliases[app.Alias]; duplicate {
			return nil, fmt.Errorf("duplicate bridge package alias %q", app.Alias)
		}
		aliases[app.Alias] = struct{}{}
		if !identifiers.ImportPath(app.ImportPath) {
			return nil, fmt.Errorf("invalid bridge import path %q", app.ImportPath)
		}
		if _, duplicate := paths[app.ImportPath]; duplicate {
			return nil, fmt.Errorf("duplicate bridge import path %q", app.ImportPath)
		}
		paths[app.ImportPath] = struct{}{}
	}
	return canonical, nil
}
