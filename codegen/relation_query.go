package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"

	"github.com/progresshans/godj/schema/ir"
)

const RelationQueryGeneratorVersion = "godj-codegen-rel-query-v1"

// GenerateRelationQuery renders the additive read/query companion for an
// exact relation-schema application. The existing generated main and relation
// metadata companion remain independent byte streams.
func GenerateRelationQuery(packageName string, input ir.Schema) ([]byte, error) {
	if !validGeneratedPackageName(packageName) {
		return nil, fmt.Errorf("invalid generated package name %q", packageName)
	}
	schema, err := ir.Normalize(input.Clone())
	if err != nil {
		return nil, fmt.Errorf("normalize relation query schema: %w", err)
	}
	if schema.FormatVersion != ir.RelationFormatVersion {
		return nil, fmt.Errorf(
			"generate relation query schema: format version %d is not relation format version %d",
			schema.FormatVersion,
			ir.RelationFormatVersion,
		)
	}
	if err := validateRelationQueryNames(schema); err != nil {
		return nil, fmt.Errorf("validate relation query names: %w", err)
	}
	hash, err := ir.Hash(schema)
	if err != nil {
		return nil, fmt.Errorf("hash relation query schema: %w", err)
	}

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by GoDj. DO NOT EDIT.")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "package %s\n\n", packageName)
	fmt.Fprintln(&output, "import (")
	if hasNullableQueryStorage(schema) {
		fmt.Fprintln(&output, "\t\"database/sql\"")
	}
	fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/db\"")
	fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/orm\"")
	fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/schema/ir\"")
	fmt.Fprintln(&output, ")")
	fmt.Fprintln(&output)
	fmt.Fprintf(
		&output,
		"const GoDjRelationQueryGeneratorVersion = %s\n",
		strconv.Quote(RelationQueryGeneratorVersion),
	)
	fmt.Fprintf(&output, "const GoDjRelationQuerySchemaSHA256 = %s\n\n", strconv.Quote(hash))

	for modelIndex, model := range schema.Models {
		renderRelationQueryModel(&output, model, modelIndex)
	}

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated relation query companion: %w", err)
	}
	return formatted, nil
}

func validateRelationQueryNames(schema ir.Schema) error {
	packageSymbols := map[string]string{}
	add := func(symbol, owner string) error {
		if previous, exists := packageSymbols[symbol]; exists {
			return fmt.Errorf("package symbol %s for %s conflicts with %s", symbol, owner, previous)
		}
		packageSymbols[symbol] = owner
		return nil
	}

	fixed := []struct {
		symbol string
		owner  string
	}{
		{symbol: "GoDjGeneratorVersion", owner: "main generator provenance constant"},
		{symbol: "GoDjSchemaSHA256", owner: "main schema provenance constant"},
		{symbol: "GoDjRelationMetadataGeneratorVersion", owner: "relation metadata provenance constant"},
		{symbol: "GoDjRelationSchemaSHA256", owner: "relation schema provenance constant"},
		{symbol: "GoDjRelationSchema", owner: "relation schema accessor"},
		{symbol: "GoDjRelationQueryGeneratorVersion", owner: "relation query provenance constant"},
		{symbol: "GoDjRelationQuerySchemaSHA256", owner: "relation query schema provenance constant"},
	}
	for _, candidate := range fixed {
		if err := add(candidate.symbol, candidate.owner); err != nil {
			return err
		}
	}

	for _, model := range schema.Models {
		owner := "model " + model.GoName
		for _, symbol := range []string{
			model.GoName,
			model.GoName + "Descriptor",
			model.GoName + "FieldSet",
			model.GoName + "Fields",
			model.GoName + "Objects",
		} {
			if err := add(symbol, owner); err != nil {
				return err
			}
		}
	}
	return nil
}

func renderRelationQueryModel(output *bytes.Buffer, model ir.Model, modelIndex int) {
	descriptor := model.GoName + "Descriptor"
	fieldSet := model.GoName + "FieldSet"
	fields := model.GoName + "Fields"
	objects := model.GoName + "Objects"

	fmt.Fprintf(output, "type %s struct{}\n\n", descriptor)
	fmt.Fprintf(output, "var _ orm.ModelDescriptor[%s] = %s{}\n\n", model.GoName, descriptor)
	fmt.Fprintf(output, "func (%s) Metadata() ir.Model {\n", descriptor)
	fmt.Fprintln(output, "\tschema := GoDjRelationSchema()")
	fmt.Fprintf(output, "\treturn schema.Models[%d].Clone()\n", modelIndex)
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	fmt.Fprintf(output, "func (%s) Scan(row db.Row) (%s, error) {\n", descriptor, model.GoName)
	fmt.Fprintf(output, "\tvar value %s\n", model.GoName)
	for _, field := range model.Fields {
		switch {
		case field.Nullable && field.Kind == ir.FieldChar:
			fmt.Fprintf(output, "\tvar scan%s sql.NullString\n", field.GoName)
		case field.Nullable && field.Kind == ir.FieldForeignKey:
			fmt.Fprintf(output, "\tvar scan%s sql.NullInt64\n", field.GoName)
		}
	}
	fmt.Fprint(output, "\tif err := row.Scan(")
	for index, field := range model.Fields {
		if index > 0 {
			fmt.Fprint(output, ", ")
		}
		if field.Nullable && (field.Kind == ir.FieldChar || field.Kind == ir.FieldForeignKey) {
			fmt.Fprintf(output, "&scan%s", field.GoName)
		} else {
			fmt.Fprintf(output, "&value.%s", field.GoName)
		}
	}
	fmt.Fprintf(output, "); err != nil {\n\t\treturn %s{}, err\n\t}\n", model.GoName)
	for _, field := range model.Fields {
		switch {
		case field.Nullable && field.Kind == ir.FieldChar:
			fmt.Fprintf(output, "\tif scan%s.Valid {\n", field.GoName)
			fmt.Fprintf(output, "\t\tscanned := scan%s.String\n", field.GoName)
			fmt.Fprintf(output, "\t\tvalue.%s = &scanned\n", field.GoName)
			fmt.Fprintln(output, "\t}")
		case field.Nullable && field.Kind == ir.FieldForeignKey:
			fmt.Fprintf(output, "\tif scan%s.Valid {\n", field.GoName)
			fmt.Fprintf(output, "\t\tscanned := scan%s.Int64\n", field.GoName)
			fmt.Fprintf(output, "\t\tvalue.%s = &scanned\n", field.GoName)
			fmt.Fprintln(output, "\t}")
		}
	}
	fmt.Fprintln(output, "\treturn value, nil")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	fmt.Fprintf(output, "func (%s) CloneModel(value %s) %s {\n", descriptor, model.GoName, model.GoName)
	for _, field := range model.Fields {
		if field.Nullable && (field.Kind == ir.FieldChar || field.Kind == ir.FieldForeignKey) {
			fmt.Fprintf(output, "\tif value.%s != nil {\n", field.GoName)
			fmt.Fprintf(output, "\t\tcloned := *value.%s\n", field.GoName)
			fmt.Fprintf(output, "\t\tvalue.%s = &cloned\n", field.GoName)
			fmt.Fprintln(output, "\t}")
		}
	}
	fmt.Fprintln(output, "\treturn value")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	fmt.Fprintf(output, "type %s struct {\n", fieldSet)
	for _, field := range model.Fields {
		if field.Kind == ir.FieldForeignKey {
			continue
		}
		fmt.Fprintf(output, "\t%s %s\n", field.GoName, ormFieldType(model.GoName, field))
	}
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	fmt.Fprintf(output, "var %s = func() %s {\n", fields, fieldSet)
	fmt.Fprintln(output, "\tschema := GoDjRelationSchema()")
	fmt.Fprintf(output, "\tmetadata := schema.Models[%d].Fields\n", modelIndex)
	fmt.Fprintf(output, "\treturn %s{\n", fieldSet)
	for fieldIndex, field := range model.Fields {
		if field.Kind == ir.FieldForeignKey {
			continue
		}
		fmt.Fprintf(
			output,
			"\t\t%s: %s(metadata[%d]),\n",
			field.GoName,
			ormFieldConstructor(model.GoName, field),
			fieldIndex,
		)
	}
	fmt.Fprintln(output, "\t}")
	fmt.Fprintln(output, "}()")
	fmt.Fprintln(output)
	fmt.Fprintf(output, "var %s = orm.NewManager[%s](%s{})\n\n", objects, model.GoName, descriptor)
}

func hasNullableQueryStorage(schema ir.Schema) bool {
	for _, model := range schema.Models {
		for _, field := range model.Fields {
			if field.Nullable && (field.Kind == ir.FieldChar || field.Kind == ir.FieldForeignKey) {
				return true
			}
		}
	}
	return false
}
