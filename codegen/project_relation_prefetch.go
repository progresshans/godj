package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
)

const ProjectRelationPrefetchGeneratorVersion = "godj-codegen-rel-prefetch-project-v1"

// GenerateProjectRelationPrefetch renders the project-only reverse prefetch
// companion. The generator is pure: it validates and formats the complete
// candidate before returning bytes, but publication and prerequisite-union
// compilation remain caller-owned.
func GenerateProjectRelationPrefetch(
	packageName string,
	packages []RelationReversePackage,
) ([]byte, error) {
	if !validGeneratedPackageName(packageName) {
		return nil, fmt.Errorf("invalid generated package name %q", packageName)
	}
	canonical, err := canonicalRelationReversePackages(packages)
	if err != nil {
		return nil, err
	}
	if err := validateProjectRelationPrefetchImports(canonical); err != nil {
		return nil, err
	}
	models, owners, err := buildProjectRelationReverseSurface(canonical)
	if err != nil {
		return nil, err
	}
	if err := validateProjectRelationReverseNamespaces(canonical, owners); err != nil {
		return nil, fmt.Errorf("validate project relation reverse prerequisites: %w", err)
	}
	objectOwners := projectRelationReverseObjectOwners(owners)
	if err := validateProjectRelationPrefetchNamespaces(canonical, owners, objectOwners); err != nil {
		return nil, fmt.Errorf("validate project relation prefetch names: %w", err)
	}
	objectModels := projectRelationReverseUsedModels(models, objectOwners)
	usedApps := projectRelationReverseUsedApps(canonical, objectModels)

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by GoDj. DO NOT EDIT.")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "package %s\n\n", packageName)
	if len(objectOwners) > 0 {
		fmt.Fprintln(&output, "import (")
		fmt.Fprintln(&output, "\tcontext \"context\"")
		for _, app := range usedApps {
			fmt.Fprintf(&output, "\t%s %s\n", app.alias, strconv.Quote(app.importPath))
		}
		fmt.Fprintln(&output, "\tdb \"github.com/progresshans/godj/db\"")
		fmt.Fprintln(&output, "\torm \"github.com/progresshans/godj/orm\"")
		fmt.Fprintln(&output, ")")
		fmt.Fprintln(&output)
	}
	fmt.Fprintf(
		&output,
		"const GoDjProjectRelationPrefetchGeneratorVersion = %s\n\n",
		strconv.Quote(ProjectRelationPrefetchGeneratorVersion),
	)

	for _, owner := range objectOwners {
		renderProjectRelationPrefetchOwner(&output, owner)
	}
	fmt.Fprintln(&output, "type ReversePrefetches struct {")
	for _, owner := range objectOwners {
		fmt.Fprintf(&output, "\t%s %sReversePrefetches\n", owner.surface, owner.surface)
	}
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)
	renderBindReversePrefetches(&output, objectOwners)

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated project relation prefetch companion: %w", err)
	}
	return formatted, nil
}

func validateProjectRelationPrefetchImports(apps []normalizedRelationReversePackage) error {
	for _, app := range apps {
		switch app.alias {
		case "context", "make", "len":
			return fmt.Errorf("invalid relation prefetch package alias %q", app.alias)
		}
		if app.importPath == "context" {
			return fmt.Errorf("reserved relation prefetch import path %q", app.importPath)
		}
	}
	return nil
}

func validateProjectRelationPrefetchNamespaces(
	apps []normalizedRelationReversePackage,
	owners []projectRelationReverseOwner,
	objectOwners []projectRelationReverseOwner,
) error {
	packageNames := make(map[string]string)
	addPackageName := func(name, owner string) error {
		if previous, duplicate := packageNames[name]; duplicate {
			return fmt.Errorf("package symbol %s for %s conflicts with %s", name, owner, previous)
		}
		packageNames[name] = owner
		return nil
	}
	prerequisiteNames := []struct {
		name  string
		owner string
	}{
		{name: "GoDjProjectBindingGeneratorVersion", owner: "project binding provenance constant"},
		{name: "Bind", owner: "project binding function"},
		{name: "GoDjProjectRelationReverseGeneratorVersion", owner: "project reverse provenance constant"},
		{name: "ReverseRelations", owner: "project reverse relation aggregate"},
		{name: "BindReverseRelations", owner: "project reverse relation binding function"},
		{name: "ReverseObjects", owner: "project reverse object aggregate"},
		{name: "BindReverseObjects", owner: "project reverse object binding function"},
	}
	for _, prerequisite := range prerequisiteNames {
		if err := addPackageName(prerequisite.name, prerequisite.owner); err != nil {
			return err
		}
	}
	if err := seedProjectRelationReversePrerequisiteNames(apps, addPackageName); err != nil {
		return err
	}
	objectOwnerSet := make(map[*projectRelationReverseModel]struct{}, len(objectOwners))
	for index := range objectOwners {
		objectOwnerSet[objectOwners[index].model] = struct{}{}
	}
	for _, owner := range owners {
		identity := owner.model.identity.AppLabel + "." + owner.model.identity.ModelName
		if err := addPackageName(owner.relationsType, "reverse relations for "+identity); err != nil {
			return err
		}
		if _, objectCapable := objectOwnerSet[owner.model]; objectCapable {
			if err := addPackageName(owner.factoryType, "reverse object factory for "+identity); err != nil {
				return err
			}
			if err := addPackageName(owner.objectType, "reverse object wrapper for "+identity); err != nil {
				return err
			}
		}
		for _, relation := range owner.relations {
			if err := addPackageName(relation.typeName, "reverse relation "+identity+"."+relation.name); err != nil {
				return err
			}
		}
	}
	prefetchNames := []struct {
		name  string
		owner string
	}{
		{name: "GoDjProjectRelationPrefetchGeneratorVersion", owner: "project relation prefetch provenance constant"},
		{name: "ReversePrefetches", owner: "project relation prefetch aggregate"},
		{name: "BindReversePrefetches", owner: "project relation prefetch binding function"},
	}
	for _, prefetch := range prefetchNames {
		if err := addPackageName(prefetch.name, prefetch.owner); err != nil {
			return err
		}
	}

	aggregateFields := make(map[string]string, len(objectOwners))
	for _, owner := range objectOwners {
		identity := owner.model.identity.AppLabel + "." + owner.model.identity.ModelName
		if previous, duplicate := aggregateFields[owner.surface]; duplicate {
			return fmt.Errorf("prefetch aggregate field %s for %s conflicts with %s", owner.surface, identity, previous)
		}
		aggregateFields[owner.surface] = identity
		if err := addPackageName(owner.surface+"ReversePrefetches", "reverse prefetches for "+identity); err != nil {
			return err
		}
		privateFields := map[string]string{"objects": "reverse object factory"}
		for _, relation := range owner.relations {
			private := lowerFirst(relation.selector)
			if previous, duplicate := privateFields[private]; duplicate {
				return fmt.Errorf(
					"private prefetch field %s for %s.%s conflicts with %s",
					private,
					identity,
					relation.name,
					previous,
				)
			}
			privateFields[private] = relation.name
		}
	}
	return nil
}

func renderProjectRelationPrefetchOwner(output *bytes.Buffer, owner projectRelationReverseOwner) {
	ownerType := owner.model.app.alias + "." + owner.model.model.GoName
	bundleType := owner.surface + "ReversePrefetches"
	fmt.Fprintf(output, "type %s struct {\n", bundleType)
	fmt.Fprintf(output, "\tobjects %s\n", owner.factoryType)
	for _, relation := range owner.relations {
		fmt.Fprintf(
			output,
			"\t%s orm.ReversePrefetch[%s, %s.%s]\n",
			lowerFirst(relation.selector),
			ownerType,
			relation.source.app.alias,
			relation.source.model.GoName,
		)
	}
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	for _, relation := range owner.relations {
		renderProjectRelationPrefetchMethod(output, owner, relation)
	}
}

func renderProjectRelationPrefetchMethod(
	output *bytes.Buffer,
	owner projectRelationReverseOwner,
	relation projectRelationReverseEdge,
) {
	ownerType := owner.model.app.alias + "." + owner.model.model.GoName
	bundleType := owner.surface + "ReversePrefetches"
	fmt.Fprintf(output, "func (_prefetches %s) %s(\n", bundleType, relation.selector)
	fmt.Fprintln(output, "\t_ctx context.Context,")
	fmt.Fprintln(output, "\t_backend db.Queryer,")
	fmt.Fprintf(output, "\t_owners []%s,\n", ownerType)
	fmt.Fprintf(output, ") ([]*%s, error) {\n", owner.objectType)
	fmt.Fprintf(output, "\t_snapshots := make([]%s, len(_owners))\n", ownerType)
	fmt.Fprintln(output, "\tfor _index := range _owners {")
	fmt.Fprintf(
		output,
		"\t\t_snapshots[_index] = (%s.%sDescriptor{}).CloneModel(_owners[_index])\n",
		owner.model.app.alias,
		owner.model.model.GoName,
	)
	fmt.Fprintln(output, "\t}")
	fmt.Fprintf(output, "\t_sets, _err := _prefetches.%s.Load(_ctx, _backend, _snapshots)\n", lowerFirst(relation.selector))
	fmt.Fprintln(output, "\tif _err != nil {")
	fmt.Fprintln(output, "\t\treturn nil, _err")
	fmt.Fprintln(output, "\t}")
	fmt.Fprintf(output, "\t_results := make([]*%s, len(_snapshots))\n", owner.objectType)
	fmt.Fprintln(output, "\tfor _index := range _snapshots {")
	fmt.Fprintln(output, "\t\t_object, _err := _prefetches.objects.From(_backend, _snapshots[_index])")
	fmt.Fprintln(output, "\t\tif _err != nil {")
	fmt.Fprintln(output, "\t\t\treturn nil, _err")
	fmt.Fprintln(output, "\t\t}")
	fmt.Fprintf(output, "\t\t_object.%s = _sets[_index]\n", lowerFirst(relation.selector))
	fmt.Fprintln(output, "\t\t_results[_index] = _object")
	fmt.Fprintln(output, "\t}")
	fmt.Fprintln(output, "\treturn _results, nil")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
}

func renderBindReversePrefetches(output *bytes.Buffer, owners []projectRelationReverseOwner) {
	fmt.Fprintln(output, "func BindReversePrefetches() (ReversePrefetches, error) {")
	if len(owners) == 0 {
		fmt.Fprintln(output, "\tif _, _err := BindReverseObjects(); _err != nil {")
		fmt.Fprintln(output, "\t\treturn ReversePrefetches{}, _err")
		fmt.Fprintln(output, "\t}")
		fmt.Fprintln(output, "\treturn ReversePrefetches{}, nil")
		fmt.Fprintln(output, "}")
		return
	}
	fmt.Fprintln(output, "\t_objects, _err := BindReverseObjects()")
	fmt.Fprintln(output, "\tif _err != nil {")
	fmt.Fprintln(output, "\t\treturn ReversePrefetches{}, _err")
	fmt.Fprintln(output, "\t}")
	for _, owner := range owners {
		for _, relation := range owner.relations {
			fmt.Fprintf(
				output,
				"\t_prefetch%d, _err := orm.BindReversePrefetch(_objects.%s.%s)\n",
				relation.bind,
				owner.surface,
				lowerFirst(relation.selector),
			)
			fmt.Fprintln(output, "\tif _err != nil {")
			fmt.Fprintln(output, "\t\treturn ReversePrefetches{}, _err")
			fmt.Fprintln(output, "\t}")
		}
	}
	fmt.Fprintln(output, "\treturn ReversePrefetches{")
	for _, owner := range owners {
		fmt.Fprintf(output, "\t\t%s: %sReversePrefetches{\n", owner.surface, owner.surface)
		fmt.Fprintf(output, "\t\t\tobjects: _objects.%s,\n", owner.surface)
		for _, relation := range owner.relations {
			fmt.Fprintf(output, "\t\t\t%s: _prefetch%d,\n", lowerFirst(relation.selector), relation.bind)
		}
		fmt.Fprintln(output, "\t\t},")
	}
	fmt.Fprintln(output, "\t}, nil")
	fmt.Fprintln(output, "}")
}
