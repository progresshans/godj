const ProjectRelationSelectRelatedGeneratorVersion = "godj-codegen-rel-select-related-project-current-v1"

// GenerateProjectRelationSelectRelated renders the current project-only
// select-related companion. It attaches a singular builder to the existing
// relation-object factory; it does not create another project binding root.
func GenerateProjectRelationSelectRelated(
	packageName string,
	packages []RelationObjectPackage,
) ([]byte, error) {
	if !validGeneratedPackageName(packageName) {
		return nil, fmt.Errorf("invalid generated package name %q", packageName)
	}
	canonical, err := canonicalRelationObjectPackages(packages)
	if err != nil {
		return nil, err
	}
	if err := validateProjectRelationSelectRelatedImports(canonical); err != nil {
		return nil, err
	}
	for _, app := range canonical {
		if err := validateRelationProjectionNames(app.schema); err != nil {
			return nil, fmt.Errorf("validate relation projection prerequisite %q: %w", app.alias, err)
		}
	}
	models, sources, err := buildProjectRelationObjectSurface(canonical)
	if err != nil {
		return nil, err
	}
	if err := validateProjectRelationObjectNamespaces(canonical, sources); err != nil {
		return nil, fmt.Errorf("validate project relation select-related prerequisites: %w", err)
	}
	if err := validateProjectRelationSelectRelatedNamespaces(canonical, sources); err != nil {
		return nil, fmt.Errorf("validate project relation select-related names: %w", err)
	}
	usedModels := projectRelationSelectRelatedUsedModels(models, sources)
	usedApps := projectRelationSelectRelatedUsedApps(canonical, usedModels)

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by GoDj. DO NOT EDIT.")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "package %s\n\n", packageName)
	if len(sources) > 0 {
		fmt.Fprintln(&output, "import (")
		fmt.Fprintln(&output, "\tcontext \"context\"")
		for _, app := range usedApps {
			fmt.Fprintf(&output, "\t%s %s\n", app.alias, strconv.Quote(app.importPath))
		}
		fmt.Fprintln(&output, "\torm \"github.com/progresshans/godj/orm\"")
		fmt.Fprintln(&output, "\tquery \"github.com/progresshans/godj/query\"")
		fmt.Fprintln(&output, ")")
		fmt.Fprintln(&output)
	}
	fmt.Fprintf(
		&output,
		"const GoDjProjectRelationSelectRelatedGeneratorVersion = %s\n\n",
		strconv.Quote(ProjectRelationSelectRelatedGeneratorVersion),
	)
	for _, model := range usedModels {
		fmt.Fprintf(
			&output,
			"var _ orm.ProjectionDescriptor[%s.%s] = %s.%sDescriptor{}\n",
			model.app.alias,
			model.model.GoName,
			model.app.alias,
			model.model.GoName,
		)
	}
	if len(usedModels) > 0 {
		fmt.Fprintln(&output)
	}

	for _, source := range sources {
		renderProjectRelationSelectRelatedSource(&output, source)
	}

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated project relation select-related companion: %w", err)
	}
	return formatted, nil
}

func validateProjectRelationSelectRelatedImports(apps []normalizedRelationObjectPackage) error {
	for _, app := range apps {
		switch app.alias {
		case "context", "sql", "db", "orm", "query", "ir", "len", "make", "string", "uint8":
			return fmt.Errorf("invalid relation select-related package alias %q", app.alias)
		}
		switch app.importPath {
		case "context", "database/sql", "github.com/progresshans/godj/db", "github.com/progresshans/godj/orm", "github.com/progresshans/godj/query", "github.com/progresshans/godj/schema/ir":
			return fmt.Errorf("reserved relation select-related import path %q", app.importPath)
		}
	}
	return nil
}

func validateProjectRelationSelectRelatedNamespaces(
	apps []normalizedRelationObjectPackage,
	sources []projectRelationObjectSource,
) error {
	packageNames := map[string]string{}
	add := func(name, owner string) error {
		if previous, duplicate := packageNames[name]; duplicate {
			return fmt.Errorf("package symbol %s for %s conflicts with %s", name, owner, previous)
		}
		packageNames[name] = owner
		return nil
	}

	for _, candidate := range []struct {
		name  string
		owner string
	}{
		{name: "GoDjProjectBindingGeneratorVersion", owner: "project binding provenance constant"},
		{name: "Bind", owner: "project binding function"},
		{name: "GoDjProjectRelationQueryGeneratorVersion", owner: "project relation query provenance constant"},
		{name: "Relations", owner: "project relation query aggregate"},
		{name: "BindRelations", owner: "project relation query binding function"},
		{name: "GoDjProjectRelationObjectGeneratorVersion", owner: "project relation object provenance constant"},
		{name: "Objects", owner: "project relation object aggregate"},
		{name: "BindObjects", owner: "project relation object binding function"},
		{name: "GoDjProjectRelationReverseGeneratorVersion", owner: "project reverse provenance constant"},
		{name: "ReverseRelations", owner: "project reverse relation aggregate"},
		{name: "BindReverseRelations", owner: "project reverse relation binding function"},
		{name: "ReverseObjects", owner: "project reverse object aggregate"},
		{name: "BindReverseObjects", owner: "project reverse object binding function"},
		{name: "GoDjProjectRelationPrefetchGeneratorVersion", owner: "project prefetch provenance constant"},
		{name: "ReversePrefetches", owner: "project prefetch aggregate"},
		{name: "BindReversePrefetches", owner: "project prefetch binding function"},
		{name: "GoDjProjectRelationSelectRelatedGeneratorVersion", owner: "project select-related provenance constant"},
	} {
		if err := add(candidate.name, candidate.owner); err != nil {
			return err
		}
	}
	for _, app := range apps {
		if err := add(app.alias, "import alias for "+app.schema.AppLabel); err != nil {
			return err
		}
	}
	queryApps := make([]normalizedRelationQueryPackage, len(apps))
	reverseApps := make([]normalizedRelationReversePackage, len(apps))
	for index, app := range apps {
		queryApps[index] = normalizedRelationQueryPackage{
			alias:      app.alias,
			prefix:     app.prefix,
			importPath: app.importPath,
			schema:     app.schema.Clone(),
		}
		reverseApps[index] = normalizedRelationReversePackage{
			alias:      app.alias,
			prefix:     app.prefix,
			importPath: app.importPath,
			schema:     app.schema.Clone(),
		}
	}
	_, querySources, err := buildProjectRelationQuerySurface(queryApps)
	if err != nil {
		return fmt.Errorf("build immutable project relation query namespace: %w", err)
	}
	if err := validateProjectRelationQueryNamespaces(queryApps, querySources); err != nil {
		return fmt.Errorf("validate immutable project relation query namespace: %w", err)
	}
	for _, source := range querySources {
		identity := source.model.identity.AppLabel + "." + source.model.identity.ModelName
		if err := add(source.relationsType, "relation query surface for "+identity); err != nil {
			return err
		}
		for _, relation := range source.relations {
			if err := add(relation.typeName, "relation query edge "+identity+"."+relation.field.Name); err != nil {
				return err
			}
		}
	}
	_, reverseOwners, err := buildProjectRelationReverseSurface(reverseApps)
	if err != nil {
		return fmt.Errorf("build immutable project reverse namespace: %w", err)
	}
	if err := validateProjectRelationReverseNamespaces(reverseApps, reverseOwners); err != nil {
		return fmt.Errorf("validate immutable project reverse namespace: %w", err)
	}
	reverseObjectOwners := projectRelationReverseObjectOwners(reverseOwners)
	if err := validateProjectRelationPrefetchNamespaces(reverseApps, reverseOwners, reverseObjectOwners); err != nil {
		return fmt.Errorf("validate immutable project prefetch namespace: %w", err)
	}
	reverseObjectSet := make(map[*projectRelationReverseModel]struct{}, len(reverseObjectOwners))
	for index := range reverseObjectOwners {
		reverseObjectSet[reverseObjectOwners[index].model] = struct{}{}
	}
	for _, owner := range reverseOwners {
		identity := owner.model.identity.AppLabel + "." + owner.model.identity.ModelName
		if err := add(owner.relationsType, "reverse relation surface for "+identity); err != nil {
			return err
		}
		if _, objectCapable := reverseObjectSet[owner.model]; objectCapable {
			if err := add(owner.factoryType, "reverse object factory for "+identity); err != nil {
				return err
			}
			if err := add(owner.objectType, "reverse object wrapper for "+identity); err != nil {
				return err
			}
			if err := add(owner.surface+"ReversePrefetches", "reverse prefetches for "+identity); err != nil {
				return err
			}
		}
		for _, relation := range owner.relations {
			if err := add(relation.typeName, "reverse relation "+identity+"."+relation.name); err != nil {
				return err
			}
		}
	}

	for _, source := range sources {
		identity := source.model.identity.AppLabel + "." + source.model.identity.ModelName
		if err := add(source.factoryType, "object factory for "+identity); err != nil {
			return err
		}
		if err := add(source.objectType, "object wrapper for "+identity); err != nil {
			return err
		}
		for _, relation := range source.relations {
			if relation.field.Nullable {
				if err := add(relation.typeName, "nullable object relation "+identity+"."+relation.field.Name); err != nil {
					return err
				}
			}
		}

		builderType := source.surface + "SelectRelated"
		dynamicType := source.surface + "DynamicSelectRelatedQuery"
		if err := add(builderType, "select-related builder for "+identity); err != nil {
			return err
		}
		if err := add(dynamicType, "dynamic select-related query for "+identity); err != nil {
			return err
		}
		factoryMembers := map[string]string{
			"From":          "existing object factory method",
			"ParseDynamic":  "existing object factory method",
			"SelectRelated": "select-related factory method",
		}
		builderMethods := map[string]string{
			"ParseDynamic": "dynamic select-related method",
		}
		dynamicFields := map[string]string{
			"kind": "dynamic select-related discriminator",
		}
		for _, relation := range source.relations {
			if relation.selector == "SelectRelated" {
				return fmt.Errorf("relation selector SelectRelated for %s.%s conflicts with the select-related factory method", identity, relation.field.Name)
			}
			if relation.field.Nullable {
				if previous, duplicate := factoryMembers[relation.selector]; duplicate {
					return fmt.Errorf("object factory member %s for %s.%s conflicts with %s", relation.selector, identity, relation.field.Name, previous)
				}
				factoryMembers[relation.selector] = relation.field.Name
			}
			if previous, duplicate := builderMethods[relation.selector]; duplicate {
				return fmt.Errorf("select-related method %s for %s.%s conflicts with %s", relation.selector, identity, relation.field.Name, previous)
			}
			builderMethods[relation.selector] = relation.field.Name
			private := lowerFirst(relation.selector)
			if previous, duplicate := dynamicFields[private]; duplicate {
				return fmt.Errorf("dynamic select-related field %s for %s.%s conflicts with %s", private, identity, relation.field.Name, previous)
			}
			dynamicFields[private] = relation.field.Name
			if err := add(
				source.surface+relation.selector+"SelectRelatedQuery",
				"select-related query for "+identity+"."+relation.field.Name,
			); err != nil {
				return err
			}
		}
	}
	return nil
}

func projectRelationSelectRelatedUsedModels(
	models []*projectRelationObjectModel,
	sources []projectRelationObjectSource,
) []*projectRelationObjectModel {
	used := make(map[*projectRelationObjectModel]struct{})
	for index := range sources {
		used[sources[index].model] = struct{}{}
		for relationIndex := range sources[index].relations {
			used[sources[index].relations[relationIndex].target] = struct{}{}
		}
	}
	result := make([]*projectRelationObjectModel, 0, len(used))
	for _, model := range models {
		if _, ok := used[model]; ok {
			result = append(result, model)
		}
	}
	return result
}

func projectRelationSelectRelatedUsedApps(
	apps []normalizedRelationObjectPackage,
	models []*projectRelationObjectModel,
) []normalizedRelationObjectPackage {
	used := make(map[string]struct{})
	for _, model := range models {
		used[model.app.schema.AppLabel] = struct{}{}
	}
	result := make([]normalizedRelationObjectPackage, 0, len(used))
	for _, app := range apps {
		if _, ok := used[app.schema.AppLabel]; ok {
			result = append(result, app)
		}
	}
	return result
}

func renderProjectRelationSelectRelatedSource(output *bytes.Buffer, source projectRelationObjectSource) {
	sourceType := source.model.app.alias + "." + source.model.model.GoName
	builderType := source.surface + "SelectRelated"
	dynamicType := source.surface + "DynamicSelectRelatedQuery"

	fmt.Fprintf(output, "type %s struct {\n", builderType)
	fmt.Fprintf(output, "\tfactory %s\n", source.factoryType)
	fmt.Fprintf(output, "\tsource  orm.QuerySet[%s]\n", sourceType)
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(
		output,
		"func (_factory %s) SelectRelated(_source orm.QuerySet[%s]) %s {\n",
		source.factoryType,
		sourceType,
		builderType,
	)
	fmt.Fprintf(output, "\treturn %s{factory: _factory, source: _source}\n", builderType)
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	for _, relation := range source.relations {
		renderProjectRelationSelectRelatedEdge(output, source, relation, builderType)
	}

	fmt.Fprintf(output, "type %s struct {\n", dynamicType)
	fmt.Fprintln(output, "\tkind uint8")
	for _, relation := range source.relations {
		fmt.Fprintf(
			output,
			"\t%s %s\n",
			lowerFirst(relation.selector),
			source.surface+relation.selector+"SelectRelatedQuery",
		)
	}
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(
		output,
		"func (_selection %s) ParseDynamic(_path string) (%s, error) {\n",
		builderType,
		dynamicType,
	)
	fmt.Fprintln(output, "\t_resolved, _err := orm.ResolveForwardSelectPath(_selection.factory.model, _path)")
	fmt.Fprintln(output, "\tif _err != nil {")
	fmt.Fprintf(output, "\t\treturn %s{}, _err\n", dynamicType)
	fmt.Fprintln(output, "\t}")
	fmt.Fprintln(output, "\tswitch _path {")
	for index, relation := range source.relations {
		binder := "orm.BindRequiredForwardSelect"
		if relation.field.Nullable {
			binder = "orm.BindNullableForwardSelect"
		}
		queryType := source.surface + relation.selector + "SelectRelatedQuery"
		private := lowerFirst(relation.selector)
		fmt.Fprintf(output, "\tcase %s:\n", strconv.Quote(relation.field.Name))
		fmt.Fprintf(
			output,
			"\t\t_relation, _err := %s(_resolved, _selection.factory.%s)\n",
			binder,
			private,
		)
		fmt.Fprintln(output, "\t\tif _err != nil {")
		fmt.Fprintf(output, "\t\t\treturn %s{}, _err\n", dynamicType)
		fmt.Fprintln(output, "\t\t}")
		fmt.Fprintf(output, "\t\t_query := %s{\n", queryType)
		fmt.Fprintln(output, "\t\t\tfactory: _selection.factory,")
		fmt.Fprintln(output, "\t\t\tquery:   _relation.Select(_selection.source),")
		fmt.Fprintln(output, "\t\t}")
		fmt.Fprintf(
			output,
			"\t\treturn %s{kind: %d, %s: _query}, nil\n",
			dynamicType,
			index+1,
			private,
		)
	}
	fmt.Fprintln(output, "\tdefault:")
	fmt.Fprintf(output, "\t\treturn %s{}, &query.Error{\n", dynamicType)
	fmt.Fprintln(output, "\t\t\tCategory: query.CategoryQuery,")
	fmt.Fprintln(output, "\t\t\tCode:     query.CodeInvalidPlan,")
	fmt.Fprintln(output, "\t\t\tDetail:   \"resolved forward selection is missing generated dispatch\",")
	fmt.Fprintln(output, "\t\t}")
	fmt.Fprintln(output, "\t}")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(output, "func (_query %s) All(_ctx context.Context) ([]*%s, error) {\n", dynamicType, source.objectType)
	fmt.Fprintln(output, "\tswitch _query.kind {")
	for index, relation := range source.relations {
		fmt.Fprintf(output, "\tcase %d:\n", index+1)
		fmt.Fprintf(output, "\t\treturn _query.%s.All(_ctx)\n", lowerFirst(relation.selector))
	}
	fmt.Fprintln(output, "\tdefault:")
	fmt.Fprintln(output, "\t\treturn nil, &query.Error{")
	fmt.Fprintln(output, "\t\t\tCategory: query.CategoryQuery,")
	fmt.Fprintln(output, "\t\t\tCode:     query.CodeInvalidPlan,")
	fmt.Fprintln(output, "\t\t\tDetail:   \"generated dynamic select-related query is zero or corrupt\",")
	fmt.Fprintln(output, "\t\t}")
	fmt.Fprintln(output, "\t}")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
}

func renderProjectRelationSelectRelatedEdge(
	output *bytes.Buffer,
	source projectRelationObjectSource,
	relation projectRelationObjectEdge,
	builderType string,
) {
	sourceType := source.model.app.alias + "." + source.model.model.GoName
	targetType := relation.target.app.alias + "." + relation.target.model.GoName
	queryType := source.surface + relation.selector + "SelectRelatedQuery"
	binder := "orm.BindRequiredForwardSelect"
	if relation.field.Nullable {
		binder = "orm.BindNullableForwardSelect"
	}

	fmt.Fprintf(output, "type %s struct {\n", queryType)
	fmt.Fprintf(output, "\tfactory          %s\n", source.factoryType)
	fmt.Fprintf(output, "\tquery            orm.ForwardSelectQuery[%s, %s]\n", sourceType, targetType)
	fmt.Fprintln(output, "\tconfigurationErr error")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(output, "func (_selection %s) %s() %s {\n", builderType, relation.selector, queryType)
	fmt.Fprintf(
		output,
		"\t_path, _err := orm.ResolveForwardSelectPath(_selection.factory.model, %s)\n",
		strconv.Quote(relation.field.Name),
	)
	fmt.Fprintln(output, "\tif _err != nil {")
	fmt.Fprintf(output, "\t\treturn %s{configurationErr: _err}\n", queryType)
	fmt.Fprintln(output, "\t}")
	fmt.Fprintf(
		output,
		"\t_relation, _err := %s(_path, _selection.factory.%s)\n",
		binder,
		lowerFirst(relation.selector),
	)
	fmt.Fprintln(output, "\tif _err != nil {")
	fmt.Fprintf(output, "\t\treturn %s{configurationErr: _err}\n", queryType)
	fmt.Fprintln(output, "\t}")
	fmt.Fprintf(output, "\treturn %s{\n", queryType)
	fmt.Fprintln(output, "\t\tfactory: _selection.factory,")
	fmt.Fprintln(output, "\t\tquery:   _relation.Select(_selection.source),")
	fmt.Fprintln(output, "\t}")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(output, "func (_query %s) All(_ctx context.Context) ([]*%s, error) {\n", queryType, source.objectType)
	fmt.Fprintln(output, "\tif _query.configurationErr != nil {")
	fmt.Fprintf(output, "\t\t_, _contextErr := (orm.ForwardSelectQuery[%s, %s]{}).All(_ctx)\n", sourceType, targetType)
	fmt.Fprintln(output, "\t\tif _contextErr == nil {")
	fmt.Fprintln(output, "\t\t\treturn nil, _query.configurationErr")
	fmt.Fprintln(output, "\t\t}")
	fmt.Fprintln(output, "\t\t_terminalErr, _ok := _contextErr.(*query.Error)")
	fmt.Fprintln(output, "\t\tif _ok && _terminalErr.Category == query.CategoryBackend && _terminalErr.Code == query.CodeInvalidPlan {")
	fmt.Fprintln(output, "\t\t\treturn nil, _query.configurationErr")
	fmt.Fprintln(output, "\t\t}")
	fmt.Fprintln(output, "\t\treturn nil, _contextErr")
	fmt.Fprintln(output, "\t}")
	fmt.Fprintln(output, "\t_selected, _err := _query.query.All(_ctx)")
	fmt.Fprintln(output, "\tif _err != nil {")
	fmt.Fprintln(output, "\t\treturn nil, _err")
	fmt.Fprintln(output, "\t}")
	fmt.Fprintf(output, "\t_results := make([]*%s, len(_selected))\n", source.objectType)
	fmt.Fprintln(output, "\tfor _index := range _selected {")
	fmt.Fprintln(output, "\t\t_source, _err := _selected[_index].Source()")
	fmt.Fprintln(output, "\t\tif _err != nil {")
	fmt.Fprintln(output, "\t\t\treturn nil, _err")
	fmt.Fprintln(output, "\t\t}")
	fmt.Fprintln(output, "\t\t_related, _err := _selected[_index].Related()")
	fmt.Fprintln(output, "\t\tif _err != nil {")
	fmt.Fprintln(output, "\t\t\treturn nil, _err")
	fmt.Fprintln(output, "\t\t}")
	fmt.Fprintln(output, "\t\t_object, _err := _query.factory.From(_query.query.Backend(), _source)")
	fmt.Fprintln(output, "\t\tif _err != nil {")
	fmt.Fprintln(output, "\t\t\treturn nil, _err")
	fmt.Fprintln(output, "\t\t}")
	fmt.Fprintf(output, "\t\t_object.%s = _related\n", lowerFirst(relation.selector))
	fmt.Fprintln(output, "\t\t_results[_index] = _object")
	fmt.Fprintln(output, "\t}")
	fmt.Fprintln(output, "\treturn _results, nil")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
}
