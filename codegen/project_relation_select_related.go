const ProjectRelationSelectRelatedGeneratorVersion = "godj-codegen-rel-select-related-project-current-v6"

// GenerateProjectRelationSelectRelated renders the current project-only
// select-related companion. It attaches a composable builder to the existing
// relation-object factory; it does not create another project binding root.
func GenerateProjectRelationSelectRelated(
	packageName string,
	packages []RelationObjectPackage,
) ([]byte, error) {
	if !validGeneratedPackageName(packageName) {
		return nil, fmt.Errorf("invalid generated package name %q", packageName)
	}
	canonical, err := canonicalRelationObjectPackages(packages)
	if err != nil {
		return nil, err
	}
	return generateProjectCompanion(packageName, newRelationProjectPlan(canonical), companionSelect)
}

func generateProjectRelationSelectRelated(packageName string, plan *relationProjectPlan) ([]byte, error) {
	canonical := plan.apps
	if err := validateProjectRelationSelectRelatedImports(canonical); err != nil {
		return nil, err
	}
	models, sources, err := plan.objectSurface()
	if err != nil {
		return nil, err
	}
	usedModels := projectRelationSelectRelatedUsedModels(models, sources)
	usedApps := projectRelationSelectRelatedUsedApps(canonical, usedModels)

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by GoDj. DO NOT EDIT.")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "package %s\n\n", packageName)
	if len(sources) > 0 {
		fmt.Fprintln(&output, "import (")
		fmt.Fprintln(&output, "\tcontext \"context\"")
		fmt.Fprintln(&output, `strings "strings"`)
		for _, app := range usedApps {
			fmt.Fprintf(&output, "\t%s %s\n", app.alias, strconv.Quote(app.importPath))
		}
		fmt.Fprintln(&output, "\torm \"github.com/progresshans/godj/orm\"")
		fmt.Fprintln(&output, "\tquery \"github.com/progresshans/godj/query\"")
		fmt.Fprintln(&output, ")")
		fmt.Fprintln(&output)
	}
	fmt.Fprintf(
		&output,
		"const GoDjProjectRelationSelectRelatedGeneratorVersion = %s\n\n",
		strconv.Quote(ProjectRelationSelectRelatedGeneratorVersion),
	)
	for _, model := range usedModels {
		fmt.Fprintf(
			&output,
			"var _ orm.ProjectionDescriptor[%s.%s] = %s.%sDescriptor{}\n",
			model.app.alias,
			model.model.GoName,
			model.app.alias,
			model.model.GoName,
		)
	}
	if len(usedModels) > 0 {
		fmt.Fprintln(&output)
	}
	if len(sources) > 0 {
		fmt.Fprintln(&output, "type relationSelectQuery[O any] interface {")
		fmt.Fprintln(&output, "\tAll(context.Context) ([]*O, error)")
		fmt.Fprintln(&output, "\tCount(context.Context) (int64, error)")
		fmt.Fprintln(&output, "\tFirst(context.Context) (*O, bool, error)")
		fmt.Fprintln(&output, "}")
		fmt.Fprintln(&output)
	}

	for _, source := range sources {
		renderProjectRelationSelectRelatedSource(&output, source)
	}

	return output.Bytes(), nil
}

func validateProjectRelationSelectRelatedImports(apps []normalizedRelationPackage) error {
	for _, app := range apps {
		switch app.alias {
		case "append", "int", "any", "context", "strings", "sql", "db", "orm", "query", "ir", "int64", "len", "make", "string", "uint8":
			return fmt.Errorf("invalid relation select-related package alias %q", app.alias)
		}
		switch app.importPath {
		case "context", "strings", "database/sql", "github.com/progresshans/godj/db", "github.com/progresshans/godj/orm", "github.com/progresshans/godj/query", "github.com/progresshans/godj/schema/ir":
			return fmt.Errorf("reserved relation select-related import path %q", app.importPath)
		}
	}
	return nil
}

func projectRelationSelectRelatedUsedModels(
	models []*projectRelationModel,
	sources []projectRelationObjectSource,
) []*projectRelationModel {
	used := make(map[*projectRelationModel]struct{})
	for index := range sources {
		used[sources[index].model] = struct{}{}
		for relationIndex := range sources[index].selections {
			used[sources[index].selections[relationIndex].target] = struct{}{}
		}
	}
	result := make([]*projectRelationModel, 0, len(used))
	for _, model := range models {
		if _, ok := used[model]; ok {
			result = append(result, model)
		}
	}
	return result
}

func projectRelationSelectRelatedUsedApps(
	apps []normalizedRelationPackage,
	models []*projectRelationModel,
) []normalizedRelationPackage {
	used := make(map[string]struct{})
	for _, model := range models {
		used[model.app.schema.AppLabel] = struct{}{}
	}
	result := make([]normalizedRelationPackage, 0, len(used))
	for _, app := range apps {
		if _, ok := used[app.schema.AppLabel]; ok {
			result = append(result, app)
		}
	}
	return result
}

