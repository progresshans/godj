package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"

	"github.com/progresshans/godj/schema/ir"
)

const RelationObjectGeneratorVersion = "godj-codegen-rel-object-v1"

// GenerateRelationObject renders the relation-key storage companion for the
// descriptor published by the current main generator.
func GenerateRelationObject(packageName string, input ir.Schema) ([]byte, error) {
	if !validGeneratedPackageName(packageName) {
		return nil, fmt.Errorf("invalid generated package name %q", packageName)
	}
	schema, err := ir.Normalize(input.Clone())
	if err != nil {
		return nil, fmt.Errorf("normalize relation object schema: %w", err)
	}
	if err := validateGeneratedNames(schema); err != nil {
		return nil, fmt.Errorf("validate object prerequisite names: %w", err)
	}
	if err := validateRelationMetadataNames(schema); err != nil {
		return nil, fmt.Errorf("validate object metadata names: %w", err)
	}
	if err := validateRelationObjectNames(schema); err != nil {
		return nil, fmt.Errorf("validate relation object names: %w", err)
	}
	hash, err := ir.Hash(schema)
	if err != nil {
		return nil, fmt.Errorf("hash relation object schema: %w", err)
	}

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by GoDj. DO NOT EDIT.")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "package %s\n\n", packageName)
	fmt.Fprintln(&output, "import (")
	if hasRelationObjectStorage(schema) {
		fmt.Fprintln(&output, "\t\"reflect\"")
	}
	fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/orm\"")
	if hasRelationObjectStorage(schema) {
		fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/query\"")
	}
	fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/schema/ir\"")
	fmt.Fprintln(&output, ")")
	fmt.Fprintln(&output)
	fmt.Fprintf(
		&output,
		"const GoDjRelationObjectGeneratorVersion = %s\n",
		strconv.Quote(RelationObjectGeneratorVersion),
	)
	fmt.Fprintf(&output, "const GoDjRelationObjectSchemaSHA256 = %s\n\n", strconv.Quote(hash))

	for modelIndex, model := range schema.Models {
		renderRelationObjectModel(&output, model, modelIndex)
	}

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated relation object companion: %w", err)
	}
	return formatted, nil
}

func validateRelationObjectNames(schema ir.Schema) error {
	packageSymbols := map[string]string{}
	add := func(symbol, owner string) error {
		if previous, exists := packageSymbols[symbol]; exists {
			return fmt.Errorf("package symbol %s for %s conflicts with %s", symbol, owner, previous)
		}
		packageSymbols[symbol] = owner
		return nil
	}

	fixed := []struct {
		symbol string
		owner  string
	}{
		{symbol: "GoDjGeneratorVersion", owner: "main generator provenance constant"},
		{symbol: "GoDjSchemaSHA256", owner: "main schema provenance constant"},
		{symbol: "GoDjRelationMetadataGeneratorVersion", owner: "relation metadata provenance constant"},
		{symbol: "GoDjRelationSchemaSHA256", owner: "relation schema provenance constant"},
		{symbol: "GoDjRelationSchema", owner: "relation schema accessor"},
		{symbol: "GoDjRelationObjectGeneratorVersion", owner: "relation object provenance constant"},
		{symbol: "GoDjRelationObjectSchemaSHA256", owner: "relation object schema provenance constant"},
	}
	for _, candidate := range fixed {
		if err := add(candidate.symbol, candidate.owner); err != nil {
			return err
		}
	}

	for _, model := range schema.Models {
		owner := "model " + model.GoName
		symbols := []string{
			model.GoName,
			model.GoName + "Descriptor",
			model.GoName + "FieldSet",
			model.GoName + "Fields",
			model.GoName + "Objects",
			model.GoName + "Create",
			model.GoName + "Patch",
			"New" + model.GoName + "Create",
			model.GoName + "UpdateFields",
			model.GoName + "UpdateFieldNames",
			model.GoName + "ForceInsert",
			model.GoName + "ForceUpdate",
			lowerFirst(model.GoName) + "Metadata",
		}
		if key, ok := primaryKey(model); ok {
			symbols = append(symbols, "New"+model.GoName+"With"+key.GoName)
		}
		for _, symbol := range symbols {
			if err := add(symbol, owner); err != nil {
				return err
			}
		}
		for _, field := range model.Fields {
			if field.Kind != ir.FieldForeignKey {
				continue
			}
			storage := relationObjectStorageName(model, field)
			if err := add(storage, "relation storage "+model.GoName+"."+field.GoName); err != nil {
				return err
			}
		}
	}
	return nil
}

func renderRelationObjectModel(output *bytes.Buffer, model ir.Model, modelIndex int) {
	descriptor := model.GoName + "Descriptor"
	relations := relationObjectFields(model)

	fmt.Fprintf(output, "var _ orm.RelationObjectDescriptor[%s] = %s{}\n\n", model.GoName, descriptor)
	fmt.Fprintf(
		output,
		"func (%s) SnapshotRelationObjectDescriptor() orm.RelationObjectDescriptor[%s] {\n",
		descriptor,
		model.GoName,
	)
	fmt.Fprintf(output, "\treturn %s{}\n", descriptor)
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(
		output,
		"func (%s) BindRelationStorage(field ir.Field) (orm.RelationStorage[%s], bool) {\n",
		descriptor,
		model.GoName,
	)
	if len(relations) == 0 {
		fmt.Fprintln(output, "\treturn nil, false")
	} else {
		fmt.Fprintln(output, "\tswitch {")
		for _, field := range relations {
			storage := relationObjectStorageName(model, field)
			fmt.Fprintf(output, "\tcase reflect.DeepEqual(field, (%s{}).Field()):\n", storage)
			fmt.Fprintf(output, "\t\treturn %s{}, true\n", storage)
		}
		fmt.Fprintln(output, "\tdefault:")
		fmt.Fprintln(output, "\t\treturn nil, false")
		fmt.Fprintln(output, "\t}")
	}
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	for _, field := range relations {
		storage := relationObjectStorageName(model, field)
		fieldIndex := fieldPosition(model, field)
		fmt.Fprintf(output, "type %s struct{}\n\n", storage)
		fmt.Fprintf(output, "var _ orm.RelationStorage[%s] = %s{}\n\n", model.GoName, storage)
		fmt.Fprintf(output, "func (%s) Field() ir.Field {\n", storage)
		fmt.Fprintln(output, "\tschema := GoDjRelationSchema()")
		fmt.Fprintf(output, "\treturn schema.Models[%d].Fields[%d].Clone()\n", modelIndex, fieldIndex)
		fmt.Fprintln(output, "}")
		fmt.Fprintln(output)
		fmt.Fprintf(output, "func (%s) Value(value %s) (query.Value, bool) {\n", storage, model.GoName)
		if field.Nullable {
			fmt.Fprintf(output, "\tif value.%s == nil {\n", field.GoName)
			fmt.Fprintln(output, "\t\treturn query.Null(), true")
			fmt.Fprintln(output, "\t}")
			fmt.Fprintf(output, "\treturn query.Integer(*value.%s), true\n", field.GoName)
		} else {
			fmt.Fprintf(output, "\treturn query.Integer(value.%s), true\n", field.GoName)
		}
		fmt.Fprintln(output, "}")
		fmt.Fprintln(output)
	}
}

func relationObjectFields(model ir.Model) []ir.Field {
	result := make([]ir.Field, 0)
	for _, field := range model.Fields {
		if field.Kind == ir.FieldForeignKey {
			result = append(result, field.Clone())
		}
	}
	return result
}

func hasRelationObjectStorage(schema ir.Schema) bool {
	for _, model := range schema.Models {
		if len(relationObjectFields(model)) > 0 {
			return true
		}
	}
	return false
}

func relationObjectStorageName(model ir.Model, field ir.Field) string {
	return lowerFirst(model.GoName) + field.GoName + "RelationStorage"
}
