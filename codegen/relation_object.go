package codegen

import (
	"bytes"
	"fmt"
	"strconv"

	"github.com/progresshans/godj/schema/ir"
)

const RelationObjectGeneratorVersion = "godj-codegen-rel-object-v1"

// GenerateRelationObject renders the relation-key storage companion for the
// descriptor published by the current main generator.
func GenerateRelationObject(packageName string, input ir.Schema) ([]byte, error) {
	if !validGeneratedPackageName(packageName) {
		return nil, fmt.Errorf("invalid generated package name %q", packageName)
	}
	prepared, err := prepareSchema(input)
	if err != nil {
		return nil, fmt.Errorf("normalize relation object schema: %w", err)
	}
	return generateAppCompanion(packageName, prepared, appObject)
}

func generateRelationObject(packageName string, prepared preparedSchema) ([]byte, error) {
	schema, hash := prepared.schema, prepared.hash

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by GoDj. DO NOT EDIT.")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "package %s\n\n", packageName)
	fmt.Fprintln(&output, "import (")
	if hasRelationObjectStorage(schema) {
		fmt.Fprintln(&output, "\t\"reflect\"")
	}
	fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/orm\"")
	if hasRelationObjectStorage(schema) {
		fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/query\"")
	}
	fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/schema/ir\"")
	fmt.Fprintln(&output, ")")
	fmt.Fprintln(&output)
	fmt.Fprintf(
		&output,
		"const GoDjRelationObjectGeneratorVersion = %s\n",
		strconv.Quote(RelationObjectGeneratorVersion),
	)
	fmt.Fprintf(&output, "const GoDjRelationObjectSchemaSHA256 = %s\n\n", strconv.Quote(hash))

	for _, model := range schema.Models {
		renderRelationObjectModel(&output, model)
	}

	return output.Bytes(), nil
}

func renderRelationObjectModel(output *bytes.Buffer, model ir.Model) {
	descriptor := model.GoName + "Descriptor"
	relations := relationObjectFields(model)

	fmt.Fprintf(output, "var _ orm.RelationObjectDescriptor[%s] = %s{}\n\n", model.GoName, descriptor)
	fmt.Fprintf(
		output,
		"func (%s) SnapshotRelationObjectDescriptor() orm.RelationObjectDescriptor[%s] {\n",
		descriptor,
		model.GoName,
	)
	fmt.Fprintf(output, "\treturn %s{}\n", descriptor)
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(
		output,
		"func (%s) BindRelationStorage(field ir.Field) (orm.RelationStorage[%s], bool) {\n",
		descriptor,
		model.GoName,
	)
	if len(relations) == 0 {
		fmt.Fprintln(output, "\treturn nil, false")
	} else {
		fmt.Fprintln(output, "\tswitch {")
		for _, field := range relations {
			storage := relationObjectStorageName(model, field)
			fmt.Fprintf(output, "\tcase reflect.DeepEqual(field, (%s{}).Field()):\n", storage)
			fmt.Fprintf(output, "\t\treturn %s{}, true\n", storage)
		}
		fmt.Fprintln(output, "\tdefault:")
		fmt.Fprintln(output, "\t\treturn nil, false")
		fmt.Fprintln(output, "\t}")
	}
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	for _, field := range relations {
		storage := relationObjectStorageName(model, field)
		fmt.Fprintf(output, "type %s struct{}\n\n", storage)
		fmt.Fprintf(output, "var _ orm.RelationStorage[%s] = %s{}\n\n", model.GoName, storage)
		fmt.Fprintf(output, "func (%s) Field() ir.Field {\n", storage)
		fmt.Fprintln(output, "\treturn ir.Field{")
		renderFieldLiteralBody(output, field, "\t\t")
		fmt.Fprintln(output, "\t}")
		fmt.Fprintln(output, "}")
		fmt.Fprintln(output)
		fmt.Fprintf(output, "func (%s) Value(value %s) (query.Value, bool) {\n", storage, model.GoName)
		if field.Nullable {
			fmt.Fprintf(output, "\tif value.%s == nil {\n", field.GoName)
			fmt.Fprintln(output, "\t\treturn query.Null(), true")
			fmt.Fprintln(output, "\t}")
			fmt.Fprintf(output, "\treturn query.Integer(*value.%s), true\n", field.GoName)
		} else {
			fmt.Fprintf(output, "\treturn query.Integer(value.%s), true\n", field.GoName)
		}
		fmt.Fprintln(output, "}")
		fmt.Fprintln(output)
	}
}

func relationObjectFields(model ir.Model) []ir.Field {
	result := make([]ir.Field, 0)
	for _, field := range model.Fields {
		if field.Kind == ir.FieldForeignKey {
			result = append(result, field.Clone())
		}
	}
	return result
}

func hasRelationObjectStorage(schema ir.Schema) bool {
	for _, model := range schema.Models {
		if len(relationObjectFields(model)) > 0 {
			return true
		}
	}
	return false
}

func relationObjectStorageName(model ir.Model, field ir.Field) string {
	return lowerFirst(model.GoName) + field.GoName + "RelationStorage"
}
