const GeneratorVersion = "godj-codegen-current-v1"

func Generate(packageName string, input ir.Schema) ([]byte, error) {
	if !validGeneratedPackageName(packageName) {
		return nil, fmt.Errorf("invalid generated package name %q", packageName)
	}
	prepared, err := prepareSchema(input)
	if err != nil {
		return nil, fmt.Errorf("normalize codegen schema: %w", err)
	}
	return generateAppCompanion(packageName, prepared, appMain)
}

func generate(packageName string, prepared preparedSchema) ([]byte, error) {
	schema, hash := prepared.storage, prepared.hash

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by GoDj. DO NOT EDIT.")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "package %s\n\n", packageName)
	fmt.Fprintln(&output, "import (")
	if hasFloatDefault(schema) {
		fmt.Fprintln(&output, "\t_godjmath \"math\"")
	}
	if hasJSONStorage(schema) {
		fmt.Fprintln(&output, "\t_godjjson \"github.com/progresshans/godj/jsonvalue\"")
	}
	if hasUUIDStorage(schema) {
		fmt.Fprintln(&output, "\t_godjuuid \"github.com/progresshans/godj/uuid\"")
	}
	if hasDecimalStorage(schema) {
		fmt.Fprintln(&output, "\t_godjdecimal \"github.com/progresshans/godj/decimal\"")
	}
	if hasDurationStorage(schema) {
		fmt.Fprintln(&output, "\t_godjduration \"github.com/progresshans/godj/duration\"")
	}
	if hasTimeStorage(schema) {
		fmt.Fprintln(&output, "\t_godjclock \"github.com/progresshans/godj/clock\"")
	}
	if hasDateStorage(schema) {
		fmt.Fprintln(&output, "\t_godjcalendar \"github.com/progresshans/godj/calendar\"")
	}
	if hasDateTimeStorage(schema) {
		fmt.Fprintln(&output, "\t_godjtime \"time\"")
	}
	if hasNullableQueryStorage(schema) {
		fmt.Fprintln(&output, "\t\"database/sql\"")
	}
	fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/db\"")
	fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/orm\"")
	fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/query\"")
	fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/schema/ir\"")
	fmt.Fprintln(&output, ")")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "const GoDjGeneratorVersion = %s\n", strconv.Quote(GeneratorVersion))
	fmt.Fprintf(&output, "const GoDjSchemaSHA256 = %s\n\n", strconv.Quote(hash))

	for _, model := range schema.Models {
		renderModel(&output, model)
	}

	return output.Bytes(), nil
}

func hasNullableQueryStorage(schema ir.Schema) bool {
	for _, model := range schema.Models {
		for _, field := range model.Fields {
			if field.Nullable && field.Kind != ir.FieldDateTime && field.Kind != ir.FieldDate && (field.Kind != ir.FieldTime && field.Kind != ir.FieldDuration && field.Kind != ir.FieldFloat && field.Kind != ir.FieldDecimal && field.Kind != ir.FieldUUID && field.Kind != ir.FieldJSON) {
				return true
			}
		}
	}
	return false
}

