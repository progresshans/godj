func lowerFirst(value string) string {
	if value == "" {
		return value
	}
	first, size := utf8.DecodeRuneInString(value)
	return string(unicode.ToLower(first)) + value[size:]
}

func renderCanonicalValue(output *bytes.Buffer, model string, field ir.Field, value, indent string) {
	if field.Kind == ir.FieldDecimal {
		fmt.Fprintf(output, "%s%sCanonical, %sError := %s.Canonical()\n", indent, value, value, value)
		fmt.Fprintf(output, "%sif %sError != nil || !%sCanonical.Fits(%d, %d) { return orm.InvalidMutation[%s](&query.Error{Category:query.CategoryField, Code:query.CodeInvalidValue, Field:%s, Detail:\"decimal exceeds field precision or scale\"}) }\n", indent, value, value, field.Decimal.MaxDigits, field.Decimal.DecimalPlaces, model, strconv.Quote(field.Name))
		fmt.Fprintf(output, "%s%s = %sCanonical\n", indent, value, value)
		return
	}
	if field.Kind == ir.FieldDuration {
		fmt.Fprintf(output, "%sif !%s.Valid() { return orm.InvalidMutation[%s](&query.Error{Category:query.CategoryField, Code:query.CodeInvalidValue, Field:%s, Detail:\"duration must be normalized days and subday microseconds\"}) }\n", indent, value, model, strconv.Quote(field.Name))
		return
	}
	if field.Kind == ir.FieldTime {
		fmt.Fprintf(output, "%sif !%s.Valid() { return orm.InvalidMutation[%s](&query.Error{Category:query.CategoryField, Code:query.CodeInvalidValue, Field:%s, Detail:\"time must be a valid clock with microsecond precision\"}) }\n", indent, value, model, strconv.Quote(field.Name))
		return
	}
	if field.Kind == ir.FieldDate {
		fmt.Fprintf(output, "%sif !%s.Valid() { return orm.InvalidMutation[%s](&query.Error{Category:query.CategoryField, Code:query.CodeInvalidValue, Field:%s, Detail:\"date must be a valid Gregorian day in years 1 through 9999\"}) }\n", indent, value, model, strconv.Quote(field.Name))
		return
	}
	if field.Kind != ir.FieldDateTime {
		return
	}
	fmt.Fprintf(output, "%s%sCanonical, %sValid := query.DateTime(%s).DateTime()\n", indent, value, value, value)
	fmt.Fprintf(output, "%sif !%sValid { return orm.InvalidMutation[%s](&query.Error{Category:query.CategoryField, Code:query.CodeInvalidValue, Field:%s, Detail:\"datetime is outside the supported UTC year range\"}) }\n", indent, value, model, strconv.Quote(field.Name))
	fmt.Fprintf(output, "%s%s = %sCanonical\n", indent, value, value)
}
