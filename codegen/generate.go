// Package codegen renders normalized Schema IR into deterministic Go source.
// It imports only schema/ir at runtime; generated target packages remain out
// of the generator's import graph.
package codegen

import (
	"bytes"
	"fmt"
	"go/token"
	"strconv"
	"unicode"
	"unicode/utf8"

	"github.com/progresshans/godj/schema/ir"
)

const GeneratorVersion = "godj-codegen-current-v1"

func Generate(packageName string, input ir.Schema) ([]byte, error) {
	if !validGeneratedPackageName(packageName) {
		return nil, fmt.Errorf("invalid generated package name %q", packageName)
	}
	prepared, err := prepareSchema(input)
	if err != nil {
		return nil, fmt.Errorf("normalize codegen schema: %w", err)
	}
	return generateAppCompanion(packageName, prepared, appMain)
}

func generate(packageName string, prepared preparedSchema) ([]byte, error) {
	schema, hash := prepared.schema, prepared.hash

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by GoDj. DO NOT EDIT.")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "package %s\n\n", packageName)
	fmt.Fprintln(&output, "import (")
	if hasNullableQueryStorage(schema) {
		fmt.Fprintln(&output, "\t\"database/sql\"")
	}
	fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/db\"")
	fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/orm\"")
	fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/query\"")
	fmt.Fprintln(&output, "\t\"github.com/progresshans/godj/schema/ir\"")
	fmt.Fprintln(&output, ")")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "const GoDjGeneratorVersion = %s\n", strconv.Quote(GeneratorVersion))
	fmt.Fprintf(&output, "const GoDjSchemaSHA256 = %s\n\n", strconv.Quote(hash))

	for _, model := range schema.Models {
		renderModel(&output, model)
	}

	return output.Bytes(), nil
}

func hasNullableQueryStorage(schema ir.Schema) bool {
	for _, model := range schema.Models {
		for _, field := range model.Fields {
			if field.Nullable {
				return true
			}
		}
	}
	return false
}

func validGeneratedPackageName(name string) bool {
	return name != "_" && token.IsIdentifier(name) && !token.Lookup(name).IsKeyword()
}

func renderModel(output *bytes.Buffer, model ir.Model) {
	fmt.Fprintf(output, "type %s struct {\n", model.GoName)
	for _, field := range model.Fields {
		fmt.Fprintf(output, "\t%s %s\n", field.GoName, goType(field))
	}
	if _, ok := primaryKey(model); ok {
		fmt.Fprintln(output, "\tgodjPrimaryKeyPresent bool")
	}
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	descriptorName := model.GoName + "Descriptor"
	metadataFunction := lowerFirst(model.GoName) + "Metadata"
	fieldSetName := model.GoName + "FieldSet"
	fieldsName := model.GoName + "Fields"
	objectsName := model.GoName + "Objects"

	fmt.Fprintf(output, "type %s struct{}\n\n", descriptorName)
	fmt.Fprintf(output, "var _ orm.ModelDescriptor[%s] = %s{}\n\n", model.GoName, descriptorName)
	fmt.Fprintf(output, "var _ orm.WriteDescriptor[%s] = %s{}\n\n", model.GoName, descriptorName)
	fmt.Fprintf(output, "func (%s) Metadata() ir.Model {\n\treturn %s()\n}\n\n", descriptorName, metadataFunction)
	fmt.Fprintf(output, "func (%s) Scan(row db.Row) (%s, error) {\n", descriptorName, model.GoName)
	fmt.Fprintf(output, "\tvar value %s\n", model.GoName)
	for _, field := range model.Fields {
		if field.Nullable {
			fmt.Fprintf(output, "\tvar scan%s %s\n", field.GoName, fieldRenderKind(field.Kind).sqlHolder)
		}
	}
	fmt.Fprint(output, "\tif err := row.Scan(")
	for index, field := range model.Fields {
		if index > 0 {
			fmt.Fprint(output, ", ")
		}
		if field.Nullable {
			fmt.Fprintf(output, "&scan%s", field.GoName)
		} else {
			fmt.Fprintf(output, "&value.%s", field.GoName)
		}
	}
	fmt.Fprintf(output, "); err != nil {\n\t\treturn %s{}, err\n\t}\n", model.GoName)
	for _, field := range model.Fields {
		if field.Nullable {
			fmt.Fprintf(output, "\tif scan%s.Valid {\n", field.GoName)
			fmt.Fprintf(output, "\t\tscanned := scan%s.%s\n", field.GoName, fieldRenderKind(field.Kind).sqlValue)
			fmt.Fprintf(output, "\t\tvalue.%s = &scanned\n", field.GoName)
			fmt.Fprintln(output, "\t}")
		}
	}
	if _, ok := primaryKey(model); ok {
		fmt.Fprintln(output, "\tvalue.godjPrimaryKeyPresent = true")
	}
	fmt.Fprintln(output, "\treturn value, nil")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	if key, ok := primaryKey(model); ok {
		fmt.Fprintf(output, "func (%s) PrimaryKey(value %s) (query.Value, bool) {\n", descriptorName, model.GoName)
		fmt.Fprintf(output, "\treturn query.Integer(value.%s), value.godjPrimaryKeyPresent\n", key.GoName)
		fmt.Fprintln(output, "}")
		fmt.Fprintln(output)
		fmt.Fprintf(output, "func (%s) SetPrimaryKey(value *%s, key int64) {\n", descriptorName, model.GoName)
		fmt.Fprintf(output, "\tvalue.%s = key\n", key.GoName)
		fmt.Fprintln(output, "\tvalue.godjPrimaryKeyPresent = true")
		fmt.Fprintln(output, "}")
		fmt.Fprintln(output)
		fmt.Fprintf(output, "func (%s) ClearPrimaryKey(value *%s) {\n", descriptorName, model.GoName)
		fmt.Fprintf(output, "\tvalue.%s = 0\n", key.GoName)
		fmt.Fprintln(output, "\tvalue.godjPrimaryKeyPresent = false")
		fmt.Fprintln(output, "}")
		fmt.Fprintln(output)
	}

	fmt.Fprintf(output, "func (%s) CloneModel(value %s) %s {\n", descriptorName, model.GoName, model.GoName)
	fmt.Fprintln(output, "\tclone := value")
	for _, field := range model.Fields {
		if field.Nullable {
			fmt.Fprintf(output, "\tif value.%s != nil {\n", field.GoName)
			fmt.Fprintf(output, "\t\tcloned%s := *value.%s\n", field.GoName, field.GoName)
			fmt.Fprintf(output, "\t\tclone.%s = &cloned%s\n", field.GoName, field.GoName)
			fmt.Fprintln(output, "\t}")
		}
	}
	fmt.Fprintln(output, "\treturn clone")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	fmt.Fprintf(output, "func (descriptor %s) CloneWriteModel(value %s) %s {\n", descriptorName, model.GoName, model.GoName)
	fmt.Fprintln(output, "\treturn descriptor.CloneModel(value)")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	fmt.Fprintf(output, "func (%s) WriteFieldValue(value %s, field ir.Field) (query.Value, bool) {\n", descriptorName, model.GoName)
	fmt.Fprintln(output, "\tswitch field.Name {")
	for _, field := range model.Fields {
		fmt.Fprintf(output, "\tcase %s:\n", strconv.Quote(field.Name))
		if field.Nullable {
			fmt.Fprintf(output, "\t\tif value.%s == nil {\n", field.GoName)
			fmt.Fprintln(output, "\t\t\treturn query.Null(), true")
			fmt.Fprintln(output, "\t\t}")
			fmt.Fprintf(output, "\t\treturn %s, true\n", queryValueExpression(field, "*value."+field.GoName))
			continue
		}
		fmt.Fprintf(output, "\t\treturn %s, true\n", queryValueExpression(field, "value."+field.GoName))
	}
	fmt.Fprintln(output, "\tdefault:")
	fmt.Fprintln(output, "\t\treturn query.Value{}, false")
	fmt.Fprintln(output, "\t}")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	fmt.Fprintf(output, "type %s struct {\n", fieldSetName)
	for _, field := range model.Fields {
		if field.Kind == ir.FieldForeignKey {
			continue
		}
		fmt.Fprintf(output, "\t%s %s\n", field.GoName, ormFieldType(model.GoName, field))
	}
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	fmt.Fprintf(output, "var %s = func() %s {\n", fieldsName, fieldSetName)
	fmt.Fprintf(output, "\tmetadata := %s()\n", metadataFunction)
	fmt.Fprintf(output, "\treturn %s{\n", fieldSetName)
	for index, field := range model.Fields {
		if field.Kind == ir.FieldForeignKey {
			continue
		}
		fmt.Fprintf(output, "\t\t%s: %s(metadata.Fields[%d]),\n", field.GoName, ormFieldConstructor(model.GoName, field), index)
	}
	fmt.Fprintln(output, "\t}")
	fmt.Fprintln(output, "}()")
	fmt.Fprintln(output)
	fmt.Fprintf(output, "var %s = orm.NewManager[%s](%s{})\n\n", objectsName, model.GoName, descriptorName)
	renderSaveBindings(output, model)
	renderWriteInputs(output, model)

	fmt.Fprintf(output, "func %s() ir.Model {\n", metadataFunction)
	fmt.Fprintln(output, "\treturn ir.Model{")
	renderModelLiteralBody(output, model, "\t\t")
	fmt.Fprintln(output, "\t}")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
}

func renderSaveBindings(output *bytes.Buffer, model ir.Model) {
	key, ok := primaryKey(model)
	if !ok {
		return
	}

	fmt.Fprintf(output, "func New%sWith%s(key %s) %s {\n", model.GoName, key.GoName, scalarGoType(key), model.GoName)
	fmt.Fprintf(output, "\treturn %s{%s: key, godjPrimaryKeyPresent: true}\n", model.GoName, key.GoName)
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	fmt.Fprintf(output, "func %sUpdateFields(fields ...orm.WritableField[%s]) orm.SaveOption[%s] {\n", model.GoName, model.GoName, model.GoName)
	fmt.Fprintln(output, "\treturn orm.UpdateFields(fields...)")
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	fmt.Fprintf(output, "func %sUpdateFieldNames(names ...string) orm.SaveOption[%s] {\n", model.GoName, model.GoName)
	fmt.Fprintf(output, "\treturn orm.UpdateFieldNames[%s](names...)\n", model.GoName)
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	fmt.Fprintf(output, "func %sForceInsert() orm.SaveOption[%s] {\n", model.GoName, model.GoName)
	fmt.Fprintf(output, "\treturn orm.ForceInsert[%s]()\n", model.GoName)
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)

	fmt.Fprintf(output, "func %sForceUpdate() orm.SaveOption[%s] {\n", model.GoName, model.GoName)
	fmt.Fprintf(output, "\treturn orm.ForceUpdate[%s]()\n", model.GoName)
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
}

func renderWriteInputs(output *bytes.Buffer, model ir.Model) {
	fields := writableFields(model)
	createName := model.GoName + "Create"
	patchName := model.GoName + "Patch"

	renderWriteInputType(output, createName, fields)
	required := requiredCreateFields(fields)
	fmt.Fprintf(output, "func New%sCreate(", model.GoName)
	for index, field := range required {
		if index > 0 {
			fmt.Fprint(output, ", ")
		}
		fmt.Fprintf(output, "%s %s", privateName(field.GoName), scalarGoType(field))
	}
	fmt.Fprintf(output, ") %s {\n", createName)
	if len(required) == 0 {
		fmt.Fprintf(output, "\treturn %s{}\n", createName)
	} else {
		fmt.Fprintf(output, "\treturn %s{\n", createName)
		for _, field := range required {
			fmt.Fprintf(output, "\t\t%s: orm.Set(%s),\n", privateName(field.GoName), privateName(field.GoName))
		}
		fmt.Fprintln(output, "\t}")
	}
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
	renderWriteWithMethods(output, createName, fields)
	renderBuildCreate(output, model, createName, fields)

	renderWriteInputType(output, patchName, fields)
	renderWriteWithMethods(output, patchName, fields)
	renderBuildPatch(output, model, patchName, fields)
}

func renderWriteInputType(output *bytes.Buffer, typeName string, fields []ir.Field) {
	fmt.Fprintf(output, "type %s struct {\n", typeName)
	for _, field := range fields {
		wrapper := "orm.Change"
		if field.Nullable {
			wrapper = "orm.NullableChange"
		}
		fmt.Fprintf(output, "\t%s %s[%s]\n", privateName(field.GoName), wrapper, scalarGoType(field))
	}
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
}

func renderWriteWithMethods(output *bytes.Buffer, typeName string, fields []ir.Field) {
	for _, field := range fields {
		fieldName := privateName(field.GoName)
		fmt.Fprintf(output, "func (input %s) With%s(value %s) %s {\n", typeName, field.GoName, scalarGoType(field), typeName)
		if field.Nullable {
			fmt.Fprintf(output, "\tinput.%s = orm.SetNullable(value)\n", fieldName)
		} else {
			fmt.Fprintf(output, "\tinput.%s = orm.Set(value)\n", fieldName)
		}
		fmt.Fprintln(output, "\treturn input")
		fmt.Fprintln(output, "}")
		fmt.Fprintln(output)
		if field.Nullable {
			fmt.Fprintf(output, "func (input %s) With%sNull() %s {\n", typeName, field.GoName, typeName)
			fmt.Fprintf(output, "\tinput.%s = orm.SetNull[%s]()\n", fieldName, scalarGoType(field))
			fmt.Fprintln(output, "\treturn input")
			fmt.Fprintln(output, "}")
			fmt.Fprintln(output)
		}
	}
}

func renderBuildCreate(output *bytes.Buffer, model ir.Model, typeName string, fields []ir.Field) {
	fmt.Fprintf(output, "func (input %s) BuildCreate() orm.Mutation[%s] {\n", typeName, model.GoName)
	fmt.Fprintf(output, "\tvar value %s\n", model.GoName)
	fmt.Fprintf(output, "\tassignments := make([]query.Assignment, 0, %d)\n", len(fields))
	for _, field := range fields {
		reference := queryFieldReferenceLiteral(field)
		inputName := privateName(field.GoName)
		changedName := "changed" + field.GoName
		if !field.Nullable {
			fmt.Fprintf(output, "\t%s, %sSet := input.%s.Get()\n", changedName, changedName, inputName)
			if field.Default == nil {
				fmt.Fprintf(output, "\tif !%sSet {\n", changedName)
				renderRequiredFieldError(output, model.GoName, field, "\t\t")
				fmt.Fprintln(output, "\t}")
			} else {
				fmt.Fprintf(output, "\tif !%sSet {\n", changedName)
				fmt.Fprintf(output, "\t\t%s = %s\n", changedName, defaultValueExpression(*field.Default))
				fmt.Fprintln(output, "\t}")
			}
			fmt.Fprintf(output, "\tvalue.%s = %s\n", field.GoName, changedName)
			fmt.Fprintf(output, "\tassignments = append(assignments, query.NewAssignment(%s, %s))\n", reference, queryValueExpression(field, changedName))
			continue
		}

		fmt.Fprintf(output, "\t%s, %sState := input.%s.Get()\n", changedName, changedName, inputName)
		fmt.Fprintf(output, "\tswitch %sState {\n", changedName)
		fmt.Fprintln(output, "\tcase orm.NullableChangeUnset:")
		if field.Default == nil {
			fmt.Fprintf(output, "\t\tvalue.%s = nil\n", field.GoName)
			fmt.Fprintf(output, "\t\tassignments = append(assignments, query.NewAssignment(%s, query.Null()))\n", reference)
		} else {
			fmt.Fprintf(output, "\t\tdefault%s := %s\n", field.GoName, defaultValueExpression(*field.Default))
			fmt.Fprintf(output, "\t\tvalue.%s = &default%s\n", field.GoName, field.GoName)
			fmt.Fprintf(output, "\t\tassignments = append(assignments, query.NewAssignment(%s, %s))\n", reference, queryValueExpression(field, "default"+field.GoName))
		}
		fmt.Fprintln(output, "\tcase orm.NullableChangeValue:")
		fmt.Fprintf(output, "\t\tstored%s := %s\n", field.GoName, changedName)
		fmt.Fprintf(output, "\t\tvalue.%s = &stored%s\n", field.GoName, field.GoName)
		fmt.Fprintf(output, "\t\tassignments = append(assignments, query.NewAssignment(%s, %s))\n", reference, queryValueExpression(field, changedName))
		fmt.Fprintln(output, "\tcase orm.NullableChangeNull:")
		fmt.Fprintf(output, "\t\tvalue.%s = nil\n", field.GoName)
		fmt.Fprintf(output, "\t\tassignments = append(assignments, query.NewAssignment(%s, query.Null()))\n", reference)
		fmt.Fprintln(output, "\tdefault:")
		renderInvalidChangeState(output, model.GoName, field, "\t\t")
		fmt.Fprintln(output, "\t}")
	}
	fmt.Fprintf(output, "\treturn orm.NewCreateMutation(value, %s, assignments)\n", strconv.Quote(model.DBTable))
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
}

func renderBuildPatch(output *bytes.Buffer, model ir.Model, typeName string, fields []ir.Field) {
	fmt.Fprintf(output, "func (input %s) BuildPatch(current %s) orm.Mutation[%s] {\n", typeName, model.GoName, model.GoName)
	fmt.Fprintln(output, "\tvalue := current")
	fmt.Fprintf(output, "\tassignments := make([]query.Assignment, 0, %d)\n", len(fields))
	for _, field := range fields {
		reference := queryFieldReferenceLiteral(field)
		inputName := privateName(field.GoName)
		changedName := "changed" + field.GoName
		if !field.Nullable {
			fmt.Fprintf(output, "\tif %s, ok := input.%s.Get(); ok {\n", changedName, inputName)
			fmt.Fprintf(output, "\t\tvalue.%s = %s\n", field.GoName, changedName)
			fmt.Fprintf(output, "\t\tassignments = append(assignments, query.NewAssignment(%s, %s))\n", reference, queryValueExpression(field, changedName))
			fmt.Fprintln(output, "\t}")
			continue
		}

		fmt.Fprintf(output, "\t%s, %sState := input.%s.Get()\n", changedName, changedName, inputName)
		fmt.Fprintf(output, "\tswitch %sState {\n", changedName)
		fmt.Fprintln(output, "\tcase orm.NullableChangeUnset:")
		fmt.Fprintln(output, "\tcase orm.NullableChangeValue:")
		fmt.Fprintf(output, "\t\tstored%s := %s\n", field.GoName, changedName)
		fmt.Fprintf(output, "\t\tvalue.%s = &stored%s\n", field.GoName, field.GoName)
		fmt.Fprintf(output, "\t\tassignments = append(assignments, query.NewAssignment(%s, %s))\n", reference, queryValueExpression(field, changedName))
		fmt.Fprintln(output, "\tcase orm.NullableChangeNull:")
		fmt.Fprintf(output, "\t\tvalue.%s = nil\n", field.GoName)
		fmt.Fprintf(output, "\t\tassignments = append(assignments, query.NewAssignment(%s, query.Null()))\n", reference)
		fmt.Fprintln(output, "\tdefault:")
		renderInvalidChangeState(output, model.GoName, field, "\t\t")
		fmt.Fprintln(output, "\t}")
	}
	fmt.Fprintf(output, "\treturn orm.NewPatchMutation(value, %s, assignments)\n", strconv.Quote(model.DBTable))
	fmt.Fprintln(output, "}")
	fmt.Fprintln(output)
}

func renderRequiredFieldError(output *bytes.Buffer, modelName string, field ir.Field, indent string) {
	fmt.Fprintf(output, "%sreturn orm.InvalidMutation[%s](&query.Error{\n", indent, modelName)
	fmt.Fprintf(output, "%s\tCategory: query.CategoryField,\n", indent)
	fmt.Fprintf(output, "%s\tCode: query.CodeRequiredField,\n", indent)
	fmt.Fprintf(output, "%s\tField: %s,\n", indent, strconv.Quote(field.Name))
	fmt.Fprintf(output, "%s\tDetail: \"required create field is omitted\",\n", indent)
	fmt.Fprintf(output, "%s})\n", indent)
}

func renderInvalidChangeState(output *bytes.Buffer, modelName string, field ir.Field, indent string) {
	fmt.Fprintf(output, "%sreturn orm.InvalidMutation[%s](&query.Error{\n", indent, modelName)
	fmt.Fprintf(output, "%s\tCategory: query.CategoryQuery,\n", indent)
	fmt.Fprintf(output, "%s\tCode: query.CodeInvalidPlan,\n", indent)
	fmt.Fprintf(output, "%s\tField: %s,\n", indent, strconv.Quote(field.Name))
	fmt.Fprintf(output, "%s\tDetail: \"unknown nullable change state\",\n", indent)
	fmt.Fprintf(output, "%s})\n", indent)
}

func writableFields(model ir.Model) []ir.Field {
	fields := make([]ir.Field, 0, len(model.Fields))
	for _, field := range model.Fields {
		if !field.PrimaryKey {
			fields = append(fields, field)
		}
	}
	return fields
}

func requiredCreateFields(fields []ir.Field) []ir.Field {
	required := make([]ir.Field, 0, len(fields))
	for _, field := range fields {
		if !field.Nullable && field.Default == nil {
			required = append(required, field)
		}
	}
	return required
}

func primaryKey(model ir.Model) (ir.Field, bool) {
	for _, field := range model.Fields {
		if field.PrimaryKey {
			return field, true
		}
	}
	return ir.Field{}, false
}

func scalarGoType(field ir.Field) string {
	scalar := field
	scalar.Nullable = false
	return goType(scalar)
}

func privateName(goName string) string {
	name := lowerFirst(goName)
	if token.Lookup(name).IsKeyword() {
		return name + "Value"
	}
	return name
}

func queryValueExpression(field ir.Field, value string) string {
	kind := fieldRenderKind(field.Kind).queryValue
	if kind == "" {
		return "query.Value{}"
	}
	return "query." + kind + "(" + value + ")"
}

func defaultValueExpression(value ir.ScalarDefault) string {
	switch value.Kind {
	case ir.ScalarString:
		return strconv.Quote(value.String)
	case ir.ScalarBoolean:
		return strconv.FormatBool(value.Boolean)
	case ir.ScalarInteger:
		return strconv.FormatInt(value.Integer, 10)
	default:
		return "nil"
	}
}

func defaultLiteral(value ir.ScalarDefault) string {
	switch value.Kind {
	case ir.ScalarString:
		return fmt.Sprintf("&ir.ScalarDefault{Kind: ir.ScalarString, String: %s}", strconv.Quote(value.String))
	case ir.ScalarBoolean:
		return fmt.Sprintf("&ir.ScalarDefault{Kind: ir.ScalarBoolean, Boolean: %t}", value.Boolean)
	case ir.ScalarInteger:
		return fmt.Sprintf("&ir.ScalarDefault{Kind: ir.ScalarInteger, Integer: %d}", value.Integer)
	default:
		return "nil"
	}
}

func goType(field ir.Field) string {
	name := fieldRenderKind(field.Kind).goType
	if field.Nullable {
		return "*" + name
	}
	return name
}

func ormFieldType(model string, field ir.Field) string {
	name := fieldRenderKind(field.Kind).fieldType(field.Nullable)
	return fmt.Sprintf("orm.%s[%s]", name, model)
}

func ormFieldConstructor(model string, field ir.Field) string {
	name := fieldRenderKind(field.Kind).fieldType(field.Nullable)
	return fmt.Sprintf("orm.New%s[%s]", name, model)
}

func irKind(kind ir.FieldKind) string {
	return fieldRenderKind(kind).irKind
}

func lowerFirst(value string) string {
	if value == "" {
		return value
	}
	first, size := utf8.DecodeRuneInString(value)
	return string(unicode.ToLower(first)) + value[size:]
}
