func privateName(goName string) string {
	name := lowerFirst(goName)
	if token.Lookup(name).IsKeyword() {
		return name + "Value"
	}
	return name
}

func queryValueExpression(field ir.Field, value string) string {
	kind := fieldRenderKind(field.Kind).queryValue
	if kind == "" {
		return "query.Value{}"
	}
	return "query." + kind + "(" + value + ")"
}

func defaultValueExpression(value ir.Scalar) string {
	switch value.Kind {
	case ir.ScalarJSON:
		return fmt.Sprintf("_godjjson.Value{Text:%s}", strconv.Quote(value.JSON))
	case ir.ScalarUUID:
		identifier, err := uuid.Parse(value.UUID)
		if err != nil {
			return "nil"
		}
		literal := "_godjuuid.UUID{"
		for _, item := range identifier {
			literal += fmt.Sprintf("0x%02x,", item)
		}
		return literal + "}"
	case ir.ScalarDecimal:
		number, err := decimal.Parse(value.Decimal)
		if err != nil {
			return "_godjdecimal.Decimal{Coefficient:\"invalid\"}"
		}
		return fmt.Sprintf("_godjdecimal.Decimal{Coefficient:%s, Exponent:%d}", strconv.Quote(number.Coefficient), number.Exponent)
	case ir.ScalarFloat:
		return fmt.Sprintf("_godjmath.Float64frombits(0x%s)", value.FloatBits)
	case ir.ScalarDuration:
		value, err := duration.Parse(value.Duration)
		if err != nil {
			return "nil"
		}
		return fmt.Sprintf("_godjduration.Duration{Days:%d, Microseconds:%d}", value.Days, value.Microseconds)
	case ir.ScalarTime:
		time, err := clock.Parse(value.Time)
		if err != nil {
			return "nil"
		}
		return fmt.Sprintf("_godjclock.Time{Hour:%d, Minute:%d, Second:%d, Microsecond:%d}", time.Hour, time.Minute, time.Second, time.Microsecond)
	case ir.ScalarDate:
		date, err := calendar.Parse(value.Date)
		if err != nil {
			return "nil"
		}
		return fmt.Sprintf("_godjcalendar.Date{Year:%d, Month:%d, Day:%d}", date.Year, date.Month, date.Day)
	case ir.ScalarDateTime:
		instant, err := temporal.ParseCanonical(value.DateTime)
		if err != nil {
			return "nil"
		}
		return fmt.Sprintf("_godjtime.UnixMicro(int64(%d)).UTC()", instant.UnixMicro())
	case ir.ScalarString:
		return strconv.Quote(value.String)
	case ir.ScalarBoolean:
		return strconv.FormatBool(value.Boolean)
	case ir.ScalarInteger:
		return "int64(" + strconv.FormatInt(value.Integer, 10) + ")"
	default:
		return "nil"
	}
}

