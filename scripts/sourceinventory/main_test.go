func TestGeneratedClassificationUsesHeaderAndDisjointPrecedence(t *testing.T) {
	for _, test := range []struct {
		path, text, category string
		generated            bool
		lines                int
	}{
		{"codegen/render.go", "package codegen\nconst output = `// Code generated by GoDj. DO NOT EDIT.`\n", "framework_cli_generator_support", false, 2},
		{"examples/app/generated.go", "// Code generated by GoDj. DO NOT EDIT.\npackage app\n", "generated", true, 2},
		{"conformance/generated_test.go", "// Code generated by GoDj. DO NOT EDIT.\npackage app", "test", true, 2},
		{"conformance/helper.go", "package app\n// Code generated by GoDj. DO NOT EDIT.\n", "conformance_support", false, 2},
		{"examples/app/model.go", "package app\n", "examples", false, 1},
		{"scripts/test_sample.py", "# comment\n\n", "test", false, 2},
		{"scripts/sample.py", "", "support", false, 0},
	} {
		t.Run(test.path, func(t *testing.T) {
			item, err := classify(test.path, []byte(test.text))
			if err != nil || item.Category != test.category || item.Generated != test.generated || item.Lines != test.lines {
				t.Fatalf("classification = %+v, %v", item, err)
			}
		})
	}
	if _, err := classify("broken.go", []byte("package app\nfunc (")); err == nil {
		t.Fatal("invalid Go source produced a partial inventory")
	}
}

func TestInventoryReadsFrozenCommitAndCurrentUntrackedChanges(t *testing.T) {
	root := t.TempDir()
	command := func(arguments ...string) {
		t.Helper()
		if _, err := git(root, arguments...); err != nil {
			t.Fatal(err)
		}
	}
	write := func(name, text string) {
		t.Helper()
		if err := os.WriteFile(filepath.Join(root, name), []byte(text), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	command("init", "-q")
	write(".gitignore", "ignored.go\n")
	write("space name.go", "package app\n")
	command("add", ".")
	command("-c", "user.name=Inventory Test", "-c", "user.email=inventory@example.invalid", "-c", "commit.gpgsign=false", "commit", "-qm", "fixture")
	before, err := inventory(root, "HEAD")
	if err != nil {
		t.Fatal(err)
	}
	write("space name.go", "// Code generated by fixture. DO NOT EDIT.\npackage app\n")
	write("new_test.go", "package app\n")
	write("ignored.go", "invalid ignored content")
	current, err := inventory(root, "")
	if err != nil || current.Go["total"] != (count{Files: 2, Lines: 3}) ||
		current.Go["generated"].Files != 1 || current.Go["test"].Files != 1 || current.SourceDigest == before.SourceDigest {
		t.Fatalf("working inventory = %+v, %v", current, err)
	}
	again, err := inventory(root, "HEAD")
	if err != nil || !reflect.DeepEqual(before, again) {
		t.Fatalf("working edits changed a frozen inventory: %+v, %v", again, err)
	}
	if err := os.Remove(filepath.Join(root, "space name.go")); err != nil {
		t.Fatal(err)
	}
	deleted, err := inventory(root, "")
	if err != nil || deleted.Go["total"] != (count{Files: 1, Lines: 1}) {
		t.Fatalf("deleted source still counted: %+v, %v", deleted, err)
	}
	if _, err := inventory(root, "missing-ref"); err == nil {
		t.Fatal("invalid revision fell back to the working tree")
	}
}
