package dbstate_test

import (
	"context"
	"errors"
	"fmt"
	"os"
	"reflect"
	"strings"
	"testing"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/progresshans/godj/conformance/internal/dbstate"
	"github.com/progresshans/godj/conformance/internal/testfixture"
)

func TestPostgresCatalogDetectsPhysicalMutation(t *testing.T) {
	databaseURL := strings.TrimSpace(os.Getenv("GODJ_TEST_POSTGRES_URL"))
	if databaseURL == "" {
		if os.Getenv("GODJ_REQUIRE_POSTGRES") == "1" {
			t.Fatal("required PostgreSQL catalog test has no database URL")
		}
		t.Skip("GODJ_TEST_POSTGRES_URL is not configured")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	connection, err := pgx.Connect(ctx, databaseURL)
	if err != nil {
		t.Fatal(testfixture.PostgresSafeError(err))
	}
	schema := fmt.Sprintf("godj_catalog_%d_%d", os.Getpid(), time.Now().UnixNano())
	quotedSchema := pgx.Identifier{schema}.Sanitize()
	defer func() {
		cleanup, stop := context.WithTimeout(context.Background(), 10*time.Second)
		defer stop()
		if _, err := connection.Exec(cleanup, "DROP SCHEMA IF EXISTS "+quotedSchema+" CASCADE"); err != nil {
			t.Error(testfixture.PostgresSafeError(err))
		}
		if err := connection.Close(cleanup); err != nil {
			t.Error(testfixture.PostgresSafeError(err))
		}
	}()
	execute := func(statement string) {
		t.Helper()
		if _, err := connection.Exec(ctx, statement); err != nil {
			t.Fatal(testfixture.PostgresSafeError(err))
		}
	}
	execute("CREATE SCHEMA " + quotedSchema)
	table := pgx.Identifier{schema, "probe"}.Sanitize()
	execute("CREATE TABLE " + table + ` (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label VARCHAR(20) NOT NULL)`)
	capture := func() dbstate.PostgresCatalog {
		t.Helper()
		snapshot, err := dbstate.CapturePostgresCatalog(ctx, connection, schema)
		if err != nil {
			t.Fatal(testfixture.PostgresSafeError(err))
		}
		return snapshot
	}
	before := capture()
	if !reflect.DeepEqual(before.Tables, []string{"probe"}) || len(before.OtherRelations) != 0 || len(before.Columns) != 2 ||
		len(before.Constraints) != 1 || len(before.Indexes) != 1 || len(before.Sequences) != 1 || before.Triggers+before.Policies+before.Rules != 0 {
		t.Fatalf("unexpected initial physical catalog: %+v", before)
	}
	if before.Columns[0].Identity != "d" || !before.Columns[0].Primary || before.Columns[0].DataType != "bigint" ||
		before.Columns[1].DataType != "character varying(20)" || !before.Columns[1].NotNull || before.Columns[1].HasDefault {
		t.Fatalf("initial column profile: %+v", before.Columns)
	}
	if again := capture(); !reflect.DeepEqual(before, again) {
		t.Fatal("observation changed physical state")
	}
	execute("ALTER TABLE " + table + ` ALTER COLUMN label DROP NOT NULL, ALTER COLUMN label SET DEFAULT 'changed'`)
	execute(`CREATE INDEX expression_idx ON ` + table + ` ((lower(label))) WHERE id > 0`)
	execute("ALTER SEQUENCE " + pgx.Identifier{schema, before.Sequences[0].Name}.Sanitize() + " INCREMENT BY 7")
	execute("ALTER TABLE " + table + ` ADD CONSTRAINT self_fk FOREIGN KEY (id) REFERENCES ` + table + `(id) DEFERRABLE INITIALLY DEFERRED`)
	execute("CREATE POLICY all_rows ON " + table + " USING (true)")
	execute("CREATE VIEW " + pgx.Identifier{schema, "probe_view"}.Sanitize() + " AS SELECT id FROM " + table)
	after := capture()
	if after.Columns[1].NotNull || !after.Columns[1].HasDefault || after.Sequences[0].Increment != 7 ||
		after.Policies != 1 || after.Rules != 1 || after.Triggers == 0 ||
		!reflect.DeepEqual(after.OtherRelations, []dbstate.PostgresRelation{{Name: "probe_view", Kind: "v"}}) {
		t.Fatalf("catalog missed column/sequence/policy/view mutation: %+v", after)
	}
	var expressionIndex, foreignConstraint bool
	for _, index := range after.Indexes {
		if index.Name == "expression_idx" {
			expressionIndex = index.HasPredicate && index.HasExpressions && index.Valid && index.Ready
		}
	}
	for _, constraint := range after.Constraints {
		if constraint.Name == "self_fk" {
			foreignConstraint = constraint.Kind == "f" && constraint.Deferrable && constraint.Deferred && constraint.InternalTriggers > 0
		}
	}
	if !expressionIndex || !foreignConstraint {
		t.Fatal("catalog missed expression index or internal constraint triggers")
	}
	canceled, stop := context.WithCancel(context.Background())
	stop()
	if _, err := dbstate.CapturePostgresCatalog(canceled, connection, schema); !errors.Is(err, context.Canceled) {
		t.Fatalf("canceled catalog capture = %v", testfixture.PostgresSafeError(err))
	}
}
