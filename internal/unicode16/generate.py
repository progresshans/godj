#!/usr/bin/env python3
"""Generate the pinned text profile from hash-verified Unicode data, not Python's tables."""
import argparse
import functools
import gzip
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile
import urllib.request

ROOT = Path(__file__).resolve().parent


def ranges(values):
    result = []
    for value in sorted(values):
        if result and value == result[-1][1] + 1:
            result[-1][1] = value
        else:
            result.append([value, value])
    return result


def property_values(text, wanted):
    result = {name: set() for name in wanted}
    for line in text.splitlines():
        fields = [part.strip() for part in line.split("#")[0].split(";")]
        if len(fields) < 2 or fields[1] not in result:
            continue
        ends = fields[0].split("..")
        result[fields[1]].update(range(int(ends[0], 16), int(ends[-1], 16) + 1))
    return result


def go_string(values):
    # Always escape code points: source layout must not depend on bidi/control
    # or line-separator behavior in a terminal, editor or Go formatter.
    return '"' + "".join(f"\\u{v:04x}" if v <= 0xffff else f"\\U{v:08x}" for v in values) + '"'


def generate(files):
    characters = {}
    first = None
    for line in files["UnicodeData.txt"].splitlines():
        fields = line.split(";")
        assert len(fields) == 15
        codepoint = int(fields[0], 16)
        if fields[1].endswith(", First>"):
            assert first is None
            first = (codepoint, fields)
        elif fields[1].endswith(", Last>"):
            assert first is not None and first[1][2:] == fields[2:]
            for value in range(first[0], codepoint + 1):
                characters[value] = fields
            first = None
        else:
            assert first is None and codepoint not in characters
            characters[codepoint] = fields
    assert first is None
    decomposition, canonical, lower, classes = {}, {}, {}, {}
    alpha_number, digit, space = set(), set(), set()
    for value, fields in characters.items():
        if fields[2][0] in "LN":
            alpha_number.add(value)
        if fields[7]:
            digit.add(value)
        if fields[2] == "Zs" or fields[4] in {"WS", "B", "S"}:
            space.add(value)
        if int(fields[3]):
            classes[value] = int(fields[3])
        parts = fields[5].split()
        if parts:
            if parts[0].startswith("<"):
                parts = parts[1:]
            else:
                canonical[value] = tuple(int(p, 16) for p in parts)
            decomposition[value] = tuple(int(p, 16) for p in parts)
        if fields[13]:
            lower[value] = (int(fields[13], 16),)
    conditions = set()
    for line in files["SpecialCasing.txt"].splitlines():
        parts = [v.strip() for v in line.split("#")[0].split(";")]
        if len(parts) < 5:
            continue
        value = int(parts[0], 16)
        if parts[4]:
            conditions.add(parts[4])
        else:
            lower[value] = tuple(int(p, 16) for p in parts[1].split())
    assert conditions == {"Final_Sigma", "lt After_Soft_Dotted", "lt More_Above", "lt", "tr", "az", "tr After_I", "az After_I", "tr Not_Before_Dot", "az Not_Before_Dot"}
    lower = {key: value for key, value in lower.items() if value != (key,)}
    excluded = property_values(files["DerivedNormalizationProps.txt"], {"Full_Composition_Exclusion"})["Full_Composition_Exclusion"]
    compositions = {}
    for value, parts in canonical.items():
        if len(parts) == 2 and value not in excluded:
            key = parts[0] << 21 | parts[1]
            assert key not in compositions and classes.get(parts[0], 0) == 0
            compositions[key] = value
    properties = property_values(files["DerivedCoreProperties.txt"], {"Cased", "Case_Ignorable"})

    @functools.cache
    def expand(value):
        if 0xac00 <= value <= 0xd7a3:
            index = value - 0xac00
            result = (0x1100 + index // 588, 0x1161 + index % 588 // 28)
            return result + ((0x11a7 + index % 28,) if index % 28 else ())
        return tuple(child for part in decomposition.get(value, (value,)) for child in (expand(part) if value in decomposition else (part,)))

    output = ["// Code generated by generate.py from Unicode 16.0.0; DO NOT EDIT.",
              "// Unicode data copyright and permission: LICENSE.unicode; source hashes: sources.json.",
              "package unicode16", "const Version = \"16.0.0\"", "var decomposition = map[rune]string{"]
    for value in sorted(decomposition):
        output.append(f"0x{value:x}: {go_string(expand(value))},")
    output.append("}\nvar composition = map[uint64]rune{")
    output.extend(f"0x{key:x}: 0x{value:x}," for key, value in sorted(compositions.items()))
    output.append("}\nvar lowercase = map[rune]string{")
    output.extend(f"0x{key:x}: {go_string(value)}," for key, value in sorted(lower.items()))
    output.append("}\nvar combiningClass = map[rune]uint8{")
    output.extend(f"0x{key:x}: {value}," for key, value in sorted(classes.items()))
    output.append("}")
    for name, values in [("alphanumeric", alpha_number), ("digits", digit), ("spaces", space), ("cased", properties["Cased"]), ("caseIgnorable", properties["Case_Ignorable"])]:
        output.append(f"var {name} = [...]codeRange{{")
        output.extend(f"{{0x{low:x}, 0x{high:x}}}," for low, high in ranges(values))
        output.append("}")
    return subprocess.run(["gofmt"], input="\n".join(output) + "\n", text=True, capture_output=True, check=True).stdout.encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=ROOT / "testdata/ucd")
    parser.add_argument("--fetch", action="store_true", help="explicitly download the pinned inputs into the cache")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    manifest = json.loads((ROOT / "sources.json").read_text())
    assert manifest["version"] == "16.0.0"
    files = {}
    for name, record in manifest["files"].items():
        path = args.data_dir / name
        if args.fetch:
            with urllib.request.urlopen(record["url"], timeout=60) as stream:
                data = stream.read(record["size"] + 1)
        elif path.exists():
            with path.open("rb") as stream:
                data = stream.read(record["size"] + 1)
        else:
            with gzip.open(str(path) + ".gz", "rb") as stream:
                data = stream.read(record["size"] + 1)
        if len(data) != record["size"] or hashlib.sha256(data).hexdigest() != record["sha256"]:
            raise ValueError("Unicode source hash mismatch: " + name)
        if args.fetch:
            args.data_dir.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        files[name] = data.decode("utf-8")
    result = generate(files)
    target = ROOT / "tables_generated.go"
    if args.check:
        if target.read_bytes() != result:
            raise ValueError("Unicode generated table drift")
    else:
        descriptor, name = tempfile.mkstemp(prefix=".tables-", suffix=".go", dir=ROOT)
        try:
            with os.fdopen(descriptor, "wb") as stream:
                stream.write(result)
            os.chmod(name, 0o644)
            os.replace(name, target)
        finally:
            Path(name).unlink(missing_ok=True)


if __name__ == "__main__":
    main()
