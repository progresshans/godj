// Tables uses only a test-owned, quoted schema prefix (or the empty SQLite
// prefix). Product queries below use the regular typed and dynamic APIs.
func Tables(prefix string) []string {
	key := "INTEGER PRIMARY KEY"
	if prefix != "" {
		key = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
	}
	return []string{
		`CREATE TABLE ` + prefix + `authors_author(id ` + key + `, name VARCHAR(200) NOT NULL)`,
		`CREATE TABLE ` + prefix + `blog_post(id ` + key + `, title VARCHAR(200) NOT NULL, author_id BIGINT NOT NULL REFERENCES ` + prefix + `authors_author(id), reviewer_id BIGINT NULL REFERENCES ` + prefix + `authors_author(id))`,
		`CREATE TABLE ` + prefix + `godj_conformance_article(id ` + key + `, title VARCHAR(200) NOT NULL, published BOOLEAN NOT NULL, summary VARCHAR(200) NULL, slug VARCHAR(50) NULL UNIQUE)`,
	}
}

func seed(t *testing.T, backend db.Mutator, input inputs) {
	t.Helper()
	id := query.NewFieldRef("id", "id", query.FieldInteger, false)
	title := query.NewFieldRef("title", "title", query.FieldString, false)
	insert := func(table string, key int64, assignments ...query.Assignment) {
		t.Helper()
		got, err := backend.Insert(t.Context(), query.NewInsertPlanReturningKey(table, assignments, id))
		if err != nil || got != key {
			t.Fatal("seed failed", table, key, got, err)
		}
	}
	for _, row := range input.Rows {
		summary := query.Null()
		if row.Summary != nil {
			summary = query.String(*row.Summary)
		}
		insert("authors_author", row.ID, query.NewAssignment(query.NewFieldRef("name", "name", query.FieldString, false), query.String(row.Title)))
		insert("godj_conformance_article", row.ID, query.NewAssignment(title, query.String(row.Title)), query.NewAssignment(query.NewFieldRef("published", "published", query.FieldBoolean, false), query.Boolean(row.Published)), query.NewAssignment(query.NewFieldRef("summary", "summary", query.FieldString, true), summary))
	}
	for _, row := range input.Posts {
		reviewer := query.Null()
		if row.Reviewer != nil {
			reviewer = query.Integer(*row.Reviewer)
		}
		insert("blog_post", row.ID, query.NewAssignment(title, query.String(row.Title)), query.NewAssignment(query.NewFieldRef("author_id", "author_id", query.FieldInteger, false), query.Integer(row.Author)), query.NewAssignment(query.NewFieldRef("reviewer_id", "reviewer_id", query.FieldInteger, true), reviewer))
	}
}

func RunQueries(t *testing.T, backend db.Session, dialect string) {
	t.Helper()
	input, want := load(t, dialect)
	seed(t, backend, input)
	articles, err := models.ArticleObjects.Using(backend).All(t.Context())
	if err != nil || len(articles) != len(input.Rows) {
		t.Fatal("seeded Article projection differs", len(articles), len(input.Rows), err)
	}
	for _, article := range articles {
		if article.Slug != nil {
			t.Fatal("omitted slug must decode as SQL NULL", article.ID, article.Slug)
		}
	}
	relations, err := project.BindRelations()
	if err != nil {
		t.Fatal(err)
	}
	for i, c := range input.Queries {
		t.Run(c.Name, func(t *testing.T) {
			lookup := []orm.LookupInput{{Key: c.Field + "__iexact", Value: c.Value}}
			switch c.Model {
			case "article":
				var typed orm.Predicate[models.Article]
				switch c.Field {
				case "title":
					typed = models.ArticleFields.Title.IExact(c.Value)
				case "summary":
					typed = models.ArticleFields.Summary.IExact(c.Value)
				default:
					t.Fatal("unknown article input", c.Field)
				}
				dynamic, err := orm.ParseDynamic(models.ArticleDescriptor{}, nil, lookup)
				if err != nil {
					t.Fatal(err)
				}
				compare(t, c, want.Queries[i], models.ArticleObjects.Using(backend), typed, dynamic, models.ArticleFields.ID, func(v models.Article) int64 { return v.ID })
			case "post":
				var typed orm.Predicate[blog.Post]
				switch c.Field {
				case "title":
					typed = blog.PostFields.Title.IExact(c.Value)
				case "author__name":
					typed = relations.BlogPost.Author.Name.IExact(c.Value)
				case "reviewer__name":
					typed = relations.BlogPost.Reviewer.Name.IExact(c.Value)
				default:
					t.Fatal("unknown post input", c.Field)
				}
				var dynamic []orm.Predicate[blog.Post]
				var err error
				if c.Field == "title" {
					dynamic, err = orm.ParseDynamic(blog.PostDescriptor{}, nil, lookup)
				} else {
					dynamic, err = relations.BlogPost.ParseDynamic(nil, lookup)
				}
				if err != nil {
					t.Fatal(err)
				}
				compare(t, c, want.Queries[i], blog.PostObjects.Using(backend), typed, dynamic, blog.PostFields.ID, func(v blog.Post) int64 { return v.ID })
			case "author":
				var typed orm.Predicate[authors.Author]
				switch c.Field {
				case "posts__title":
					typed = relations.AuthorsAuthor.Posts.Title.IExact(c.Value)
				case "posts__reviewer__name":
					typed = relations.AuthorsAuthor.Posts.Reviewer().Name.IExact(c.Value)
				case "reviewed_posts__title":
					typed = relations.AuthorsAuthor.ReviewedPosts.Title.IExact(c.Value)
				case "reviewed_posts__author__name":
					typed = relations.AuthorsAuthor.ReviewedPosts.Author().Name.IExact(c.Value)
				default:
					t.Fatal("unknown author input", c.Field)
				}
				dynamic, err := relations.AuthorsAuthor.ParseDynamic(nil, lookup)
				if err != nil {
					t.Fatal(err)
				}
				compare(t, c, want.Queries[i], authors.AuthorObjects.Using(backend), typed, dynamic, authors.AuthorFields.ID, func(v authors.Author) int64 { return v.ID })
			default:
				t.Fatal("unknown reference model", c.Model)
			}
		})
	}
}

func compare[M any](t *testing.T, c queryCase, want observation, base orm.QuerySet[M], typed orm.Predicate[M], dynamic []orm.Predicate[M], id orm.AutoField[M], key func(M) int64) {
	t.Helper()
	if len(dynamic) != 1 {
		t.Fatal("dynamic predicate missing")
	}
	modify := func(p orm.Predicate[M]) orm.Predicate[M] {
		switch c.Mode {
		case "filter":
			return p
		case "exclude":
			return orm.Not(p)
		case "or_id1":
			return orm.Or(p, id.Exact(1))
		case "not_or_id1":
			return orm.Not(orm.Or(p, id.Exact(1)))
		case "double_not":
			return orm.Not(orm.Not(p))
		default:
			t.Fatal("unknown reference mode", c.Mode)
			return p
		}
	}
	left, right := base.Filter(modify(typed)).OrderBy(id.Asc()), base.Filter(modify(dynamic[0])).OrderBy(id.Asc())
	if !left.Plan().Equal(right.Plan()) {
		t.Fatal("typed/dynamic query AST diverged")
	}
	for _, qs := range []orm.QuerySet[M]{left, right} {
		// Count/Exists execute before All, so cached materialization cannot
		// hide their native SQL or reverse-join multiplicity.
		count, err := qs.Count(t.Context())
		if err != nil || count != want.Count {
			t.Fatal("Count differs from Django", count, want.Count, err)
		}
		exists, err := qs.Exists(t.Context())
		if err != nil || exists != want.Exists {
			t.Fatal("Exists differs from Django", exists, want.Exists, err)
		}
		rows, err := qs.All(t.Context())
		if err != nil {
			t.Fatal(err)
		}
		ids := make([]int64, len(rows))
		for i, row := range rows {
			ids[i] = key(row)
		}
		if !reflect.DeepEqual(ids, want.IDs) {
			t.Fatal("rows differ from Django", ids, want.IDs)
		}
	}
}
